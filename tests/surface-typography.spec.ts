import { expect, test } from '@playwright/test'

test('composes card variants and elevations around a form with a stable loading action', async ({ page }) => {
  await page.goto('/?component=W.card')
  const variants = page.getByRole('region', { name: '卡片色调' })
  await expect(variants.locator('.sy-card')).toHaveCount(6)
  const flat = page.getByRole('region', { name: '卡片层级' }).locator('[data-elevation="none"]')
  const raised = page.getByRole('region', { name: '卡片层级' }).locator('[data-elevation="high"]')
  await expect(flat).toHaveCSS('box-shadow', 'none')
  await expect(raised).not.toHaveCSS('box-shadow', 'none')
  await expect(page.getByRole('note')).toContainText('字体许可证')

  const form = page.getByRole('form', { name: '编辑公开资料' })
  const field = form.getByRole('textbox', { name: '显示名称' })
  const save = form.getByRole('button', { name: '保存资料' })
  await field.fill('团队档案')
  const width = (await save.boundingBox())!.width
  await save.click()
  await expect(save).toHaveAttribute('aria-busy', 'true')
  expect((await save.boundingBox())!.width).toBe(width)
  await expect(form.getByRole('status').locator('.sy-visually-hidden')).toHaveText('已保存 团队档案')
  await field.fill('一次误改')
  await form.getByRole('button', { name: '取消修改' }).click()
  await expect(field).toHaveValue('团队档案')
  await page.setViewportSize({ width: 320, height: 720 })
  await expect.poll(() => form.evaluate(node => node.getBoundingClientRect().right <= node.ownerDocument.documentElement.clientWidth)).toBe(true)
})

test('preserves card link semantics, composes a selected ring with depth, and submits independent options', async ({ page }) => {
  await page.goto('/?component=W.clickable-card')
  const report = page.getByRole('link', { name: '打开交付报告' })
  await expect(report).toHaveAttribute('href', '#review-delivery-report')
  await report.press('Enter')
  await expect(page).toHaveURL(/#review-delivery-report$/)
  const disabled = page.getByRole('link', { name: '打开成员权限' })
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
  await expect(disabled).not.toHaveAttribute('href')

  await page.goto('/?component=W.selectable-card')
  const plans = page.getByRole('group', { name: '选择订阅方案' })
  const studio = plans.getByRole('checkbox', { name: '协作版' })
  const studioCard = plans.locator('[data-elevation="low"]')
  await expect(studio).toBeChecked()
  await studio.press('Space')
  await expect(studio).toBeChecked()
  const shadow = await studioCard.evaluate(node => getComputedStyle(node).boxShadow)
  expect(shadow).not.toBe('none')
  const personal = plans.getByRole('checkbox', { name: '个人版' })
  await personal.press('Enter')
  await expect(personal).toBeChecked()
  await expect(studio).not.toBeChecked()
  await expect(studioCard).toHaveCSS('box-shadow', shadow)
  const form = page.getByRole('form', { name: '配置附加功能' })
  await form.getByRole('checkbox', { name: '自动备份' }).press('Space')
  await form.getByRole('button', { name: '保存附加功能' }).click()
  await expect(form.locator('output .sy-visually-hidden')).toHaveText('版本记录、团队审阅、自动备份')
  await form.getByRole('button', { name: '恢复默认功能' }).click()
  await expect(form.getByRole('checkbox', { name: '版本记录' })).toBeChecked()
  await expect(form.getByRole('checkbox', { name: '自动备份' })).not.toBeChecked()
})

test('announces distinct banner actions and transitions dismissal without removing neighboring notices', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 820 })
  await page.goto('/?component=W.banner')
  const statuses = page.getByRole('region', { name: '通知状态' })
  for (const tone of ['info', 'success', 'warning', 'danger']) {
    await expect(statuses.locator(`[data-tone="${tone}"]`)).toBeVisible()
  }
  const floating = page.locator('.sy-banner[data-elevation="med"]')
  await expect(floating).not.toHaveCSS('box-shadow', 'none')
  const expand = page.getByRole('button', { name: '收起同步详情' })
  const details = page.locator('.sy-banner__details').filter({ hasText: '默认同步范围为当前团队' })
  await expect(expand).toHaveAttribute('aria-expanded', 'true')
  await expand.click()
  await expect(details).toHaveAttribute('inert', '')
  await page.getByRole('button', { name: '展开同步详情' }).press('Enter')
  await expect(details).not.toHaveAttribute('inert')
  await statuses.getByRole('button', { name: '重新验证' }).press('Enter')
  const dialog = page.getByRole('dialog', { name: '重新验证' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '确认设置' }).click()
  await expect(page.getByRole('status').locator('.sy-visually-hidden')).toHaveText('已确认重新验证')
  const archived = statuses.locator('[data-tone="success"]')
  await archived.evaluate(node => {
    node.addEventListener('transitionstart', event => {
      if ((event as TransitionEvent).propertyName === 'grid-template-rows') {
        node.ownerDocument.documentElement.dataset.bannerExit = getComputedStyle(node).transitionTimingFunction
      }
    })
  })
  await archived.getByRole('button', { name: '关闭本周记录已同步' }).click()
  await expect(archived).toHaveCount(0)
  await expect(page.locator('html')).toHaveAttribute('data-banner-exit', /cubic-bezier/)
  await expect(statuses.locator('.sy-banner')).toHaveCount(3)
})

test('matches text semantics and keeps full-text tooltips synchronized with content and width', async ({ page }) => {
  await page.goto('/?component=W.text')
  const levels = page.getByRole('region', { name: '六种标题规格' })
  for (const level of [1, 2, 3, 4, 5, 6] as const) {
    await expect(levels.getByRole('heading', { level })).toHaveCount(1)
  }
  const wrapping = page.getByRole('region', { name: '换行与断词' })
  await expect(wrapping.locator('[data-wrap="balance"]')).toHaveCSS('text-wrap', /balance/)
  await expect(wrapping.locator('[data-wrap="nowrap"]')).toHaveCSS('white-space', 'nowrap')
  await expect(wrapping.locator('[data-word-break="break-all"]')).toHaveCSS('word-break', 'break-all')

  const summary = page.getByRole('region', { name: '多行截断' })
  await summary.getByRole('combobox', { name: '摘要行数' }).click()
  await page.getByRole('option', { name: '两行' }).click()
  await expect(summary.locator('.sy-line-clamp')).toHaveCSS('-webkit-line-clamp', '2')
  await summary.getByRole('combobox', { name: '摘要行数' }).click()
  await page.getByRole('option', { name: '三行' }).click()
  await expect(summary.locator('.sy-line-clamp')).toHaveCSS('-webkit-line-clamp', '3')

  const paths = page.getByRole('region', { name: '路径列截断' })
  const build = paths.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '构建', exact: true }) }).locator('.sy-line-clamp')
  await expect(build).toHaveAttribute('tabindex', '0')
  await build.focus()
  const tooltip = page.getByRole('tooltip')
  await expect(tooltip).toContainText('release/2026.11/preview/index.html')
  await paths.getByRole('switch', { name: '切换发布版本' }).evaluate(node => (node as HTMLElement).click())
  await expect(tooltip).toContainText('release/rebuilt/2026.12/preview/index.html')
  await paths.getByRole('switch', { name: '缩窄路径列' }).click()
  await expect(build).not.toHaveAttribute('tabindex')
  await expect(tooltip).toHaveCount(0)
  await expect(paths.getByText('README.md')).not.toHaveAttribute('tabindex')
})
