test('formats rich text, edits links, undoes a mark and reads the submitted JSON in a static view', async ({ page }) => {
  await page.goto('/?component=WP.rich-text-editor')
  const body = page.getByRole('textbox', { name: '编辑交付说明' })
  const toolbar = page.getByRole('toolbar', { name: '文本格式' })
  await expect(body.getByRole('heading', { name: '品牌资源交付说明' })).toBeVisible()
  await body.press('ControlOrMeta+A')
  await page.keyboard.insertText('发布说明')
  await body.press('ControlOrMeta+A')
  await toolbar.getByRole('button', { name: '斜体', exact: true }).click()
  await expect(body.locator('em')).toHaveText('发布说明')
  await toolbar.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(body.locator('em')).toHaveCount(0)
  await toolbar.getByRole('button', { name: '重做', exact: true }).click()
  await expect(body.locator('em')).toHaveText('发布说明')

  await body.press('ControlOrMeta+A')
  await toolbar.getByRole('button', { name: '链接', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const url = dialog.getByRole('textbox', { name: '链接地址' })
  await url.fill('file:///tmp/review.pdf')
  await url.press('Enter')
  await expect(url).toHaveAttribute('aria-invalid', 'true')
  await url.fill('https://example.com/review')
  await url.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(body.getByRole('link', { name: '发布说明' })).toHaveAttribute('href', 'https://example.com/review')

  await page.getByRole('button', { name: '保存内容', exact: true }).click()
  const saved = page.getByRole('region', { name: '已保存内容' })
  await expect(saved.locator('[contenteditable]')).toHaveCount(0)
  await expect(saved.getByRole('link', { name: '发布说明' })).toHaveAttribute('href', 'https://example.com/review')
  await page.getByRole('button', { name: '恢复草稿' }).click()
  await expect(body.getByRole('heading', { name: '品牌资源交付说明' })).toBeVisible()
})

test('keeps permitted paste formatting, rejects unavailable link schemes and enforces the character limit', async ({ page }) => {
  await page.goto('/?component=WP.rich-text-editor')
  const body = page.getByRole('textbox', { name: '编辑交付说明' })
  await body.press('ControlOrMeta+A')
  await body.evaluate(node => {
    const clipboard = new DataTransfer()
    clipboard.setData('text/html', '<p><em>保留斜体</em> <a href="file:///tmp/review.pdf">本地文件</a></p>')
    const paste = new Event('paste', { bubbles: true, cancelable: true })
    Object.defineProperty(paste, 'clipboardData', { value: clipboard })
    node.dispatchEvent(paste)
  })
  await expect(body.locator('em')).toHaveText('保留斜体')
  await expect(body.getByRole('link')).toHaveCount(0)
  await body.press('End')
  await page.keyboard.insertText('字'.repeat(251))
  await expect(body).toHaveText('保留斜体 本地文件')
})

