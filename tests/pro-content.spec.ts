test('highlights code, copies its exact text and keeps long lines within the scrolling panel', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText: async (text: string) => { document.body.dataset.copied = text } },
    })
  })
  await page.setViewportSize({ width: 320, height: 720 })
  await page.goto('/?component=WP.code-block')
  const region = page.getByRole('region', { name: '代码内容' }).first()
  const code = region.locator('pre code')
  const copy = page.getByRole('button', { name: '复制代码' })
  await expect(code.locator('.hljs-keyword').first()).toHaveText('export')
  expect(await region.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  const width = (await copy.boundingBox())!.width
  await copy.click()
  await expect(page.getByRole('button', { name: '已复制' })).toBeFocused()
  expect((await copy.or(page.getByRole('button', { name: '已复制' })).boundingBox())!.width).toBe(width)
  expect(await page.locator('body').getAttribute('data-copied')).toBe(await code.textContent())
})
