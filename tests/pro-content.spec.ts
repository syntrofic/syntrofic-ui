test('a second branded header edit continues from the displayed sizes', async ({ page }) => {
  await page.goto('/?component=WP.code-block')
  const group = page.getByRole('group', { name: '头部尺寸规则' })
  const header = group.locator('.sy-layout-header')
  await expect(header).toHaveCSS('height', '68px')
  const sizes = await group.evaluate(async node => {
    const host = node.querySelector('.sy-layout-header')!
    const row = host.querySelector('.sy-navbar__bar')!
    const edit = (label: string) => [...node.querySelectorAll('button')].find(button => button.textContent?.trim() === label)!.click()
    const motion = (element: Element) => element.getAnimations().find(animation =>
      (animation.effect as KeyframeEffect | null)?.getKeyframes().some(frame => 'blockSize' in frame))
    edit('高度冲突')
    await Promise.resolve()
    for (const effect of [motion(host)!, motion(row)!]) effect.currentTime = Number(effect.effect!.getTiming().duration) / 4
    const shown = [host, row].map(element => parseFloat(getComputedStyle(element).blockSize))
    edit('内边距冲突')
    await Promise.resolve()
    const resumed = [host, row].map(element => parseFloat(String((motion(element)?.effect as KeyframeEffect)?.getKeyframes()[0]?.blockSize)))
    return { shown, resumed }
  })
  expect(sizes.shown[0]).toBeGreaterThan(68)
  expect(sizes.shown[0]).toBeLessThan(76)
  expect(sizes.shown[1]).toBeGreaterThan(48)
  expect(sizes.shown[1]).toBeLessThan(60)
  for (const [index, actual] of sizes.resumed.entries()) expect(actual).toBeCloseTo(sizes.shown[index]!, 1)
  await expect(header).toHaveCSS('height', '68px')
  await expect(header.locator('.sy-navbar__bar')).toHaveCSS('height', '48px')
})

