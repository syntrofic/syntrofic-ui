import { expect, test } from '@playwright/test'

test('list focus pages, repairs the tab stop and scopes typeahead and the text caret', async ({ page }) => {
  await page.goto('/?component=W.list-box')
  const sample = page.getByRole('region', { name: '线性焦点工具示例' })
  const toolbar = sample.getByRole('toolbar', { name: '目录键盘导航' })
  const first = toolbar.getByRole('button', { name: 'Örebro' })
  const oslo = toolbar.getByRole('button', { name: 'Oslo' })
  const odense = toolbar.getByRole('button', { name: 'Odense' })
  const note = toolbar.getByRole('textbox', { name: '输入备注' })
  await expect(first).toHaveAttribute('tabindex', '0')
  await first.focus()
  await first.press('ArrowUp')
  await expect(note).toBeFocused()
  await note.press('Home')
  await expect(first).toBeFocused()
  await first.press('End')
  await expect(note).toBeFocused()
  await first.focus()
  await page.keyboard.press('o')
  await expect(oslo).toBeFocused()
  await page.keyboard.press('o')
  await expect(odense).toBeFocused()
  await page.keyboard.press('o')
  await expect(first).toBeFocused()
  await page.keyboard.press('PageDown')
  await expect(odense).toBeFocused()
  await note.fill('资料')
  await note.evaluate(input => (input as HTMLInputElement).setSelectionRange(1, 1))
  await page.keyboard.press('ArrowLeft')
  await expect(note).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(toolbar.getByRole('button', { name: 'Trondheim' })).toBeFocused()
  await oslo.focus()
  await sample.getByRole('checkbox', { name: '禁用 Oslo' }).check()
  await expect(oslo).toHaveAttribute('tabindex', '-1')
  await expect(odense).toHaveAttribute('tabindex', '0')
  const nested = toolbar.getByRole('button', { name: '独立动作' })
  await nested.press('Escape')
  await expect(nested).toBeFocused()
  await expect(sample).toContainText('循环按方向键浏览项目。')
  await odense.press('Escape')
  await expect(sample).toContainText('已结束列表导航。')
})

test('grid focus preserves disabled geometry, passes boundary coordinates and mirrors arrows', async ({ page }) => {
  await page.goto('/?component=WP.data-grid')
  const sample = page.getByRole('region', { name: '网格焦点工具示例' })
  const grid = sample.getByRole('grid', { name: '排期导航网格' })
  const monday = grid.getByRole('button', { name: '周一', exact: true })
  const wednesday = grid.getByRole('button', { name: '周三' })
  const saturday = grid.getByRole('button', { name: '周六' })
  await expect(monday).toHaveAttribute('tabindex', '0')
  await monday.press('ArrowRight')
  await expect(wednesday).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(saturday).toBeFocused()
  await page.keyboard.press('Home')
  await expect(grid.getByRole('button', { name: '周四' })).toBeFocused()
  await page.keyboard.press('Control+End')
  await expect(grid.getByRole('button', { name: '下周二' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(sample).toContainText('结束边界 · 第 3 列 · 步长 3')
  await page.keyboard.press('Shift+PageDown')
  await expect(sample).toContainText('下一组排期')
  await sample.getByRole('checkbox', { name: '反向排列排期' }).check()
  await wednesday.press('ArrowRight')
  await expect(monday).toBeFocused()
  await expect(grid.locator('[tabindex="0"]')).toHaveCount(1)
})

test('tree focus expands parents, skips disabled children and matches international labels', async ({ page }) => {
  await page.goto('/?component=WP.file-tree')
  const sample = page.getByRole('region', { name: '树形焦点工具示例' })
  const tree = sample.getByRole('tree', { name: '项目附件树' })
  const folder = tree.getByRole('treeitem', { name: '项目资料' })
  const overview = tree.getByRole('treeitem', { name: 'Översikt' })
  const notes = tree.getByRole('treeitem', { name: 'Łódź' })
  await expect(folder).toHaveAttribute('tabindex', '0')
  await folder.press('ArrowRight')
  await expect(folder).toHaveAttribute('aria-expanded', 'true')
  await folder.press('ArrowRight')
  await expect(overview).toBeFocused()
  await overview.press('Enter')
  await expect(sample).toContainText('已打开 Översikt')
  await overview.press('ArrowLeft')
  await expect(folder).toBeFocused()
  await page.keyboard.press('l')
  await expect(notes).toBeFocused()
  await page.keyboard.press('Home')
  await folder.press('ArrowLeft')
  await expect(overview).toHaveCount(0)
  await expect(folder).toHaveAttribute('tabindex', '0')
  await expect(tree.locator('[tabindex="0"]')).toHaveCount(1)
})

test('keyboard hints use the top layer and dismiss once without consuming arrow navigation', async ({ page }) => {
  await page.goto('/?component=W.tabs')
  const selected = page.getByRole('tab', { name: '概况' })
  const neighbor = page.getByRole('tab', { name: '文件' })
  const hint = page.locator('.sy-layer:popover-open:has(.sy-keyboard-hint)')
  await selected.focus()
  await expect(hint).toBeVisible()
  await expect(hint).toHaveAttribute('aria-hidden', 'true')
  expect(await hint.evaluate(node => node.matches(':popover-open'))).toBe(true)
  await page.keyboard.press('ArrowRight')
  await expect(neighbor).toBeFocused()
  await expect(hint).toBeHidden()
  await neighbor.evaluate(element => (element as HTMLElement).blur())
  await selected.focus()
  await expect(hint).toBeHidden()

  await page.reload()
  await selected.focus()
  await expect(hint).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(selected).toBeFocused()
  await expect(hint).toBeHidden()
})

test('hover affordances wait for intent, respect nested boundaries and remain keyboard accessible', async ({ page }) => {
  await page.goto('/?component=W.thumbnail')
  const sample = page.getByRole('region', { name: '延迟显示操作示例' })
  const outer = sample.getByRole('button', { name: '管理工作区图片' })
  const child = sample.getByRole('button', { name: '管理单张图片' })
  await expect(outer).toHaveCSS('opacity', '0')
  await sample.getByText('工作区图片', { exact: true }).hover()
  await expect(outer).toHaveCSS('opacity', '1')
  await sample.getByText('单张图片', { exact: true }).hover()
  await expect(outer).toHaveCSS('opacity', '0')
  await expect(child).toHaveCSS('opacity', '1')
  await outer.focus()
  await expect(outer).toHaveCSS('opacity', '1')
  await sample.getByRole('checkbox', { name: '锁定外层操作' }).check()
  await expect(outer).toHaveCSS('opacity', '1')
  await sample.getByRole('checkbox', { name: '悬停显示操作' }).uncheck()
  await expect(child).toHaveCSS('opacity', '1')
  await expect(child).not.toHaveAttribute('data-sy-reveal-item')
})

test('a hidden input paints its keyboard focus on the supplied indicator', async ({ page }) => {
  await page.goto('/?component=W.indicator')
  const sample = page.getByRole('region', { name: '自定义指示图形焦点' })
  const input = sample.getByRole('checkbox', { name: '附件已审核' })
  const indicator = sample.locator('.reveal-review__marker')
  await input.focus()
  await expect(indicator).toHaveAttribute('data-sy-indicator-focus', '')
  await expect(indicator).toHaveCSS('outline-style', 'solid')
  await sample.getByRole('checkbox', { name: '禁用自定义指示器' }).check()
  await expect(input).toBeDisabled()
  await expect(indicator).not.toHaveAttribute('data-sy-indicator-focus')
})

test('polymorphic controls resolve links, idle content and the current trigger', async ({ page }) => {
  await page.goto('/?component=W.clickable-card')
  const sample = page.getByRole('region', { name: '交互角色示例' })
  await expect(sample.getByRole('link', { name: '跳至角色说明' })).toHaveAttribute('data-resolved-role', 'link')
  await expect(sample.getByText('普通说明')).toHaveAttribute('data-resolved-role', 'inert')
  const action = sample.getByRole('button', { name: '确认角色操作' })
  await expect(action).toHaveAttribute('data-resolved-role', 'button')
  await action.press('Enter')
  await expect(page.getByText('已确认角色操作')).toBeVisible()
  const trigger = sample.getByRole('button', { name: '打开角色说明' })
  await expect(trigger).toHaveAttribute('data-resolved-role', 'button')
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog', { name: '角色面板' })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})
