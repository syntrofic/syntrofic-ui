import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect(await page.pageErrors()).toEqual([])
})

test('application layout keeps desktop preferences while the mobile drawers come and go', async ({ page }) => {
  await page.setViewportSize({ width: 1160, height: 760 })
  await page.goto('/?component=WP.app-layout')
  const example = page.getByRole('region', { name: '组件示例' })
  const navigation = example.getByRole('button', { name: '导航', exact: true })
  const details = example.getByRole('button', { name: '详情', exact: true })
  const sidebar = example.getByRole('navigation', { name: '工作区链接' })
  const main = example.getByRole('main', { name: '工作区内容' })
  await expect(example.locator('.sy-app-layout__pane--aside')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(sidebar.getByRole('link', { name: '概览', exact: true })).toHaveAttribute('aria-current', 'page')
  const handle = example.getByRole('separator', { name: '调整侧栏宽度' })
  await expect(handle).toHaveAttribute('aria-valuenow', '145')
  const previous = (await handle.boundingBox())!
  await handle.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', '153')
  await expect.poll(async () => (await handle.boundingBox())!.x).toBeCloseTo(previous.x + 8, 0)
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + 22)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 30, box.y + 22, { steps: 5 })
  await page.mouse.up()
  await expect(handle).toHaveAttribute('aria-valuenow', '183')

  await navigation.click()
  await expect(navigation).toHaveAttribute('aria-expanded', 'false')
  await expect(sidebar.getByRole('link', { name: '概览', exact: true })).toBeVisible()
  await expect(sidebar).toHaveAttribute('data-rail', 'true')
  await expect(handle).toHaveCount(0)
  await details.click()
  await expect(details).toHaveAttribute('aria-expanded', 'false')

  await page.setViewportSize({ width: 390, height: 740 })
  await expect(example.locator('.sy-app-layout')).toHaveClass(/sy-app-layout--compact/)
  await navigation.press('Enter')
  const drawer = page.getByRole('dialog', { name: '工作区导航' })
  await expect(drawer.getByRole('link', { name: '项目', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(navigation).toBeFocused()
  await details.click()
  const detailDrawer = page.getByRole('dialog', { name: '项目详情' })
  await expect(detailDrawer.getByText('品牌资源库')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(detailDrawer).toBeHidden()

  await navigation.click()
  await drawer.getByRole('link', { name: '项目', exact: true }).click()
  await expect(drawer).toBeHidden()
  await expect(main.getByRole('heading', { name: '项目' })).toBeVisible()
  await expect(page).toHaveURL(/component=WP.app-layout/)
  await page.setViewportSize({ width: 1160, height: 760 })
  await expect(sidebar.getByRole('link', { name: '项目', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(sidebar).toHaveAttribute('data-rail', 'true')
  await expect(details).toHaveAttribute('aria-expanded', 'false')
  await navigation.click()
  await expect(handle).toHaveAttribute('aria-valuenow', '183')
})

test('selecting a route keeps the application sidebar and its visible rows in place', async ({ page }) => {
  await page.setViewportSize({ width: 1160, height: 760 })
  await page.goto('/?component=WP.app-layout')
  const shell = page.getByRole('region', { name: '组件示例' })
  const pane = shell.locator('.sy-app-layout__pane--sidebar')
  const projects = pane.getByRole('link', { name: '项目', exact: true })
  await expect(pane).toHaveCSS('scrollbar-gutter', 'stable')
  await pane.evaluate(node => {
    node.style.maxBlockSize = '110px'
    node.scrollTop = 28
  })
  const position = () => projects.evaluate(node => {
    const sidebar = node.closest<HTMLElement>('.sy-app-layout__pane--sidebar')!
    const row = node.getBoundingClientRect()
    const pane = sidebar.getBoundingClientRect()
    return { scroll: sidebar.scrollTop, pane: pane.top, left: row.left, top: row.top, width: row.width, height: row.height }
  })
  const before = await position()
  expect(before.scroll).toBeGreaterThan(0)
  await projects.click()
  await expect(projects).toHaveAttribute('aria-current', 'page')
  await expect(shell.getByRole('main', { name: '工作区内容' }).getByRole('heading', { name: '项目' })).toBeVisible()
  expect(await position()).toEqual(before)
})

test('top navigation keeps a stable mobile trigger and shares current selection', async ({ page }) => {
  await page.setViewportSize({ width: 1060, height: 720 })
  await page.goto('/?component=WP.navbar')
  const nav = page.getByRole('navigation', { name: '项目顶部导航' })
  const trigger = nav.getByRole('button', { name: '菜单' })
  await expect(nav).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(nav.getByRole('button', { name: '概览' })).toHaveAttribute('aria-current', 'page')
  await nav.getByRole('button', { name: '项目', exact: true }).click()
  await expect(nav.getByRole('button', { name: '项目', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.setViewportSize({ width: 390, height: 720 })
  await expect(trigger).toBeVisible()
  const before = (await trigger.boundingBox())!
  await trigger.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(nav.getByRole('button', { name: '项目', exact: true })).toHaveAttribute('aria-current', 'page')
  expect(await page.evaluate(() => document.documentElement.style.overflowY)).toBe('hidden')
  expect((await trigger.boundingBox())!.width).toBe(before.width)
  await nav.getByRole('button', { name: '文件', exact: true }).press('Escape')
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(nav.getByRole('button', { name: '文件', exact: true })).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.style.overflowY)).toBe('')
  await trigger.press('Space')
  await nav.getByRole('button', { name: '文件', exact: true }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(trigger).toBeFocused()
  await page.setViewportSize({ width: 1060, height: 720 })
  await expect(nav.getByRole('button', { name: '文件', exact: true })).toHaveAttribute('aria-current', 'page')
})

test('shell descendants can open, close and disable mobile navigation with the drawer id', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.goto('/?component=WP.app-layout')
  const shell = page.getByRole('region', { name: '组件示例' })
  const custom = page.locator('button[data-auto-toggle]').filter({ hasText: '打开应用导航' })
  const choice = shell.getByLabel('移动导航触发器')
  const dialog = page.getByRole('dialog', { name: '工作区导航' })
  await choice.selectOption('manual')
  await expect(custom).toHaveAttribute('data-auto-toggle', 'false')
  await expect(shell.getByRole('button', { name: '导航', exact: true })).toHaveCount(0)
  await custom.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(custom).toHaveAttribute('aria-expanded', 'true')
  expect(await custom.getAttribute('aria-controls')).toBe(await dialog.getAttribute('id'))
  await dialog.getByRole('button', { name: '返回应用内容' }).click()
  await expect(dialog).toBeHidden()
  await expect(custom).toBeFocused()
  await choice.selectOption('auto')
  const automatic = shell.getByRole('button', { name: 'Toggle navigation', exact: true })
  await expect(automatic).toBeVisible()
  await automatic.click()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await choice.selectOption('disabled')
  await expect(custom).toBeDisabled()
  await expect(automatic).toHaveCount(0)
})

test('sidebar groups, nested links, page switches and rail retain accessible selection', async ({ page }) => {
  await page.setViewportSize({ width: 1060, height: 740 })
  await page.goto('/?component=WP.sidebar')
  const example = page.getByRole('region', { name: '组件示例' })
  const label = '项目侧栏'
  const nav = example.getByRole('navigation', { name: label })
  const group = nav.getByRole('button', { name: '团队' })
  await group.click()
  await expect(group).toHaveAttribute('aria-expanded', 'false')
  await expect(nav.getByRole('button', { name: '成员', exact: true })).toHaveCount(0)
  await group.click()
  await nav.getByRole('button', { name: '展开 成员' }).press('Enter')
  await nav.getByRole('button', { name: '权限', exact: true }).click()
  await expect(nav.getByRole('button', { name: '权限', exact: true })).toHaveAttribute('aria-current', 'page')
  await example.getByRole('button', { name: '切换分区' }).click()
  await expect(nav.getByRole('button', { name: '账户', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(nav.getByRole('button', { name: '成员', exact: true })).toHaveCount(0)
  const trigger = example.getByRole('button', { name: '导航', exact: true })
  await trigger.press('ControlOrMeta+b')
  await expect(nav).toHaveAttribute('data-rail', 'true')
  await expect(nav.getByRole('button', { name: '账户', exact: true })).toHaveAttribute('title', '账户')

  await page.setViewportSize({ width: 390, height: 740 })
  await expect(nav).toHaveCount(0)
  await trigger.press('Enter')
  const drawer = page.getByRole('dialog', { name: label })
  await expect(drawer.getByRole('button', { name: '账户', exact: true })).toHaveAttribute('aria-current', 'page')
  await drawer.getByRole('button', { name: '通知', exact: true }).click()
  await expect(drawer).toBeHidden()
  await expect(trigger).toBeFocused()
})
