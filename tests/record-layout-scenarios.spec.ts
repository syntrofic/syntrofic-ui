import { expect, test } from '@playwright/test'

test('item examples expose media and statuses and keep focus on adjacent documents', async ({ page }) => {
  await page.goto('/?component=W.item')
  const media = page.getByRole('region', { name: '条目媒体与状态' })
  await expect(media.locator('[data-highlighted]')).toContainText('待核对')
  await expect(media.locator('[data-selected]')).toContainText('需处理')
  await media.getByText('负责版本签发', { exact: true }).click()
  await expect(media.getByRole('status', { name: '成员条目结果' }).locator('.sy-visually-hidden')).toHaveText('查看了林舟')

  const documents = page.getByRole('region', { name: '文档条目标签' })
  const brief = documents.getByRole('button', { name: '发布简报', exact: true })
  await expect(brief).toHaveAttribute('aria-pressed', 'true')
  const research = documents.getByRole('button', { name: '调研笔记', exact: true })
  await documents.getByText('调研笔记', { exact: true }).click()
  await expect(research).toHaveAttribute('aria-pressed', 'true')
  await documents.getByRole('button', { name: '关闭 调研笔记' }).click()
  await expect(research).toHaveCount(0)
  await expect(documents.getByRole('button', { name: '交互原型', exact: true })).toBeFocused()
  await documents.getByRole('button', { name: '新建文档' }).click()
  await expect(documents.getByRole('button', { name: '新文档 1', exact: true })).toBeFocused()
  await expect(documents.getByRole('status', { name: '当前文档' }).locator('.sy-visually-hidden')).toHaveText('新文档 1')
})

