test('list reorder accepts a keyboard or pointer and preserves the locked final item', async ({ page }) => {
  await page.goto('/?component=WP.list-view')
  const list = page.getByRole('list', { name: '交付消息分组' })
  const rows = list.getByRole('listitem')
  const handle = list.getByRole('button', { name: '排序 发布通知' })
  await handle.press('Alt+ArrowDown')
  await expect(rows.first()).toHaveAttribute('data-reorder-key', 'team')
  await expect(rows.nth(1)).toHaveAttribute('data-reorder-key', 'inbox')
  await expect(handle).toBeFocused()
  await handle.press('Alt+ArrowDown')
  await expect(rows.last()).toHaveAttribute('data-reorder-key', 'archive')

  await handle.scrollIntoViewIfNeeded()
  const target = await rows.first().boundingBox()
  const start = await handle.boundingBox()
  if (!target || !start) throw new Error('Missing reorder bounds')
  const x = start.x + start.width / 2
  await page.mouse.move(x, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(x, target.y + 4, { steps: 12 })
  await expect(rows.first()).toHaveAttribute('data-sy-reorder-target', 'before')
  await page.mouse.up()
  await expect(rows.first()).toHaveAttribute('data-reorder-key', 'inbox')
})

test('metadata disclosure restores focus and its column layout adapts to the available space', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/?component=W.metadata-list')
  const details = page.getByRole('region', { name: '发布详情' })
  await expect(details.locator('dt')).toHaveCount(3)
  const expand = details.getByRole('button', { name: '展开发布详情' })
  await expand.click()
  const collapse = details.getByRole('button', { name: '收起发布详情' })
  await expect(collapse).toHaveAttribute('aria-expanded', 'true')
  await expect(details.locator('dt')).toHaveCount(6)
  const link = details.getByRole('link', { name: '发布目录' })
  await link.focus()
  await collapse.evaluate(button => button.click())
  await expect(expand).toBeFocused()
  await expect(link).toHaveCount(0)
  await expect(details.locator('dt')).toHaveCount(3)

  const group = page.getByRole('region', { name: '资料归档字段' })
  const rows = group.locator('dl > div')
  const position = (i: number) => rows.nth(i).evaluate(row => row.offsetTop)
  await expect.poll(() => position(1)).toBe(await position(0))
  const horizontal = page.getByRole('region', { name: '交付摘要字段' })
  await expect(horizontal.locator('dl')).toHaveCSS('display', 'flex')
  await page.getByRole('button', { name: '增加交付组件数' }).click()
  await expect(horizontal.locator('.sy-visually-hidden')).toHaveText('15')
  await page.setViewportSize({ width: 320, height: 800 })
  await expect.poll(() => position(1)).toBeGreaterThan(await position(0))
})

test('steppers keep interactive detail state and offer semantic indicators and density', async ({ page }) => {
  await page.goto('/?component=WP.stepper')
  const release = page.getByRole('region', { name: '签发步骤与详情' })
  const current = release.getByRole('button', { name: '签发复核', exact: true })
  const handoff = release.getByRole('button', { name: '补充通知' })
  await expect(current).toHaveAttribute('aria-current', 'step')
  await expect(current).toHaveAccessibleDescription(/需要确认/)
  await expect(handoff).toHaveAccessibleDescription(/可选步骤/)
  await expect(release.getByRole('button', { name: '受限签发' })).toBeDisabled()
  const notes = release.getByRole('textbox', { name: '签发说明' })
  await notes.fill('发布时同步东区目录')
  await release.getByRole('button', { name: '继续签发' }).press('Enter')
  await expect(handoff).toBeFocused()
  await expect(handoff).toHaveAttribute('aria-current', 'step')
  await expect(notes).toHaveCount(0)
  await release.getByRole('button', { name: '返回签发复核' }).press('Enter')
  await expect(notes).toHaveValue('发布时同步东区目录')
  await expect(release.locator('li[data-status="current"]')).toHaveAttribute('data-density', 'spacious')
  await expect(release.locator('.sy-stepper')).toHaveAttribute('data-indicator-position', 'on-track')
  await expect(release.locator('li[data-status="current"] .sy-stepper__connector')).toHaveAttribute('style', /0\.45/)

  const indicators = page.getByRole('region', { name: '步骤指示器类型' })
  await indicators.getByRole('button', { name: '自定义' }).click()
  await expect(indicators.locator('.sy-stepper__marker .sy-spinner')).toBeVisible()
  await indicators.getByRole('button', { name: '隐藏' }).click()
  await expect(indicators.locator('.sy-stepper__marker').first()).toHaveCSS('visibility', 'hidden')
  await indicators.getByRole('button', { name: '编号' }).click()
  await expect(indicators.locator('li[data-status="complete"] .sy-stepper__marker .sy-visually-hidden')).toHaveText('1')
})

test('responsive steppers collapse with matching controls, preserve selection and skip disabled steps', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/?component=WP.stepper')
  const sample = page.getByRole('region', { name: '自适应发布步骤' })
  const stepper = sample.locator('.sy-stepper')
  const narrow = sample.getByRole('switch', { name: '收窄步骤容器' })
  await expect(stepper).not.toHaveAttribute('data-compact')
  await narrow.click()
  await expect(stepper).toHaveAttribute('data-compact', 'true')
  const next = sample.getByRole('button', { name: '下一道签发步骤' })
  const previous = sample.getByRole('button', { name: '上一道签发步骤' })
  const summary = sample.locator('.sy-stepper__summary')
  await expect(previous).toBeDisabled()
  await expect(next.locator('.sy-button__start svg path')).toBeVisible()
  await next.click()
  await expect(summary.locator('.sy-stepper__title .sy-visually-hidden')).toHaveText('确认可见范围')
  await expect(sample.locator('li').filter({ hasText: '受限迁移' })).toHaveAttribute('data-status', 'pending')
  await next.press('Enter')
  await expect(next).toBeDisabled()
  await expect(previous).toBeFocused()
  await expect(summary.locator('.sy-stepper__title .sy-visually-hidden')).toHaveText('签发版本')
  await sample.getByRole('button', { name: '仅摘要' }).click()
  await expect(next).toHaveCount(0)
  await expect(summary).toBeVisible()
  await sample.getByRole('button', { name: '仅指示器' }).click()
  await expect(summary).toHaveCount(0)
  await narrow.click()
  const current = sample.getByRole('button', { name: '签发版本', exact: true })
  await expect(current).toBeEnabled()
  await expect(current).toHaveAttribute('aria-current', 'step')
  await page.setViewportSize({ width: 320, height: 780 })
  await expect(stepper).toHaveAttribute('data-compact', 'true')
  await expect(sample.getByRole('list', { name: '自适应签发流程' })).toBeVisible()
  expect(await page.pageErrors()).toEqual([])
})
