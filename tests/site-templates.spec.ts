test('filtering and empty results preserve the responsive table tracks', async ({ page }) => {
  const stage = await openTemplate(page, 'table-page')
  const table = stage.getByRole('table', { name: '资料目录', exact: true })
  const headers = table.locator('thead tr')
  const search = stage.getByRole('searchbox', { name: '搜索资料' })
  const tracks = () => headers.evaluate(row => {
    const origin = row.getBoundingClientRect().left
    return Array.from((row as HTMLTableRowElement).cells, cell => {
      const { left, width } = cell.getBoundingClientRect()
      return [left - origin, width]
    })
  })
  await expect(table.getByRole('rowheader')).toHaveCount(4)
  const wide = await tracks()
  for (const width of [1280, 540]) {
    await page.setViewportSize({ width, height: 900 })
    if (width === 540) await expect.poll(async () => (await tracks())[2][1]).toBeLessThan(wide[2][1])
    const before = await tracks()
    await search.fill('品牌')
    await expect(table.getByRole('rowheader')).toHaveText(['品牌资料归档'])
    expect(await tracks()).toEqual(before)
    await search.fill('不存在的记录')
    await expect(table.getByText('没有匹配记录。', { exact: true })).toBeVisible()
    expect(await tracks()).toEqual(before)
    await search.fill('')
    await expect(table.getByRole('rowheader')).toHaveCount(4)
    expect(await tracks()).toEqual(before)
  }
})

test('the filterable table retries a failed source and keeps the current rows during refresh', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 840 })
  let releaseFirst = () => {}
  const first = new Promise<void>(resolve => { releaseFirst = resolve })
  let releaseRefresh = () => {}
  const refresh = new Promise<void>(resolve => { releaseRefresh = resolve })
  let attempts = 0
  await page.route('**/demo-data/delivery-table.json', async route => {
    const attempt = ++attempts
    if (attempt === 1) await first
    if (attempt === 3) await refresh
    if (attempt === 1 || attempt === 3) await route.fulfill({ status: 503, body: 'Unavailable' })
    else await route.continue()
  })
  try {
    const stage = await openTemplate(page, 'table-filter')
    const table = stage.getByRole('table', { name: '交付资料', exact: true })
    const headingWidths = () => table.locator('thead tr').evaluate(row =>
      Array.from((row as HTMLTableRowElement).cells, cell => cell.getBoundingClientRect().width))
    const message = table.locator('.sy-table__message')
    await expect(table).toHaveAttribute('aria-busy', 'true')
    await expect(message.locator('.sy-spinner__ring')).toHaveCSS('animation-name', 'sy-spin')
    const tracks = await headingWidths()
    expect(await message.evaluate(element => {
      const border = element.closest('.sy-table__scroll')!.getBoundingClientRect()
      const bounds = element.getBoundingClientRect()
      return bounds.left >= border.left - 1 && bounds.right <= border.right + 1
    })).toBe(true)
    await stage.getByRole('searchbox', { name: '搜索交付资料' }).fill('品牌')
    releaseFirst()
    await expect(table.getByText('交付资料加载失败。')).toBeVisible()
    const retry = stage.getByRole('button', { name: '重试', exact: true })
    await retry.press('Enter')
    await expect(table.getByRole('rowheader')).toHaveText(['品牌资源'])
    expect(await headingWidths()).toEqual(tracks)

    const reload = stage.getByRole('button', { name: '重新加载' })
    await reload.press('Enter')
    await expect(table).toHaveAttribute('aria-busy', 'true')
    await expect(table.getByRole('rowheader')).toHaveText(['品牌资源'])
    expect(await headingWidths()).toEqual(tracks)
    releaseRefresh()
    await expect(stage.getByText('交付资料加载失败。')).toBeVisible()
    await expect(table.getByRole('rowheader')).toHaveText(['品牌资源'])
    await retry.press('Enter')
    await expect(retry).toBeHidden()
    await expect(table).not.toHaveAttribute('aria-busy', 'true')
    await expect(table.getByRole('rowheader')).toHaveText(['品牌资源'])
    await expect(stage.getByRole('searchbox', { name: '搜索交付资料' })).toHaveValue('品牌')
    expect(attempts).toBe(4)
  } finally {
    releaseFirst()
    releaseRefresh()
  }
})

