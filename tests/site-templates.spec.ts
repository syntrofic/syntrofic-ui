test('canvas touch gestures separate drag, pinch and layer rotation and cancel cleanly', async ({ page }) => {
  const stage = await openTemplate(page, 'canvas-editor')
  const layer = stage.locator('[data-canvas-layer="title"]')
  const rotation = stage.getByRole('spinbutton', { name: '旋转角度' })
  const zoom = stage.getByRole('slider', { name: '缩放' })
  const x = stage.getByRole('spinbutton', { name: '横向位置' })
  await layer.click()
  async function transform(cancel: boolean) {
    await layer.evaluate((node, cancel) => {
      const r = node.getBoundingClientRect()
      const x = r.left + r.width / 2
      const y = r.top + r.height / 2
      function dispatch(type: string, pointerId: number, dx: number, dy: number) {
        node.dispatchEvent(new PointerEvent(type, { bubbles: true, pointerType: 'touch', pointerId, isPrimary: pointerId === 10,
          clientX: x + dx, clientY: y + dy }))
      }
      dispatch('pointerdown', 10, -18, 0)
      dispatch('pointerdown', 11, 18, 0)
      dispatch('pointermove', 11, 28, 46)
      dispatch(cancel ? 'pointercancel' : 'pointerup', 11, 28, 46)
      dispatch('pointerup', 10, -18, 0)
    }, cancel)
  }
  await expect(rotation).toHaveValue('0')
  await transform(true)
  await expect(rotation).toHaveValue('0')
  await expect(zoom).toHaveAttribute('aria-valuenow', '80')
  await transform(false)
  await expect(rotation).toHaveValue('45')
  await expect(zoom).toHaveAttribute('aria-valuenow', '140')
  await expect(x).toHaveValue('48')
  await expect(layer).toHaveCSS('rotate', '45deg')
})

