test('the gallery reserves its columns and animates loading, filtering and retry in place', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 960 })
  let request = 0
  let load!: () => void
  let failRefresh!: () => void
  let retry!: () => void
  let remove!: () => void
  const loading = new Promise<void>(resolve => { load = resolve })
  const pendingRefresh = new Promise<void>(resolve => { failRefresh = resolve })
  const pendingRetry = new Promise<void>(resolve => { retry = resolve })
  const pendingRemoval = new Promise<void>(resolve => { remove = resolve })
  await page.route('**/demo-data/delivery-gallery.json', async route => {
    const call = ++request
    if (call === 1) { await loading; await route.continue(); return }
    if (call === 2) { await pendingRefresh; await route.fulfill({ status: 503 }); return }
    await (call === 3 ? pendingRetry : pendingRemoval)
    const response = await route.fetch()
    const assets = await response.json() as { id: string }[]
    await route.fulfill({ response, json: call === 3 ? assets.reverse() : assets.filter(asset => asset.id !== 'delivery') })
  })
  try {
    const stage = await openTemplate(page, 'classic-gallery')
    const search = stage.getByRole('searchbox', { name: '搜索图集' })
    const headline = stage.getByRole('heading', { name: '交付资料图集', exact: true })
    const frame = stage.locator('.sy-asset-gallery__results')
    const filters = stage.locator('.sy-asset-gallery__filters')
    const resource = stage.getByRole('button', { name: '查看 · 资源分布' })
    const delivery = stage.getByRole('button', { name: '查看 · 交付区域' })
    const footer = page.locator('.site-footer')
    const settle = (target: typeof frame) => target.evaluate(async node => {
      await new Promise(requestAnimationFrame)
      await Promise.allSettled(node.getAnimations().map(animation => animation.finished))
    })
    await expect(frame).toHaveAttribute('data-state', 'loading')
    await expect(frame.getByRole('status')).toHaveText('正在加载图集…')
    await expect(frame.locator('.sy-asset-gallery__placeholder')).toHaveCount(3)
    await settle(stage)
    const controls = async () => [await headline.boundingBox(), await filters.boundingBox(), await search.boundingBox()]
    const initial = await controls()
    load()
    await expect(resource).toBeVisible()
    await expect(frame.getByRole('status')).toHaveCount(0)
    await settle(frame)
    expect(await controls()).toEqual(initial)
    const natural = (await resource.boundingBox())!
    const footerBefore = (await footer.boundingBox())!.y
    await resource.evaluate(button => {
      const tile = button.closest<HTMLElement>('[data-gallery-asset]')!
      const animate = tile.animate.bind(tile)
      tile.animate = (frames, options) => {
        const result = animate(frames, options)
        const keyframes = (result.effect as KeyframeEffect).getKeyframes()
        if (keyframes.some(frame => frame.translate)) tile.dataset.testGalleryMotion = String(keyframes.length)
        return result
      }
    })
    await stage.getByRole('button', { name: '资源', exact: true }).click()
    await expect(stage.locator('[data-gallery-asset="resources"]:not([aria-hidden])').first()).toHaveAttribute('data-test-gallery-motion', /\d+/)
    await expect(delivery).toHaveCount(0)
    await settle(frame)
    await expect.poll(async () => (await resource.boundingBox())!.x).toBeLessThan(natural.x - 100)
    const filtered = (await resource.boundingBox())!
    expect(filtered.width).toBeCloseTo(natural.width, 0)
    expect((await footer.boundingBox())!.y).toBeCloseTo(footerBefore, 0)
    expect(await controls()).toEqual(initial)

    await frame.evaluate(node => {
      const animate = node.animate.bind(node)
      node.animate = (frames, options) => {
        const result = animate(frames, options)
        const keyframes = (result.effect as KeyframeEffect).getKeyframes()
        const easing = (result.effect as KeyframeEffect).getTiming().easing
        if (keyframes.some(frame => frame.blockSize)) node.dataset.testGalleryHeight = easing
        return result
      }
    })
    await search.fill('没有匹配项目')
    await expect(frame).toHaveAttribute('data-state', 'empty')
    await expect(frame).toHaveAttribute('data-test-gallery-height', /cubic-bezier/)
    await expect(frame.getByRole('status')).toHaveText('没有匹配的资料。')
    await expect(search).toBeFocused()
    await search.clear()
    await stage.getByRole('button', { name: '全部', exact: true }).click()
    await expect(delivery).toBeVisible()
    await settle(frame)

    await stage.getByRole('button', { name: '重新加载' }).click()
    await expect(frame.getByRole('list')).toHaveAttribute('aria-busy', 'true')
    await expect(resource).toBeVisible()
    expect(await controls()).toEqual(initial)
    failRefresh()
    await expect(frame.getByRole('alert').locator('.sy-visually-hidden')).toHaveText('图集加载失败，请重试。')
    await expect(resource).toBeVisible()
    await frame.getByRole('button', { name: '重试' }).click()
    await expect(search).toBeFocused()
    await delivery.click()
    const viewer = page.getByRole('dialog', { name: '交付资料图集' })
    await expect(viewer.getByRole('img', { name: '交付园区地图' })).toBeVisible()
    retry()
    await expect(frame.locator('.sy-asset-gallery__body:not([data-layout-swap-copy]) [data-gallery-asset]').first())
      .toHaveAttribute('data-gallery-asset', 'version')
    await expect(viewer.getByRole('img', { name: '交付园区地图' })).toBeVisible()
    await viewer.getByRole('button', { name: '关闭' }).click()
    await expect(delivery).toBeFocused()
    await expect(frame.locator('[data-layout-swap-copy]')).toHaveCount(0)
    await stage.getByRole('button', { name: '重新加载' }).click()
    await delivery.click()
    await expect(viewer.getByRole('img', { name: '交付园区地图' })).toBeVisible()
    remove()
    await expect(viewer).toBeHidden()
    await expect(search).toBeFocused()
  } finally {
    load()
    failRefresh()
    retry()
    remove()
  }
})

