test('compound toolbar slots center content, share sizes and keep tabs independently operable', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.goto('/?component=W.toolbar')
  const demo = page.getByRole('region', { name: '工具栏布局与操作示例' })
  const bar = demo.getByRole('toolbar', { name: '交付文档操作' })
  const title = bar.getByRole('heading', { name: '资料手册' })
  const bounds = (await bar.boundingBox())!
  const headline = (await title.boundingBox())!
  expect(Math.abs(bounds.x + bounds.width / 2 - (headline.x + headline.width / 2))).toBeLessThan(2)
  const back = bar.getByRole('button', { name: '上一份文档' })
  await back.press('ArrowRight')
  await expect(bar.getByRole('button', { name: '舍弃修改' })).toBeFocused()
  await bar.getByRole('button', { name: '保存文档' }).click()
  await expect(demo.locator('.toolbar-review__card-body .sy-visually-hidden')).toHaveText('已保存 资料手册')
  await back.click()
  await expect(bar.getByRole('heading', { name: '发布简报' })).toBeVisible()
  for (const [label, size] of [['紧凑工具栏', 'sm'], ['标准工具栏', 'md'], ['宽松工具栏', 'lg']]) {
    const row = demo.getByRole('toolbar', { name: label })
    await expect(row.getByRole('searchbox')).toHaveAttribute('data-size', size)
    await expect(row.getByRole('button')).toHaveAttribute('data-size', size)
  }

  const tabs = demo.getByRole('toolbar', { name: '发布视图操作' })
  await tabs.getByRole('tab', { name: '待发布' }).press('ArrowRight')
  await expect(tabs.getByRole('tab', { name: '已发布' })).toHaveAttribute('aria-selected', 'true')
  await expect(demo.getByRole('tabpanel', { name: '已发布' }).getByText('品牌指南')).toBeVisible()
  await tabs.getByRole('button', { name: '新建发布草稿' }).click()
  await expect(demo.getByRole('tabpanel', { name: '待发布' }).getByText('交付草稿 1')).toBeVisible()
})

test('the filter toolbar changes visible records and columns and supports undoable bulk operations', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.goto('/?component=W.toolbar')
  const filter = page.getByRole('toolbar', { name: '交付资料筛选' })
  const table = page.getByRole('table', { name: '交付资料列表' })
  const phase = filter.getByRole('combobox', { name: '筛选阶段' })
  await phase.click()
  await page.getByRole('option', { name: '待审核' }).click()
  await expect(filter.locator('.toolbar-review__count .sy-visually-hidden')).toHaveText('2 条记录')
  await expect(table.getByText('交付手册')).toHaveCount(0)
  await filter.getByRole('searchbox').fill('字标')
  await expect(filter.locator('.toolbar-review__count .sy-visually-hidden')).toHaveText('1 条记录')
  await filter.getByRole('button', { name: '清除筛选' }).click()
  await expect(filter.locator('.toolbar-review__count .sy-visually-hidden')).toHaveText('5 条记录')

  const columns = filter.getByRole('button', { name: '选择列' })
  await columns.click()
  const chooser = page.getByRole('dialog', { name: '选择可见列' })
  await chooser.getByRole('checkbox', { name: '显示负责团队' }).uncheck()
  await expect(table.getByRole('columnheader', { name: '负责团队' })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(columns).toBeFocused()

  const first = table.getByRole('row', { name: /品牌字标/ }).getByRole('checkbox')
  const second = table.getByRole('row', { name: /字体授权/ }).getByRole('checkbox')
  await first.check()
  await second.check()
  const batch = page.getByRole('toolbar', { name: '批量操作' })
  await expect(batch.locator('.sy-toolbar__start .sy-visually-hidden')).toHaveText('已选 2 条')
  await batch.getByRole('button', { name: '归档所选' }).click()
  await page.getByRole('alertdialog', { name: '归档所选记录？' }).getByRole('button', { name: '确认批量操作' }).click()
  await expect(table.getByRole('row', { name: /品牌字标|字体授权/ })).toHaveCount(0)
  const undo = batch.getByRole('button', { name: '撤销批量操作' })
  await expect(undo).toBeFocused()
  await undo.click()
  await expect(table.getByRole('row', { name: /品牌字标|字体授权/ })).toHaveCount(2)
  await expect(filter.getByRole('searchbox')).toBeFocused()
})

