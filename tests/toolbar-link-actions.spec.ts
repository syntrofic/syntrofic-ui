test('toggle buttons animate icon and text changes with a stable accessible name and a focused loading state', async ({ page }) => {
  await page.goto('/?component=W.toggle-button')
  const scenes = page.getByRole('region', { name: '切换操作示例' })
  const favorites = scenes.getByRole('button', { name: '收藏当前资料' })
  await expect(favorites.locator('svg > path')).toHaveAttribute('fill', 'none')
  await favorites.press('Enter')
  await expect(favorites).toHaveAttribute('aria-pressed', 'true')
  await expect(favorites.locator('svg > path[fill="currentColor"]')).toHaveCount(1)
  await expect(favorites).toHaveAttribute('data-pressed-tone', 'warning')
  await expect(favorites).toBeFocused()
  await expect(favorites).toHaveCSS('transition-timing-function', /cubic-bezier/)
  const saved = scenes.getByRole('button', { name: '保存书签' })
  await saved.press('Space')
  await expect(saved.locator('.sy-visually-hidden')).toHaveText('已保存书签')
  await expect(saved).toHaveAttribute('aria-pressed', 'true')
  await expect(scenes.getByRole('button', { name: '共享已锁定' })).toBeDisabled()

  const sync = scenes.getByRole('button', { name: '同步状态' })
  await expect(sync).toHaveAttribute('aria-busy', 'true')
  await expect(sync.locator('.sy-spinner')).toBeVisible()
  await sync.focus()
  await page.keyboard.press('Enter')
  await expect(sync).toHaveAttribute('aria-pressed', 'false')
  await expect(sync).toBeFocused()
  await scenes.getByRole('switch', { name: '模拟同步等待' }).click()
  await sync.press('Enter')
  await expect(sync).toHaveAttribute('aria-pressed', 'true')
  await expect(sync).not.toHaveAttribute('aria-busy')
})

