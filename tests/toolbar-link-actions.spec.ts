test.describe('touch toggle groups', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })

  test('touch slides preview until release, cancel outside, and register taps once', async ({ page, browserName }) => {
    test.skip(browserName !== 'chromium', 'Uses the Chromium touch input protocol')
    await page.goto('/?component=W.toggle-button-group')
    const group = page.getByRole('group', { name: '自定义视图' })
    const timeline = group.getByRole('button', { name: '时间线' })
    const table = group.getByRole('button', { name: '表格' })
    await group.scrollIntoViewIfNeeded()
    const from = (await timeline.boundingBox())!
    const to = (await table.boundingBox())!
    expect(from.height).toBeLessThan(44)
    expect(await timeline.evaluate(node => parseFloat(getComputedStyle(node, '::after').top))).toBeLessThan(0)
    const center = (box: typeof from) => ({ x: box.x + box.width / 2, y: box.y + box.height / 2 })
    const cdp = await page.context().newCDPSession(page)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [center(from)] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [center(to)] })
    await expect(table).toHaveAttribute('data-sy-toggle-preview', '')
    await expect(table).toHaveAttribute('aria-pressed', 'false')
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(table).not.toHaveAttribute('data-sy-toggle-preview')
    await expect(table).toHaveAttribute('aria-pressed', 'true')
    await expect(timeline).toHaveAttribute('aria-pressed', 'false')
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [center(from)] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 389, y: center(from).y }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect(table).toHaveAttribute('aria-pressed', 'true')
    await expect(timeline).not.toHaveAttribute('data-sy-toggle-preview')
    await table.tap()
    await expect(table).toHaveAttribute('aria-pressed', 'false')
  })
})

test('async toggle previews the latest choice, rolls back failure and ignores stale completions', async ({ page }) => {
  await page.goto('/?component=W.toggle-button')
  const form = page.getByRole('form', { name: '异步固定示例' })
  const pin = form.getByRole('button', { name: '固定共享资料', exact: true })
  const confirmed = form.getByLabel('已保存状态').locator('.sy-visually-hidden')
  const accept = form.getByRole('button', { name: '确认请求' })
  const reject = form.getByRole('button', { name: '拒绝请求' })
  await expect(confirmed).toHaveText('未固定')
  await pin.press('Space')
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await expect(pin).toHaveAttribute('aria-busy', 'true')
  await expect(pin).toBeEnabled()
  await expect(pin).toBeFocused()
  await expect(pin.locator('.sy-spinner')).toBeVisible()
  await expect(confirmed).toHaveText('未固定')
  await expect(form).toHaveAttribute('data-order', 'click change action')
  await pin.press('Enter')
  await expect(pin).toHaveAttribute('aria-pressed', 'false')
  await expect(form).toHaveAttribute('data-aborted', '1')
  await reject.click()
  await expect(pin).toHaveAttribute('aria-busy', 'true')
  await expect(form.getByRole('alert')).toHaveCount(0)
  await accept.click()
  await expect(pin).not.toHaveAttribute('aria-busy')
  await expect(confirmed).toHaveText('未固定')

  await pin.press('Space')
  await accept.click()
  await expect(confirmed).toHaveText('已固定')
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await pin.press('Space')
  await reject.click()
  await expect(form.getByRole('alert')).toHaveText('固定失败，请重试')
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await expect(pin).not.toHaveAttribute('aria-busy')
  await expect(confirmed).toHaveText('已固定')

  const lock = form.getByRole('switch', { name: '禁止切换' })
  await lock.click()
  await pin.press('Space')
  await expect(form).toHaveAttribute('data-order', 'click change')
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await expect(accept).toBeDisabled()
  await lock.click()
  await pin.press('Space')
  await form.getByRole('button', { name: '重置请求' }).click()
  await expect(form).toHaveAttribute('data-aborted', '2')
  await expect(pin).toHaveAttribute('aria-pressed', 'true')
  await expect(pin).not.toHaveAttribute('aria-busy')
  await accept.click()
  await expect(confirmed).toHaveText('已固定')
})

test('links annotate new tabs and recognize URLs, email addresses and custom issue references', async ({ page }) => {
  await page.goto('/?component=W.link')
  const demo = page.getByRole('region', { name: '链接交互示例' })
  const external = demo.getByRole('link', { name: /无障碍参考.*在新标签页打开/ })
  await expect(external).toHaveAttribute('target', '_blank')
  await expect(external).toHaveAttribute('rel', /noopener/)
  await expect(external.locator('.sy-link__indicator')).toBeVisible()
  const rules = demo.getByRole('link', { name: '交付规则' })
  await rules.focus()
  await expect(rules).toHaveAccessibleDescription('查询发布前的审核和授权要求。')
  await page.keyboard.press('Escape')
  await expect(rules).toBeFocused()

  const matches = demo.locator('.link-review__matches')
  await expect(matches.getByRole('link', { name: 'design@example.org' })).toHaveAttribute('href', 'mailto:design@example.org')
  await expect(matches.getByRole('link', { name: /www\.w3\.org/ })).toHaveAttribute('href', 'https://www.w3.org/WAI/')
  await matches.getByRole('link', { name: '#248' }).press('Enter')
  await expect(demo.locator('[role="status"] .sy-visually-hidden')).toHaveText('已查看任务 #248')
  const comment = demo.getByRole('textbox', { name: '交付评论' })
  await comment.fill('等待复核 #305')
  await expect(matches.getByRole('link', { name: '#305' })).toBeVisible()
  await comment.fill('这条评论没有链接。')
  await expect(matches.getByRole('link')).toHaveCount(0)
  await expect(matches).toHaveText('这条评论没有链接。')
})

