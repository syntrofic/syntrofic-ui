test('WebGL heatmap theme changes ease the rendered pixels without reallocating geometry', async ({ page }) => {
  await page.addInitScript(() => {
    if (!globalThis.WebGL2RenderingContext) return
    const gl = WebGL2RenderingContext.prototype
    const draw = gl.drawArrays
    const buffer = gl.bufferData
    gl.drawArrays = function (mode, start, count) {
      draw.call(this, mode, start, count)
      if (mode !== this.TRIANGLES || count !== 49 * 6 || !(this.canvas instanceof HTMLCanvasElement)
        || !this.canvas.matches('canvas[data-webgl]')) return
      const rgba = new Uint8Array(4)
      this.readPixels(this.drawingBufferWidth >> 1, Math.floor(this.drawingBufferHeight / 14), 1, 1, this.RGBA, this.UNSIGNED_BYTE, rgba)
      const last = [...rgba].join(',')
      this.canvas.dataset.testHeatColor = last
      if (this.canvas.hasAttribute('data-test-heat-samples')) this.canvas.dataset.testHeatSamples += '|' + last
    }
    gl.bufferData = function (...args: unknown[]) {
      Reflect.apply(buffer, this, args)
      if (args[0] === this.ARRAY_BUFFER && this.canvas instanceof HTMLCanvasElement && this.canvas.matches('canvas[data-webgl]')) {
        this.canvas.dataset.testHeatAllocations = String(Number(this.canvas.dataset.testHeatAllocations ?? 0) + 1)
      }
    }
  })
  await page.goto('/?component=W.webgl-chart')
  await page.getByRole('button', { name: '热力', exact: true }).click()
  const canvas = page.locator('canvas[data-webgl="ready"]')
  await canvas.evaluate(node => {
    node.parentElement!.style.setProperty('--sy-motion-replace', '0ms')
    node.parentElement!.style.setProperty('--sy-chart-sage', 'rgb(30, 100, 180)')
  })
  await expect(canvas).toHaveAttribute('data-test-heat-color', '30,100,180,255')
  const allocations = await canvas.getAttribute('data-test-heat-allocations')
  await canvas.evaluate(node => {
    node.setAttribute('data-test-heat-samples', '')
    node.parentElement!.style.setProperty('--sy-motion-replace', '420ms')
    node.parentElement!.style.setProperty('--sy-chart-sage', 'color(srgb .862745 .235294 .313725)')
  })
  await expect(canvas).toHaveAttribute('data-test-heat-color', '220,60,80,255')
  const samples = (await canvas.getAttribute('data-test-heat-samples'))!.split('|')
    .filter(Boolean).map(color => color.split(',').map(Number))
  expect(new Set(samples.filter(([red]) => red > 40 && red < 210).map(([red]) => red)).size).toBeGreaterThan(1)
  await expect(canvas).toHaveAttribute('data-test-heat-allocations', allocations!)
})

