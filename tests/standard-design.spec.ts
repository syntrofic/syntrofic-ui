test('a composed chart keeps its SVG marks through GPU loss and draws before replacing them', async ({ page }) => {
  await page.goto('/?component=W.webgl-chart')
  const plot = page.getByRole('slider', { name: '配送阶段与进度' })
  const heatmap = plot.locator('.sy-chart__gl-layer[data-mark=heatmap]')
  await expect(heatmap).toHaveAttribute('data-renderer', 'webgl')
  const canvas = heatmap.locator('canvas')
  const realContextLoss = await canvas.evaluate(node => {
    const target = node as HTMLCanvasElement & { reviewLoss?: WEBGL_lose_context }
    const extension = target.getContext('webgl2')?.getExtension('WEBGL_lose_context')
    if (extension) {
      target.reviewLoss = extension
      extension.loseContext()
    } else target.dispatchEvent(new Event('webglcontextlost', { cancelable: true }))
    return Boolean(extension)
  })
  await expect(heatmap).toHaveAttribute('data-renderer', 'svg')
  await expect(heatmap.locator('rect').first()).toBeVisible()
  await canvas.evaluate(node => {
    const target = node as HTMLCanvasElement & { reviewLoss?: WEBGL_lose_context }
    if (target.reviewLoss) target.reviewLoss.restoreContext()
    else target.dispatchEvent(new Event('webglcontextrestored'))
  })
  await expect(heatmap).toHaveAttribute('data-renderer', 'webgl')
  const rendered = await canvas.elementHandle()
  await page.getByRole('button', { name: '使用 SVG 回退' }).click()
  await expect(heatmap).toHaveAttribute('data-renderer', 'svg')
  await expect(heatmap.locator('rect')).toHaveCount(12)
  if (realContextLoss) {
    await expect.poll(() => rendered!.evaluate(node => (node as HTMLCanvasElement).getContext('webgl2')?.isContextLost())).toBe(true)
  }
})
