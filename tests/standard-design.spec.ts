  await page.setViewportSize({ width: 390, height: 740 })
  await nav.getByRole('button', { name: '移动产品导航' }).click()
  await trigger.press('ArrowDown')
  await expect(panel).toHaveAttribute('data-inline', '')
  await expect(analysis).toBeFocused()
