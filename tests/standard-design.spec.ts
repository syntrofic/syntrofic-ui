test('lightbox pinches around the image and dismisses with a downward drag from fit', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=W.lightbox')
  const trigger = page.getByRole('button', { name: '查看配送图集' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '配送图集' })
  const stage = dialog.getByRole('group', { name: '配送范围示意图' })
  const image = stage.getByRole('img')
  await expect.poll(() => image.evaluate(node => node.naturalWidth)).toBeGreaterThan(0)
  await stage.evaluate(node => {
    const box = node.getBoundingClientRect()
    const center = { x: box.left + box.width / 2, y: box.top + box.height / 2 }
    function event(type: string, id: number, offset: number) {
      node.dispatchEvent(new PointerEvent(type, {
        bubbles: true, pointerType: 'touch', pointerId: id, isPrimary: id === 73,
        clientX: center.x + offset, clientY: center.y, button: 0,
      }))
    }
    event('pointerdown', 73, -30)
    event('pointerdown', 74, 30)
    event('pointermove', 73, -85)
    event('pointermove', 74, 95)
    event('pointerup', 73, -85)
    event('pointerup', 74, 95)
  })
  await expect(image).toHaveAttribute('data-zoomed', 'true')
  await expect.poll(() => image.evaluate(node => new DOMMatrix(getComputedStyle(node).transform).a)).toBeCloseTo(3)
  const offset = await image.evaluate(node => new DOMMatrix(getComputedStyle(node).transform).e)
  await stage.press('ArrowRight')
  await expect.poll(() => image.evaluate(node => new DOMMatrix(getComputedStyle(node).transform).e)).toBeLessThan(offset)
  await expect(dialog.locator('.sy-lightbox__actions [aria-live="polite"]')).toHaveText('1 / 2')
  await stage.press('0')
  await expect(image).not.toHaveAttribute('data-zoomed')
  const box = (await stage.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 95, { steps: 7 })
  await expect(stage).toHaveAttribute('data-moving', 'true')
  await page.mouse.up()
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

