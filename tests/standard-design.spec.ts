  await expect(confirm).toBeVisible()
  await confirm.getByRole('button', { name: '保留草稿' }).click()
  await expect(remove).toBeFocused()

  await page.goto('/?component=W.button-group')
  const group = page.getByRole('group', { name: '浮起的编辑工具' })
  await expect(group).toHaveCSS('box-shadow', /0px 6px 16px/)
