import { expect, test } from '@playwright/test'

test('dot pagination changes the visible carousel slide and follows its selected position', async ({ page }) => {
  await page.goto('/?component=W.pagination')
  const carousel = page.getByRole('region', { name: '交付说明轮播' })
  const dots = carousel.getByRole('navigation', { name: '选择交付阶段' })
  const first = dots.getByRole('button', { name: '品牌资料' })
  const archive = dots.getByRole('button', { name: '文件归档' })
  await expect(first).toHaveAttribute('aria-current', 'page')
  await archive.press('Enter')
  await expect(archive).toHaveAttribute('aria-current', 'page')
  await expect(carousel.getByRole('heading', { name: '文件归档' })).toBeVisible()
})

test('compact, direct page entry and unknown totals offer the appropriate controls', async ({ page }) => {
  await page.goto('/?component=W.pagination')
  const compact = page.getByRole('navigation', { name: '交付进度页码' })
  const last = compact.getByRole('link', { name: '末页' })
  await expect(last).toHaveAttribute('href', '#交付进度-10')
  await last.press('Enter')
  await expect(compact.getByRole('status').locator('.sy-visually-hidden')).toHaveText('第 10 页，共 10 页')
  await expect(compact.getByRole('button', { name: '末页' })).toBeFocused()
  await expect(compact.getByRole('button', { name: '下一页 · 2' })).toHaveAttribute('aria-disabled', 'true')
  const previous = compact.getByRole('link', { name: '上一页 · 2' })
  await expect(previous).toHaveAttribute('href', '#交付进度-8')
  await previous.press('Enter')
  await expect(compact.getByRole('status').locator('.sy-visually-hidden')).toHaveText('第 8 页，共 10 页')
  await compact.getByRole('link', { name: '下一页 · 2' }).press('Enter')
  await expect(compact.getByRole('button', { name: '下一页 · 2' })).toBeFocused()
  const entry = page.getByRole('navigation', { name: '文档章节分页' })
  const number = entry.getByRole('spinbutton', { name: /章节/ })
  await number.fill('19')
  await number.press('Enter')
  await expect(number).toHaveValue('8')
  await entry.getByRole('button', { name: '首页' }).click()
  await expect(number).toHaveValue('1')
  const cursor = page.getByRole('navigation', { name: '按批次翻页' })
  const next = cursor.getByRole('button', { name: '下一页' })
  await next.press('Enter')
  await next.press('Enter')
  await expect(next).toHaveAttribute('aria-disabled', 'true')
  await expect(cursor.getByRole('status').locator('.sy-visually-hidden')).toHaveText('第 3 页')
})

test('paged tables cancel superseded loads and reset to the first page after changing page size', async ({ page }) => {
  await page.goto('/?component=W.pagination')
  const region = page.getByRole('region', { name: '分页交付记录' })
  const pager = region.getByRole('navigation', { name: '交付记录分页' })
  const next = pager.getByRole('button', { name: '下一页' })
  const range = pager.locator('.sy-pagination__readout .sy-visually-hidden')
  const rows = region.getByRole('table', { name: '分页后的交付记录' }).getByRole('rowheader')
  await expect(range).toHaveText('1–4 条，共 13 条')
  await next.press('Enter')
  await expect(pager).toHaveAttribute('aria-busy', 'true')
  await expect(pager.getByRole('status', { name: '加载交付记录' })).toBeVisible()
  await next.press('Enter')
  await expect(rows).toHaveText(['设计记录 09', '设计记录 10', '设计记录 11', '设计记录 12'])
  await expect(pager).not.toHaveAttribute('aria-busy')
  await expect(range).toHaveText('9–12 条，共 13 条')
  await pager.getByRole('combobox', { name: '每页条数' }).click()
  await page.getByRole('option', { name: '8', exact: true }).click()
  await expect(range).toHaveText('1–8 条，共 13 条')
  await expect(rows).toHaveCount(8)
  await expect(rows.first()).toHaveText('设计记录 01')
})
