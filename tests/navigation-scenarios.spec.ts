test('the overflow menu supports separators, sections, and a compact action sheet', async ({ page }) => {
  await page.goto('/?component=W.dropdown')
  const review = page.getByRole('region', { name: '文档更多操作' })
  const grouped = review.getByRole('button', { name: '分组操作' })
  await grouped.press('Enter')
  const menu = page.getByRole('menu', { name: '分组操作' })
  await expect(menu.getByText('编辑与整理')).toBeVisible()
  await menu.getByRole('menuitem', { name: '重命名' }).click()
  await review.getByRole('textbox', { name: '文档名称' }).fill('新版发布清单')
  await review.getByRole('button', { name: '保存名称' }).click()
  await expect(review.locator('strong .sy-visually-hidden')).toHaveText('新版发布清单')
  await review.getByRole('button', { name: '含分隔线的操作' }).click()
  await expect(page.getByRole('menu', { name: '含分隔线的操作' }).getByRole('separator')).toHaveCount(1)
  await page.keyboard.press('Escape')
  const sheetToggle = review.getByRole('button', { name: '底部操作面板' })
  await sheetToggle.click()
  const sheet = page.getByRole('dialog', { name: '底部操作面板' })
  await sheet.getByRole('button', { name: '移到归档' }).click()
  await expect(sheet).toBeHidden()
  await expect(sheetToggle).toBeFocused()
  await expect(review.getByRole('button', { name: '恢复文档' })).toBeVisible()
  await review.getByRole('button', { name: '恢复文档' }).click()
  await expect(review.getByRole('status', { name: '文档操作结果' }).locator('.sy-visually-hidden')).toHaveText('已恢复文档')
})
