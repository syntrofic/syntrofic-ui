import { expect, test } from '@playwright/test'

test('breadcrumb variants, composed anchors and sibling menus keep the current page clear', async ({ page }) => {
  await page.goto('/?component=W.breadcrumbs')
  const deep = page.getByRole('navigation', { name: '项目档案路径' })
  await expect(deep.getByRole('listitem')).toHaveCount(5)
  await expect(deep.locator('[aria-current="page"]')).toHaveText('布展交接记录')
  await expect(deep.getByRole('link', { name: '工作室' }).locator('svg')).toBeVisible()
  await expect(deep.locator('.sy-crumbs__separator').last()).toHaveText('›')
  await expect(page.getByRole('navigation', { name: '辅助路径' })).toHaveAttribute('data-variant', 'supporting')
  const authored = page.getByRole('navigation', { name: '组合式报表路径' })
  await expect(authored.getByRole('link', { name: '运营报表' })).toHaveAttribute('data-custom-crumb', '')
  await expect(authored.locator('[aria-current="page"]')).toHaveText('交付周期')
  const workspace = page.getByRole('navigation', { name: '切换同级工作区' })
  await workspace.getByRole('button', { name: '品牌组' }).press('Enter')
  const menu = page.getByRole('menu', { name: '品牌组' })
  await expect(menu.getByRole('separator')).toHaveCount(1)
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  const sibling = workspace.getByRole('button', { name: '产品研发组' })
  await expect(sibling).toBeFocused()
  await expect(workspace.locator('[aria-current="page"] .sy-visually-hidden')).toHaveText('审批记录')
  await workspace.getByRole('button', { name: '工作室', exact: true }).click()
  await expect(workspace.locator('[aria-current="page"] .sy-visually-hidden')).toHaveText('工作室概览')
})

test('side navigation account changes, pinning and collapse preserve selection and focus', async ({ page }) => {
  await page.goto('/?component=WP.sidebar')
  const region = page.getByRole('region', { name: '可折叠工作区侧栏' })
  const nav = region.getByRole('navigation', { name: '交付资源侧栏' })
  const switcher = region.getByRole('button', { name: '切换团队账户' })
  await switcher.press('Enter')
  await page.getByRole('menuitem', { name: '交付团队' }).click()
  await expect(switcher).toBeFocused()
  await expect(nav.locator('.sy-side-nav-heading__title .sy-visually-hidden')).toHaveText('交付团队')
  const draft = nav.getByRole('button', { name: '发布草稿', exact: true })
  const menu = nav.getByRole('button', { name: '发布草稿操作' })
  await expect(draft).toHaveAttribute('aria-current', 'page')
  await menu.press('Enter')
  await page.getByRole('menuitem', { name: '置顶发布草稿' }).click()
  await expect(menu).toBeFocused()
  await expect(nav.getByRole('listitem').first().getByRole('button', { name: '发布草稿', exact: true })).toBeVisible()
  await expect(draft).toHaveAttribute('aria-current', 'page')
  await nav.getByRole('button', { name: '收起交付侧栏' }).click()
  const expand = nav.getByRole('button', { name: '展开交付侧栏' })
  await expect(expand).toHaveAttribute('aria-expanded', 'false')
  await expect(nav).toHaveAttribute('data-rail', 'true')
  await expect(draft).toHaveAttribute('aria-current', 'page')
  await expect(menu).toHaveCount(0)
  await expand.press('Enter')
  await expect(nav.getByRole('button', { name: '收起交付侧栏' })).toBeFocused()
  await expect(menu).toBeVisible()
})

test('application shell supports content-only, top, side and combined navigation with a dismissible banner', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 880 })
  await page.goto('/?component=WP.app-layout')
  const scenario = page.getByRole('combobox', { name: '应用布局示例' })
  const shell = page.getByRole('region', { name: '应用布局组合' })
  const content = shell.getByRole('main', { name: '发布页面' })
  const navbar = shell.getByRole('navigation', { name: '交付顶部导航' })
  const sidebar = shell.getByRole('navigation', { name: '发布管理侧栏' })
  async function choose(label: string) {
    await scenario.click()
    await page.getByRole('option', { name: label, exact: true }).click()
  }
  await choose('仅正文')
  await expect(content.getByRole('heading', { name: '交付说明' })).toBeVisible()
  await expect(navbar).toHaveCount(0)
  await expect(sidebar).toHaveCount(0)
  await expect(content).not.toHaveCSS('padding-inline-start', '0px')
  await choose('仅顶部导航')
  await expect(navbar).toBeVisible()
  await expect(sidebar).toHaveCount(0)
  await choose('仅侧栏导航')
  await expect(sidebar).toBeVisible()
  await expect(navbar).toHaveCount(0)
  await choose('顶部与侧栏导航')
  await expect(navbar).toBeVisible()
  await sidebar.getByRole('link', { name: '交付日历' }).click()
  await expect(navbar.getByRole('link', { name: '交付日历' })).toHaveAttribute('aria-current', 'page')
  await expect(content.getByRole('heading', { name: '交付日历' })).toBeVisible()
  await choose('带公告栏的工作台')
  await expect(shell.getByText('发布窗口调整')).toBeVisible()
  await expect.poll(async () => (await content.boundingBox())!.y - (await navbar.boundingBox())!.y).toBeGreaterThan(60)
  await shell.getByRole('button', { name: '关闭发布公告' }).click()
  await expect(shell.getByText('发布窗口调整')).toHaveCount(0)
  await expect(content).toBeFocused()
})

test('a side-only shell exposes its navigation after reflow and restores the mobile trigger', async ({ page }) => {
  await page.setViewportSize({ width: 1080, height: 800 })
  await page.goto('/?component=WP.app-layout')
  await page.getByRole('combobox', { name: '应用布局示例' }).click()
  await page.getByRole('option', { name: '仅侧栏导航' }).click()
  const shell = page.getByRole('region', { name: '应用布局组合' })
  await expect(shell.getByRole('navigation', { name: '发布管理侧栏' })).toBeVisible()
  await page.setViewportSize({ width: 360, height: 790 })
  const toggle = page.locator('button[aria-label="发布导航"]')
  await toggle.press('Enter')
  const drawer = page.getByRole('dialog', { name: '发布导航' })
  await expect(drawer).toBeVisible()
  expect(await toggle.getAttribute('aria-controls')).toBe(await drawer.getAttribute('id'))
  await drawer.getByRole('link', { name: '协作团队' }).click()
  await expect(drawer).toBeHidden()
  await expect(toggle).toBeFocused()
  await expect(shell.getByRole('heading', { name: '协作团队' })).toBeVisible()
})

test('standalone mobile drawers support visual title omission and a right-side presentation', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 840 })
  await page.goto('/?component=W.mobile-nav')
  const toggle = page.getByRole('button', { name: '打开无标题导航抽屉' })
  await toggle.press('Enter')
  const simple = page.getByRole('dialog', { name: '交付目录' })
  await expect(simple.getByRole('heading', { name: '交付目录' })).toHaveClass(/sy-visually-hidden/)
  await expect(simple.getByRole('region', { name: '帮助' })).toBeVisible()
  await simple.getByRole('button', { name: '设计资料' }).click()
  await expect(simple).toBeHidden()
  await expect(toggle).toBeFocused()
  await page.getByRole('button', { name: '从右侧打开目录抽屉' }).click()
  const right = page.getByRole('dialog', { name: '资源目录' })
  await expect(right.locator('..')).toHaveAttribute('data-side', 'right')
  await expect(right.getByRole('button', { name: '设计资料' })).toHaveAttribute('aria-current', 'page')
  await expect.poll(async () => (await right.boundingBox())!.x).toBeCloseTo(54, 0)
  await page.keyboard.press('Escape')
  await expect(right).toBeHidden()
})

