test('complex selectors support a keyboard grid, staged deadline updates and searchable folders', async ({ page }) => {
  await page.goto('/?component=W.complex-selector')
  const gridTrigger = page.getByRole('combobox', { name: '文档显示布局' })
  await gridTrigger.press('Enter')
  const grid = page.getByRole('grid', { name: '预览布局网格' })
  await grid.getByRole('button', { name: '表格 · 紧凑' }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(grid.getByRole('button', { name: '列表 · 紧凑' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(grid).toBeHidden()
  await expect(gridTrigger.locator('.sy-visually-hidden')).toHaveText('列表 · 紧凑')
  await expect(gridTrigger).toBeFocused()
  const deadline = page.getByRole('combobox', { name: '交付截止时间' })
  await deadline.click()
  const choose = page.getByRole('dialog', { name: '交付截止时间' })
  await choose.getByRole('button', { name: '自定义日期和时间' }).click()
  await expect(choose).toBeVisible()
  await expect(deadline.locator('.sy-visually-hidden')).toHaveText('设置截止时间')
  await choose.getByRole('button', { name: '应用截止时间' }).click()
  await expect(choose).toBeHidden()
  await expect(deadline.locator('.sy-visually-hidden')).toHaveText('2026-11-24 16:30')
  const destination = page.getByRole('combobox', { name: '目标文件夹' })
  await destination.click()
  const popover = page.getByRole('dialog', { name: '目标文件夹' })
  await popover.getByRole('textbox', { name: '搜索文件夹' }).fill('标志')
  const folder = popover.getByRole('treeitem', { name: '标志库' })
  await folder.press('Enter')
  await expect(popover).toBeHidden()
  await expect(destination.locator('.sy-visually-hidden')).toHaveText('标志库')
  await expect(destination).toBeFocused()
})
