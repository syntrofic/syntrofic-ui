import { expect, test } from '@playwright/test'

test('async command search separates bootstrap, loading, empty and error states without stale results', async ({ page }) => {
  await page.goto('/?component=WP.command')
  const palette = page.getByRole('region', { name: '异步文件搜索' })
  const input = palette.getByRole('combobox', { name: '查找文件' })
  await expect(palette.getByRole('status')).toHaveText('输入文件名开始搜索。')
  await input.fill('发')
  await expect(input).toHaveAttribute('aria-busy', 'true')
  await expect(palette.getByRole('status')).toHaveText('正在读取文件目录…')
  await expect(palette.locator('.sy-command__spinner')).toBeVisible()
  await input.fill('颜色')
  await expect(palette.getByRole('option', { name: /颜色令牌/ })).toBeVisible()
  await expect(input).not.toHaveAttribute('aria-busy')
  await expect(palette.getByRole('option')).toHaveCount(1)
  await input.press('Enter')
  await expect(page.getByLabel('命令选择结果').locator('.sy-visually-hidden')).toHaveText('已选择颜色令牌')
  await input.fill('归档')
  await palette.getByRole('option', { name: '交付归档' }).click()
  await expect(palette.getByRole('option', { name: '评审记录' })).toBeVisible()
  await palette.getByRole('button', { name: '返回目录搜索' }).click()
  await expect(input).toHaveValue('归档')
  await expect(palette.getByRole('option', { name: '交付归档' })).toBeVisible()
  await input.fill('未收录的资料')
  await expect(palette.getByRole('status')).toHaveText('未找到文件。')
  await palette.getByRole('switch', { name: '文件目录在线' }).click()
  await input.fill('发布')
  await expect(palette.getByRole('status')).toHaveText('文件目录暂不可用。连接后可重新搜索。')
  await expect(palette.getByRole('option')).toHaveCount(0)
})

test('picker selection persists independently of command navigation and groups retain shortcuts', async ({ page }) => {
  await page.goto('/?component=WP.command')
  const trigger = page.getByRole('button', { name: '选择查看方式' })
  await trigger.click()
  const picker = page.getByRole('dialog', { name: '选择表格视图' })
  const input = picker.getByRole('combobox', { name: '搜索表格视图' })
  const summary = picker.getByRole('option', { name: '概览视图' })
  const compact = picker.getByRole('option', { name: '紧凑视图' })
  await expect(summary).toHaveAttribute('aria-selected', 'true')
  await input.press('ArrowDown')
  await expect(input).toHaveAttribute('aria-activedescendant', (await compact.getAttribute('id'))!)
  await expect(compact).toHaveAttribute('aria-selected', 'false')
  await input.press('Enter')
  await expect(picker).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(compact).toHaveAttribute('aria-selected', 'true')
  await expect(compact.locator('.sy-command__check')).toHaveAttribute('data-selected', 'true')
  await input.press('Escape')
  await expect(picker).toBeHidden()
  await expect(trigger).toBeFocused()
  const grouped = page.getByRole('region', { name: '分组工作台命令' })
  const search = grouped.getByRole('combobox', { name: '筛选工作台命令' })
  await expect(grouped.getByRole('group', { name: '项目导航' })).toBeVisible()
  await search.fill('schedule')
  await expect(grouped.getByRole('option')).toHaveCount(1)
  await expect(grouped.getByRole('option').locator('kbd')).toBeVisible()
})

test('standalone command lists support grouped and disabled items with roving keyboard selection', async ({ page }) => {
  await page.goto('/?component=WP.command')
  const region = page.getByRole('region', { name: '手动组合命令列表' })
  const list = region.getByRole('listbox', { name: '文件命令' })
  const start = list.getByRole('option', { name: '打开交付首页' })
  const records = list.getByRole('option', { name: '查看交付记录' })
  await expect(list.getByRole('group')).toHaveCount(2)
  await expect(list.getByRole('option', { name: '修改自动发布设置' })).toHaveAttribute('aria-disabled', 'true')
  await expect(records).toHaveAttribute('aria-selected', 'true')
  await start.press('ArrowDown')
  await expect(records).toBeFocused()
  await records.press('End')
  const last = list.getByRole('option', { name: '查看发送队列' })
  await expect(last).toBeFocused()
  await last.press('Enter')
  await expect(last).toHaveAttribute('aria-selected', 'true')
  await expect(region.locator('.sy-command__hint')).toHaveCount(3)
})

test('autocomplete limits focused suggestions and links validation and help to the field', async ({ page }) => {
  await page.goto('/?component=W.autocomplete')
  const assets = page.getByRole('combobox', { name: '查找交付资料' })
  await assets.focus()
  await expect(page.getByRole('option')).toHaveCount(3)
  await expect(assets).toHaveAccessibleDescription('显示最相关的三项资料。')
  await assets.press('Escape')
  const person = page.getByRole('combobox', { name: '通知同事' })
  await person.fill('目录外')
  await expect(person).toHaveAttribute('aria-invalid', 'true')
  await expect(person).toHaveAccessibleDescription(/发布完成后会通知所选同事。.*请选择目录中已有的同事。/)
  await person.fill('林')
  await page.getByRole('option', { name: '林舟' }).click()
  await expect(person).toHaveValue('林舟')
  await expect(person).not.toHaveAttribute('aria-invalid', 'true')
})

