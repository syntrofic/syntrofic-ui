test('typeahead changes from a listbox to a dialog and returns focus to an existing filter button', async ({ page }) => {
  await page.goto('/?component=W.autocomplete')
  const region = page.getByRole('region', { name: '条件补全和编辑' })
  const input = region.getByRole('combobox', { name: '添加搜索条件' })
  await input.fill('优先')
  await expect(page.getByRole('listbox', { name: '可用条件' }).getByRole('option')).toHaveCount(1)
  await input.press('ArrowDown')
  await input.press('Enter')
  const editor = page.getByRole('dialog', { name: '编辑优先级' })
  await expect(editor).toBeVisible()
  await expect(editor.getByRole('radio', { name: '高', exact: true })).toBeFocused()
  await editor.getByRole('radio', { name: '中', exact: true }).check()
  await editor.getByRole('button', { name: '应用条件' }).click()
  await expect(editor).toBeHidden()
  await expect(input).toBeFocused()
  const chip = region.getByRole('button', { name: '编辑已应用的优先级' })
  await chip.click()
  await expect(editor.getByRole('radio', { name: '中', exact: true })).toBeChecked()
  await page.keyboard.press('Escape')
  await expect(editor).toBeHidden()
  await expect(chip).toBeFocused()
})

