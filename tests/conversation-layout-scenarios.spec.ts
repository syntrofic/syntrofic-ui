import { expect, test } from '@playwright/test'

test('a panel keeps its composer visible while the conversation supports density and starts a real reply', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 830 })
  await page.goto('/?component=WP.chat-conversation')
  const sample = page.getByRole('region', { name: '带编辑器的交接对话' })
  const log = sample.getByRole('log', { name: '交接面板消息' })
  const editor = sample.getByRole('textbox', { name: '输入交接回复' })
  const panel = sample.locator('.sy-chat-conversation')
  const frame = sample.locator('.sy-chat-conversation__content')
  await expect(panel).toHaveAttribute('data-layout', 'panel')
  await expect(frame).toHaveCSS('row-gap', '11px')
  await sample.getByRole('button', { name: '宽松间距' }).press('Space')
  await expect(panel).toHaveAttribute('data-density', 'spacious')
  await expect(frame).toHaveCSS('row-gap', '22px')
  await sample.getByRole('button', { name: '紧凑间距' }).press('Space')
  await expect(frame).toHaveCSS('row-gap', '5px')
  const view = (await log.boundingBox())!
  expect((await editor.boundingBox())!.y).toBeGreaterThanOrEqual(view.y + view.height)
  await editor.fill('发布前复核色板')
  await editor.press('Enter')
  const reply = log.getByRole('article', { name: '交接助手' }).last()
  await expect(reply).toHaveAttribute('aria-busy', 'true')
  await expect(reply.getByRole('status')).toHaveText('正在记录交接要求')
  await expect(reply).toContainText('归档完成后会更新交接记录。')
  await expect(editor).toHaveValue('')
  await expect.poll(() => log.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(4)
})

test('the jump button marks new messages, returns focus and supports standalone labels', async ({ page }) => {
  await page.goto('/?component=WP.chat-conversation')
  const sample = page.getByRole('region', { name: '带编辑器的交接对话' })
  const log = sample.getByRole('log', { name: '交接面板消息' })
  await expect.poll(() => log.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(4)
  await log.evaluate(node => { node.scrollTop = 0 })
  const latest = sample.getByRole('button', { name: '回到交接末尾' })
  await expect(latest).toBeVisible()
  await expect(latest).toHaveAttribute('data-compact', 'true')
  await sample.getByRole('button', { name: '追加未读交接' }).press('Enter')
  await expect(latest.locator('.sy-visually-hidden')).toHaveText('查看未读交接')
  await latest.press('Enter')
  await expect(log).toBeFocused()
  await expect(latest).toHaveCount(0)
  await expect.poll(() => log.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(4)

  const states = page.getByRole('region', { name: '滚动按钮标签与状态' })
  const trigger = states.getByRole('switch', { name: '模拟向上浏览' })
  const compact = states.getByRole('button', { name: '跳到最新交接' })
  await expect(compact).toHaveCount(0)
  await trigger.press('Space')
  await expect(compact).toBeVisible()
  await states.getByRole('button', { name: '未读数量' }).press('Space')
  await states.getByRole('button', { name: '3 条未读回复' }).press('Enter')
  await expect(trigger).toBeFocused()
  await expect(states.getByRole('status', { name: '滚动位置' }).locator('.sy-visually-hidden')).toHaveText('位于消息末尾')
})
