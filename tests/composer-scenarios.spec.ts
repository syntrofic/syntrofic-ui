import { expect, test } from '@playwright/test'

test('the composer integrates a collapsible attachment drawer, context meter and footer menu', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 850 })
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '完整交付编辑器' })
  const composer = sample.getByRole('form', { name: '交付消息正文' })
  const field = composer.getByRole('textbox', { name: '交付消息正文' })
  const attachment = composer.getByRole('button', { name: /交付消息附件/ })
  const usage = composer.getByRole('progressbar', { name: '上下文使用率' })
  await expect(usage).toHaveAttribute('aria-valuenow', '42')
  await attachment.press('Enter')
  await expect(attachment).toHaveAttribute('aria-expanded', 'false')
  await expect(composer.getByRole('button', { name: '从草稿移除 发布清单.csv' })).toHaveCount(0)
  await attachment.press('Space')
  await composer.locator('input[type=file]').setInputFiles({ name: '交接补充.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') })
  const remove = composer.getByRole('button', { name: '从草稿移除 交接补充.txt' })
  await expect(remove).toBeVisible()
  await expect(usage).toHaveAttribute('aria-valuenow', '50')
  await remove.press('Enter')
  await expect(field).toBeFocused()
  await expect(usage).toHaveAttribute('aria-valuenow', '42')
  const model = composer.getByRole('button', { name: '选择复核方式' })
  await model.press('Enter')
  await page.getByRole('menuitem', { name: '逐项复核' }).press('Enter')
  await expect(model.locator('.sy-visually-hidden')).toHaveText('逐项复核')
  await expect(model).toBeFocused()
  await composer.getByRole('button', { name: '提及校对组' }).press('Enter')
  await expect(field).toHaveValue('@校对组 ')
  await sample.getByRole('switch', { name: '平面输入框' }).click()
  await expect(composer).toHaveAttribute('data-variant', 'flat')
  await sample.getByRole('switch', { name: '接近上下文上限' }).click()
  await expect(field).toHaveAccessibleDescription(/92%/)
  expect(await composer.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
})

test('status placement, retry and stopping retain the draft and the send control', async ({ page }) => {
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '完整交付编辑器' })
  const composer = sample.getByRole('form', { name: '交付消息正文' })
  const field = composer.getByRole('textbox', { name: '交付消息正文' })
  const feedback = composer.locator('.sy-prompt-input__feedback')
  await sample.getByRole('switch', { name: '接近上下文上限' }).click()
  await expect(field).toHaveAccessibleDescription(/上下文已使用 92%/)
  expect(await feedback.evaluate(node => Boolean(node.previousElementSibling?.classList.contains('sy-prompt-input__shell')))).toBe(true)
  await expect(field).not.toHaveAttribute('aria-invalid')
  const settings = composer.getByRole('button', { name: '交付设置' })
  await settings.press('Enter')
  await page.getByRole('menuitem', { name: '模拟连接中断' }).press('Enter')

  await field.fill('请生成发布摘要')
  const send = composer.getByRole('button', { name: '发送交付消息' })
  const handle = await send.elementHandle()
  await send.press('Enter')
  const stop = composer.getByRole('button', { name: '停止生成交付摘要' })
  await expect(stop).toHaveAttribute('data-spinning', 'true')
  await expect(stop).toHaveAttribute('aria-busy', 'true')
  await expect(field).toHaveJSProperty('readOnly', true)
  const retry = composer.getByRole('button', { name: '重试交付消息' })
  await expect(retry).toBeFocused()
  await expect(field).toHaveValue('请生成发布摘要')
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(field).toHaveAccessibleDescription(/发布服务暂时不可用/)
  const error = composer.getByRole('alert')
  expect(await error.evaluate(node => node.getBoundingClientRect().bottom <= node.parentElement!.querySelector('.sy-prompt-input__shell')!.getBoundingClientRect().top)).toBe(true)

  await settings.press('Enter')
  await page.getByRole('menuitem', { name: '恢复连接' }).press('Enter')
  await retry.press('Enter')
  await expect(composer).toHaveAttribute('data-status', 'streaming')
  await stop.press('Enter')
  await expect(send).toBeFocused()
  expect(await send.evaluate((current, before) => current === before, handle)).toBe(true)
  await expect(field).toHaveValue('请生成发布摘要')
  await expect(field).toHaveJSProperty('readOnly', false)
})

