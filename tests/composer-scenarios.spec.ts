test('a controlled composer submits distinct slash commands and mentions and honors disabled input', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 850 })
  await page.goto('/?component=W.chat-composer-input')
  const sample = page.getByRole('region', { name: '受控草稿与指令' })
  const editor = sample.getByRole('combobox', { name: '受控交付草稿' })
  await sample.getByRole('button', { name: '载入交付草稿' }).click()
  await expect(editor).toContainText('请核对发布清单')
  await expect(editor).toBeFocused()
  await editor.pressSequentially('/br')
  await expect(page.getByRole('option', { name: /起草发布摘要/ })).toBeVisible()
  await editor.press('Enter')
  await expect(editor.locator('[data-prompt-token-value="/brief"]')).toBeVisible()
  await editor.pressSequentially('@own')
  await expect(page.getByRole('option', { name: /发布负责人/ })).toBeVisible()
  await editor.press('Enter')
  await editor.press('Enter')
  await expect(sample.getByRole('status', { name: '结构化提交结果' }).locator('.sy-visually-hidden'))
    .toHaveText('请核对发布清单 /brief @owner · 2 个结构化引用')
  await expect(editor).toBeEmpty()
  const disabled = sample.getByLabel('已锁定草稿')
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
  await expect(disabled).toHaveAttribute('contenteditable', 'false')
  expect(await sample.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
})

test('standalone send actions swap custom icons without changing focus or dimensions', async ({ page }) => {
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '独立发送与停止按钮' })
  await expect(sample.getByRole('button', { name: '草稿为空' })).toBeDisabled()
  const send = sample.getByRole('button', { name: '提交审核' })
  const box = await send.boundingBox()
  const check = await send.locator('svg path').getAttribute('d')
  await send.press('Enter')
  const stop = sample.getByRole('button', { name: '中止审核' })
  await expect(stop).toBeFocused()
  await expect(stop.locator('svg path')).toHaveCount(1)
  expect(await stop.locator('svg path').getAttribute('d')).not.toBe(check)
  const stoppedBox = await stop.boundingBox()
  expect(stoppedBox?.width).toBe(box?.width)
  expect(stoppedBox?.height).toBe(box?.height)
  await stop.press('Space')
  await expect(send).toBeFocused()
  await expect(sample.getByRole('status', { name: '发送按钮状态' }).locator('.sy-visually-hidden')).toHaveText('已中止审核')
})

test('dictation states provide two sizes with editable simulation and a distinct speaking signal', async ({ page }) => {
  await page.goto('/?component=W.chat-dictation-button')
  const sample = page.getByRole('region', { name: '听写尺寸与状态预览' })
  const small = sample.getByRole('button', { name: '小号开始听写' })
  const medium = sample.getByRole('button', { name: '中号开始听写' })
  await expect(small).toHaveAttribute('data-size', 'sm')
  await expect(medium).toHaveAttribute('data-size', 'md')
  expect((await small.boundingBox())!.height).toBeLessThan((await medium.boundingBox())!.height)
  await small.press('Enter')
  const stop = sample.getByRole('button', { name: '小号停止听写' })
  await expect(stop).toBeFocused()
  await expect(stop.locator('.sy-dictation-button__meter > span')).toHaveCount(5)
  await sample.getByRole('button', { name: '检测到声音' }).press('Space')
  await expect(stop).toHaveAttribute('data-speaking', 'true')
  await stop.press('Enter')
  await expect(small).toHaveAttribute('aria-pressed', 'false')
  await expect(sample.getByRole('status', { name: '模拟听写状态说明' }).locator('.sy-visually-hidden')).toHaveText('待命')
})
