import { expect, test } from '@playwright/test'

test('keeps virtual list selection, navigation and row actions independent', async ({ page }) => {
  await page.goto('/?component=WP.list-view')
  const grid = page.getByRole('grid', { name: '交付资源' })
  const sample = page.getByRole('region', { name: '组件示例' })
  const first = grid.getByRole('row', { name: '品牌色板' })
  await expect(grid).toHaveAttribute('aria-rowcount', '86')
  expect(await grid.locator('.sy-list-view__row').count()).toBeLessThan(30)
  await first.press('Space')
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await first.press('ArrowDown')
  const second = grid.getByRole('row', { name: '版式规范' })
  await expect(second).toBeFocused()
  await second.press('Shift+ArrowDown')
  const next = grid.getByRole('row', { name: '交付清单' })
  await expect(next).toBeFocused()
  await expect(next).toHaveAttribute('aria-selected', 'true')
  await expect(grid.getByRole('row', { name: '待审草稿' })).toHaveAttribute('aria-disabled', 'true')
  await next.press('F2')
  const details = grid.getByRole('button', { name: '详情 交付清单' })
  await expect(details).toBeFocused()
  await details.press('Enter')
  await expect(sample.locator('.review-list-view__result .sy-visually-hidden')).toHaveText('正在查看交付清单')
  await details.press('Escape')
  await expect(next).toBeFocused()
  await next.press('End')
  const last = grid.getByRole('row', { name: '资源 80' })
  await expect(last).toBeFocused()
  await expect(last).toHaveAttribute('aria-rowindex', '86')
  const filter = sample.getByRole('textbox', { name: '筛选资源' })
  await filter.fill('没有这个文件')
  await expect(sample.getByText('没有匹配的资源')).toBeVisible()
  await filter.clear()
  await expect(first).toHaveAttribute('aria-selected', 'true')
})

test('uses actual WebGL, restores popup focus and retains markers and clusters on theme changes', async ({ page }) => {
  await page.goto('/?component=WP.map')
  const map = page.getByRole('region', { name: '制作园区地图' })
  await expect(map).toHaveAttribute('data-ready', 'true', { timeout: 12000 })
  await expect(map.locator('.maplibregl-canvas')).toBeVisible()
  const count = map.getByRole('button', { name: '5 个地点，放大查看' })
  await expect(count).toBeVisible()
  const marker = map.getByRole('button', { name: '制作间' })
  await marker.press('Enter')
  const dialog = map.getByRole('dialog', { name: '制作间' })
  await expect(dialog.getByRole('button', { name: '关闭' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(marker).toBeFocused()
  await page.getByRole('switch', { name: '深色地图' }).click()
  await expect(map).toHaveAttribute('data-ready', 'true')
  await expect(count).toBeVisible()
  await expect(marker).toBeVisible()
  await map.getByRole('button', { name: '放大', exact: true }).click()
  await expect(page.locator('.review-map__tools output .sy-visually-hidden')).toHaveText('14.5')
  await map.getByRole('button', { name: '缩小', exact: true }).click()
  await expect(page.locator('.review-map__tools output .sy-visually-hidden')).toHaveText('13.5')
  await count.click()
  await expect(page.locator('.review-map__tools output .sy-visually-hidden')).not.toHaveText('13.5')
})

test('provides a retryable map fallback when WebGL cannot initialize', async ({ page }) => {
  await page.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (...args: unknown[]) {
      if (String(args[0]).startsWith('webgl')) return null
      return Reflect.apply(getContext, this, args)
    } as typeof getContext
  })
  await page.goto('/?component=WP.map')
  const map = page.getByRole('region', { name: '制作园区地图' })
  const error = map.getByRole('alert')
  await expect(error).toContainText('园区地图暂不可用', { timeout: 12000 })
  await expect(map.getByRole('button', { name: '放大', exact: true })).toHaveCount(0)
  await error.getByRole('button', { name: '重试' }).click()
  await expect(map.getByRole('alert')).toContainText('园区地图暂不可用')
})

test('keeps the timeline semantic and reflows alternating cards beside the left rail on small screens', async ({ page }) => {
  await page.setViewportSize({ width: 1200, height: 760 })
  await page.goto('/?component=WP.timeline')
  const history = page.getByRole('list', { name: '交付经过' })
  await expect(history.getByRole('listitem')).toHaveCount(3)
  await expect(history.locator('time').first()).toHaveAttribute('datetime', '2026-11-20T16:30:00+08:00')
  await expect(history.getByRole('listitem').first()).toHaveAttribute('aria-current', 'true')
  const content = page.locator('.review-timeline__history .sy-timeline__content')
  const aligned = () => content.evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().left))
  const desktop = await aligned()
  expect(desktop[0]).toBeGreaterThan(desktop[1])
  expect(desktop[0]).toBe(desktop[2])
  await page.setViewportSize({ width: 390, height: 755 })
  const mobile = await aligned()
  expect(new Set(mobile).size).toBe(1)
  await expect(page.getByRole('list', { name: '交付里程碑' })).toHaveAttribute('data-orientation', 'horizontal')
})

test('retains widget and controls dimensions through refresh and restores scope on retry', async ({ page }) => {
  await page.goto('/?component=WP.widget')
  const deliveries = page.getByRole('region', { name: '资源交付' })
  const refresh = deliveries.getByRole('button', { name: '刷新' })
  const body = deliveries.locator('.sy-widget__body')
  const before = await body.boundingBox()
  const button = await refresh.boundingBox()
  await refresh.click()
  await expect(body).toHaveAttribute('aria-busy', 'true')
  await expect(refresh).toHaveAttribute('aria-busy', 'true')
  expect(await body.boundingBox()).toEqual(before)
  expect(await refresh.boundingBox()).toEqual(button)
  await expect(deliveries.locator('.sy-kpi__value .sy-visually-hidden').first()).toHaveText('1,432')
  await expect(body).not.toHaveAttribute('aria-busy', 'true')
  expect(await body.boundingBox()).toEqual(before)
  const records = page.getByRole('region', { name: '交付记录' })
  await expect(records.getByRole('list', { name: '记录状态' }).getByRole('listitem')).toHaveCount(2)
  await records.getByRole('button', { name: '重试' }).press('Enter')
  await expect(records).toBeFocused()
  await expect(records).toHaveAttribute('data-state', 'empty')
  await expect(records.getByRole('status')).toHaveText('暂无交付记录')
})
