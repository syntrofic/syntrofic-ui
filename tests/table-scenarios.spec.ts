import { expect, test, type Page } from '@playwright/test'

async function openScenarios(page: Page) {
  await page.goto('/?component=W.table')
  const trigger = page.getByRole('button', { name: '表格样式、筛选与批量操作' })
  await trigger.click()
  const contentId = await trigger.getAttribute('aria-controls')
  await page.locator(`[id="${contentId}"]`).evaluate(async node => {
    await Promise.allSettled(node.getAnimations().map(animation => animation.finished))
  })
}

test('the table card combines rich cells, status markers, compact grids and two filter modes', async ({ page }) => {
  await openScenarios(page)
  const scene = page.getByRole('region', { name: '表格外观与筛选' })
  const table = scene.getByRole('table', { name: '团队交付清单' })
  await expect(table.getByRole('link', { name: '周昱' })).toHaveAttribute('href', 'mailto:zhou@example.test')
  await expect(table.getByRole('img', { name: '完成交付' }).locator('svg')).toHaveCount(1)
  await expect(table.getByRole('img', { name: '已排入队列' }).locator('.sy-table__status-dot')).toBeVisible()
  const surface = scene.locator('.sy-table')
  await scene.getByRole('checkbox', { name: '网格线' }).check()
  await expect(surface).toHaveAttribute('data-dividers', 'grid')
  await expect(surface).toHaveAttribute('data-density', 'compact')
  await expect(table.getByRole('cell').nth(2)).toHaveCSS('box-shadow', /inset/)
  await scene.getByRole('checkbox', { name: '交替行底色' }).uncheck()
  await expect(surface).toHaveAttribute('data-unstriped', 'true')

  await table.getByRole('button', { name: '筛选负责人' }).click()
  const filter = page.getByRole('dialog', { name: '筛选负责人' })
  await filter.getByRole('textbox', { name: '筛选负责人' }).fill('林舟')
  await filter.getByRole('button', { name: '应用筛选' }).click()
  await expect(table.getByRole('rowheader')).toHaveText(['交付指南', '验收附件'])
  await scene.getByRole('button', { name: '表头内筛选' }).click()
  const inline = table.getByRole('textbox', { name: '筛选负责人' })
  await expect(inline).toHaveValue('林舟')
  await inline.fill('方宁')
  await expect(table.getByRole('rowheader')).toHaveText(['上线记录'])
})

test('the table sort state is shared with the readout and grouped rows keep their controls', async ({ page }) => {
  await openScenarios(page)
  const scene = page.getByRole('region', { name: '表格外观与筛选' })
  const card = page.locator('.table-catalog-card')
  const table = card.locator('.sy-table__grid')
  await table.locator('[data-table-column-key="owner"] .sy-table__sort').press('Enter')
  const secondarySort = table.locator('[data-table-column-key="quantity"] .sy-table__sort')
  await secondarySort.press('Shift+Enter')
  await expect(card.locator('.sy-card__footer .sy-visually-hidden')).toHaveText('负责人 升序、条目数 升序')
  await expect(secondarySort).toBeFocused()
  const visible = await table.locator('tbody th[scope="row"]').allTextContents()
  expect(visible.indexOf('验收附件')).toBeLessThan(visible.indexOf('交付指南'))
  await scene.getByRole('checkbox', { name: '按团队分组' }).check()
  const group = table.getByRole('button', { name: '设计组 · 2 条资料' })
  await group.click()
  await expect(group).toHaveAttribute('aria-expanded', 'false')
  await expect(table.getByRole('rowheader', { name: '交付指南' })).toHaveCount(0)
  await expect(table.getByRole('rowheader', { name: '上线记录' })).toBeVisible()
})

test('the selection toolbar counts across pages and clears the complete selection', async ({ page }) => {
  await openScenarios(page)
  const scene = page.getByRole('region', { name: '批量选择与操作' })
  const table = scene.getByRole('table', { name: '待核对交付记录' })
  const selectPage = table.getByRole('checkbox', { name: '选择本页交付记录' })
  const toolbar = scene.getByRole('toolbar', { name: '交付批量操作' })
  await expect(toolbar).toBeHidden()
  await selectPage.check()
  await expect(toolbar).toContainText('已选 8 条')
  await scene.getByRole('button', { name: '交付下一页' }).click()
  await table.getByRole('checkbox', { name: '选择第 9 批 交付指南' }).check()
  await expect(toolbar).toContainText('已选 9 条')
  await toolbar.getByRole('button', { name: '选中全部记录' }).click()
  await expect(toolbar).toContainText('已选 16 条')
  await expect(toolbar.getByRole('button', { name: '只保留本页' })).toBeFocused()
  await toolbar.getByRole('button', { name: '清除选择' }).click()
  await expect(toolbar).toBeHidden()
  await expect(selectPage).toBeFocused()
  await scene.getByRole('button', { name: '交付上一页' }).click()
  await expect(selectPage).not.toBeChecked()
  await expect(table.getByRole('checkbox', { name: '选择第 1 批 交付指南' })).not.toBeChecked()
})

test('the floating toolbar stays within its scrollport and archives rows with undo', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await openScenarios(page)
  const scene = page.getByRole('region', { name: '批量选择与操作' })
  await scene.getByRole('button', { name: '随滚动区悬浮' }).click()
  const scroller = scene.locator('.table-catalog-scroll')
  const select = scroller.getByRole('checkbox', { name: '选择第 1 批 交付指南' })
  const table = scroller.getByRole('table', { name: '待核对交付记录' })
  const toolbar = scroller.getByRole('toolbar', { name: '交付批量操作' })
  await select.scrollIntoViewIfNeeded()
  const header = table.getByRole('columnheader', { name: '资料' })
  const position = () => header.evaluate(node => {
    const scroll = node.closest('.table-catalog-scroll')!
    return node.getBoundingClientRect().y - scroll.getBoundingClientRect().y + scroll.scrollTop
  })
  const before = await position()
  await select.check()
  await expect(toolbar).toBeVisible()
  await expect.poll(async () => Math.abs(await position() - before)).toBeLessThan(1)
  await expect.poll(async () => {
    const outer = (await scroller.boundingBox())!
    const inner = (await toolbar.boundingBox())!
    return Math.round(outer.y + outer.height - inner.y - inner.height)
  }).toBe(16)
  await toolbar.getByRole('button', { name: '归档选中记录' }).click()
  await expect(table.getByRole('rowheader', { name: '第 1 批 交付指南' })).toHaveCount(0)
  const undo = scene.getByRole('button', { name: '撤销本次归档' })
  await undo.click()
  await expect(table.getByRole('rowheader', { name: '第 1 批 交付指南' })).toBeVisible()
  const selectPage = table.getByRole('checkbox', { name: '选择本页交付记录' })
  await expect(selectPage).toBeFocused()
  await selectPage.check()
  await toolbar.getByRole('button', { name: '选中全部记录' }).click()
  await toolbar.getByRole('button', { name: '归档选中记录' }).click()
  await expect(table).toContainText('暂无交付记录')
  await expect(scroller.getByRole('region', { name: '待核对交付记录' })).toBeFocused()
  await undo.click()
  await expect(selectPage).toBeFocused()
})

test('avatar and checkbox share a fixed slot with hover, focus and controlled selection', async ({ page }) => {
  await openScenarios(page)
  const scene = page.getByRole('region', { name: '头像位置选择' })
  const row = scene.getByRole('row', { name: /交付指南/ })
  const avatar = row.locator('.table-catalog-mark__avatar')
  const mark = row.locator('.table-catalog-mark__checkbox')
  const checkbox = row.getByRole('checkbox')
  await avatar.scrollIntoViewIfNeeded()
  await expect(avatar).toHaveCSS('opacity', '1')
  await expect(mark).toHaveCSS('opacity', '0')
  await mark.locator('..').hover()
  await expect(mark).toHaveCSS('opacity', '1')
  await scene.getByRole('columnheader', { name: '团队' }).hover()
  await checkbox.focus()
  await expect(mark).toHaveCSS('opacity', '1')
  const height = (await row.boundingBox())!.height
  await checkbox.press('Space')
  await expect(checkbox).toBeChecked()
  await expect(row).not.toHaveAttribute('aria-selected')
  await expect(scene.locator('.table-catalog-mark__checkbox').last()).toHaveCSS('opacity', '1')
  expect((await row.boundingBox())!.height).toBe(height)
})

