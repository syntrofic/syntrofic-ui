import { expect, test } from '@playwright/test'

test('checkbox details keep the native name, update form validity and restore focus across status changes', async ({ page }) => {
  await page.goto('/?component=W.checkbox')
  const scene = page.getByRole('region', { name: '复选框状态' })
  const metadata = scene.getByRole('checkbox', { name: '包括文件信息', exact: true })
  await expect(metadata).toHaveAccessibleDescription('让评审者查看版本来源和创建日期。')
  const contract = scene.getByRole('checkbox', { name: '供应商合同', exact: true })
  await expect(contract).toHaveAttribute('aria-disabled', 'true')
  await contract.focus()
  await expect(page.getByRole('tooltip')).toHaveText('供应商合同仅对法务团队开放。')
  await contract.press('Space')
  await expect(contract).not.toBeChecked()
  const fixed = scene.getByRole('checkbox', { name: '包括清单首页', exact: true })
  await fixed.press('Space')
  await expect(fixed).toBeChecked()
  await expect(fixed).toHaveAttribute('aria-readonly', 'true')

  const all = scene.getByRole('checkbox', { name: '选中所有附件' })
  const box = all.locator('..').locator('.sy-checkbox__box')
  const expectCenteredMark = async (mark: '.sy-checkbox__mixed' | '.sy-checkbox__check') => {
    const path = box.locator(mark)
    await expect(path).toHaveCSS('opacity', '1')
    const offset = await path.evaluate(element => {
      const glyph = element as SVGGeometryElement
      const { x, y, width, height } = glyph.getBBox()
      const center = new DOMPoint(x + width / 2, y + height / 2).matrixTransform(glyph.getScreenCTM()!)
      const bounds = glyph.closest('.sy-checkbox__box')!.getBoundingClientRect()
      return Math.max(Math.abs(center.x - (bounds.left + bounds.width / 2)), Math.abs(center.y - (bounds.top + bounds.height / 2)))
    })
    expect(offset).toBeLessThan(0.25)
  }
  await expect(all).toHaveJSProperty('indeterminate', true)
  await expectCenteredMark('.sy-checkbox__mixed')
  await all.press('Space')
  await expect(scene.getByRole('checkbox', { name: '交付记录' })).toBeChecked()
  await expect(all).toBeChecked()
  await expect(all).toHaveJSProperty('indeterminate', false)
  await expectCenteredMark('.sy-checkbox__check')
  await all.press('Space')
  await expect(scene.getByRole('checkbox', { name: '设计说明' })).not.toBeChecked()

  const permission = scene.getByRole('checkbox', { name: '确认资料使用授权' })
  const submit = scene.getByRole('button', { name: '验证资料' })
  await expect(permission).toHaveAccessibleDescription('请先确认已取得资料使用授权。')
  await expect(permission).toHaveAttribute('aria-invalid', 'true')
  await submit.click()
  await expect(permission).toBeFocused()
  await expect(scene.getByText('资料通过校验')).toHaveCount(0)
  await permission.press('Space')
  await expect(permission).toBeFocused()
  await expect(permission).not.toHaveAttribute('aria-invalid', 'true')
  await expect(permission).toHaveAccessibleDescription('已确认可随简报交付这些资料。')
  await submit.click()
  await expect(scene.getByText('资料通过校验').first()).toBeVisible()
})

test('checkbox lists keep trailing badges outside names and scope pending state to the updated item', async ({ page }) => {
  await page.goto('/?component=W.checkbox-group')
  const group = page.getByRole('group', { name: '订阅内容' })
  const product = group.getByRole('checkbox', { name: '产品公告', exact: true })
  const design = group.getByRole('checkbox', { name: '设计更新', exact: true })
  const all = page.getByRole('checkbox', { name: '全选可用渠道' })
  await expect(product).toHaveAccessibleDescription('收到影响交付计划的新功能通知。')
  await expect(group.getByText('按需', { exact: true })).toBeVisible()
  await expect(all).toHaveJSProperty('indeterminate', true)
  await product.press('Space')
  await expect(product).toBeChecked()
  await expect(product).toHaveAttribute('aria-busy', 'true')
  await expect(design).not.toHaveAttribute('aria-busy', 'true')
  await product.press('Space')
  await expect(product).toBeChecked()
  await expect(product).toBeFocused()
  await expect(product).not.toHaveAttribute('aria-busy', 'true')
  await expect(all).toBeChecked()

  await all.press('Space')
  await page.getByRole('button', { name: '提交订阅' }).click()
  await expect(design).toBeFocused()
  await expect(design).toHaveJSProperty('validationMessage', '请至少选择一种消息。')
  await page.getByRole('button', { name: '恢复默认' }).click()
  await expect(design).toBeChecked()
  await expect(product).not.toBeChecked()
  await expect(all).toHaveJSProperty('indeterminate', true)
})

test('switch settings keep their descriptions, focus and optimistic values through asynchronous saves', async ({ page }) => {
  await page.goto('/?component=W.switch')
  const scene = page.getByRole('region', { name: '开关状态' })
  const digest = scene.getByRole('switch', { name: '每周简报', exact: true })
  await expect(digest).toHaveAccessibleDescription('在工作周结束时汇总全部更新。')
  const row = digest.locator('..')
  await expect(row.locator('.sy-switch__track')).toHaveCSS('width', '32px')
  const layout = await row.evaluate(element => ({
    label: element.querySelector('label')!.getBoundingClientRect().left,
    track: element.querySelector('.sy-switch__track')!.getBoundingClientRect().left,
  }))
  expect(layout.label).toBeLessThan(layout.track)
  const order = scene.getByRole('checkbox', { name: '标签在开关前' })
  await order.press('Space')
  await expect(row).toHaveAttribute('data-label-position', 'end')
  await expect.poll(() => row.evaluate(element => element.querySelector('label')!.getBoundingClientRect().left
    > element.querySelector('.sy-switch__track')!.getBoundingClientRect().left)).toBe(true)
  await digest.press('Space')
  await expect(digest).toBeChecked()
  await expect(digest).toHaveAttribute('aria-busy', 'true')
  await expect(row.locator('.sy-switch__thumb .sy-spinner')).toBeVisible()
  await digest.press('Space')
  await expect(digest).toBeChecked()
  await expect(digest).toBeFocused()
  await expect(digest).not.toHaveAttribute('aria-busy', 'true')
  await expect(scene.getByText('已订阅每周简报').first()).toBeVisible()
  const sharing = scene.getByRole('switch', { name: '外部共享' })
  await sharing.focus()
  await expect(page.getByRole('tooltip')).toHaveText('仅组织管理员可以启用外部共享。')
  await sharing.press('Space')
  await expect(sharing).not.toBeChecked()
  const archive = scene.getByRole('switch', { name: '保留归档副本' })
  await archive.press('Space')
  await expect(archive).toHaveAccessibleDescription('关闭后只保留当前版本。')
  await expect(archive).toBeFocused()
})

test('radio lists expose orientation and pricing, reject an empty response and clear errors on selection', async ({ page }) => {
  await page.goto('/?component=W.radio-group')
  const visibility = page.getByRole('radiogroup', { name: '可见范围' })
  await expect(visibility).toHaveAttribute('data-orientation', 'horizontal')
  const team = visibility.getByRole('radio', { name: '团队可见' })
  const personal = visibility.getByRole('radio', { name: '仅自己' })
  await team.press('ArrowRight')
  await expect(personal).toBeChecked()
  await expect(personal).toHaveAccessibleDescription('仅你和明确邀请的人。')

  const delivery = page.getByRole('radiogroup', { name: '交付方式' })
  const workspace = delivery.getByRole('radio', { name: '工作区交付', exact: true })
  const mail = delivery.getByRole('radio', { name: '邮件交付', exact: true })
  await expect(delivery.getByText('¥15', { exact: true })).toBeVisible()
  const submit = page.getByRole('button', { name: '确认交付' })
  await submit.click()
  await expect(workspace).toBeFocused()
  await expect(delivery).toHaveAttribute('aria-invalid', 'true')
  await expect(delivery).toHaveAccessibleDescription('两种方式均会发送交付记录。 请选择一种交付方式。')
  await mail.press('Space')
  await expect(delivery).not.toHaveAttribute('aria-invalid', 'true')
  await submit.click()
  await expect(page.getByText('已安排邮件交付').first()).toBeVisible()
})
