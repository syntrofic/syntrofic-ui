import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect(await page.pageErrors()).toEqual([])
})

test('info tips preview on hover and focus, pin on keyboard activation, and dismiss when focus leaves', async ({ page }) => {
  await page.goto('/?component=W.info-tip')
  const metric = page.getByRole('button', { name: '了解按时交付率' })
  const explanation = page.getByRole('tooltip').filter({ hasText: '按约定时间完成的交付数除以到期交付总数。' })
  await metric.hover()
  await expect(explanation).toBeVisible()
  await expect(metric).toHaveAttribute('aria-expanded', 'false')
  await page.mouse.move(1, 1)
  await expect(explanation).toBeHidden()
  await metric.focus()
  await expect(metric).toHaveAccessibleDescription('按约定时间完成的交付数除以到期交付总数。')
  await metric.press('Space')
  await expect(metric).toHaveAttribute('aria-expanded', 'true')
  await expect(metric).toHaveAttribute('aria-controls', await explanation.getAttribute('id') ?? '')
  await page.keyboard.press('Escape')
  await expect(metric).toHaveAttribute('aria-expanded', 'false')
  await expect(explanation).toBeHidden()
  await expect(metric).toBeFocused()
  const permission = page.getByRole('button', { name: '了解归档保留期权限' })
  await permission.focus()
  const notes = page.getByRole('tooltip').filter({ hasText: '只有工作区管理员可以修改归档保留期。' })
  await expect(notes).toBeVisible()
  await permission.press('Enter')
  await expect(permission).toHaveAttribute('aria-expanded', 'true')
  await permission.press('Tab')
  await expect(notes).toBeHidden()
  await expect(permission).toHaveAttribute('aria-expanded', 'false')
})

test('touch info tips use a second press or an outside tap to dismiss pinned help', async ({ browser, baseURL }) => {
  const page = await browser.newPage({ baseURL, viewport: { width: 360, height: 850 }, hasTouch: true })
  try {
    await page.goto('/?component=W.info-tip')
    const button = page.getByRole('button', { name: '了解待复核文件' })
    const tip = page.getByRole('tooltip').filter({ hasText: '已提交且尚未完成复核的文件数。' })
    await button.tap()
    await expect(tip).toBeVisible()
    await expect(button).toHaveAttribute('aria-expanded', 'true')
    await button.tap()
    await expect(tip).toBeHidden()
    await button.tap()
    await expect(tip).toBeVisible()
    await page.getByText('团队成员', { exact: true }).tap()
    await expect(tip).toBeHidden()
    await expect(button).toHaveAttribute('aria-expanded', 'false')
  } finally { await page.close() }
})

test('hover cards explain inline terms, navigate from link previews and initialize a visible profile', async ({ page }) => {
  await page.goto('/?component=WP.hover-card')
  const glossary = page.getByRole('button', { name: '交付快照' })
  await glossary.focus()
  await expect(glossary).toHaveAccessibleDescription('交付快照记录发布时的文件版本和评审状态。')
  await glossary.press('Escape')
  await expect(page.getByRole('tooltip', { name: '交付快照说明' })).toBeHidden()
  const link = page.getByRole('link', { name: '发布材料索引', exact: true })
  await link.press('ArrowDown')
  const preview = page.getByRole('dialog', { name: '发布材料索引预览' })
  await expect(preview.getByRole('link', { name: '查看发布材料索引' })).toBeFocused()
  await expect(preview.getByText('按品牌、文案和源文件分类列出交付内容。')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(link).toBeFocused()
  await page.getByRole('button', { name: '显隐维护者预览' }).click()
  const profile = page.getByRole('dialog', { name: '发布维护者预览' })
  await expect(profile.getByRole('img', { name: '方以' })).toBeVisible()
})

test('numbered citations retain named links, non-link reference previews and icon source lists', async ({ page }) => {
  await page.goto('/?component=WP.chat-source')
  const region = page.getByRole('region', { name: '数字引文和资料索引' })
  const index = region.getByRole('link', { name: '引用 1 · 发布文件索引' })
  await expect(index).toHaveText('1')
  await expect(index).toHaveAttribute('href', '#交付引用目录')
  const note = region.getByRole('note', { name: '引用 3 · 内部复核备注' })
  await expect(note).toHaveText('3')
  await expect(note).toHaveAttribute('tabindex', '0')
  await note.focus()
  await expect(page.getByRole('tooltip').filter({ hasText: '记录尚需确认的签名和版本。' })).toBeVisible()
  await note.press('Escape')
  await index.press('Enter')
  await expect(page).toHaveURL(/#(?:交付引用目录|%E4%BA%A4)/)
  const sources = region.getByRole('list')
  await expect(sources.getByRole('listitem')).toHaveCount(3)
  await expect(sources.locator('svg')).toHaveCount(3)
})
