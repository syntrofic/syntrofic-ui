test('a touch submenu pick cancels its detached release and absorbs late browser clicks only', async ({ page }) => {
  await page.goto('/?component=W.dropdown')
  await page.evaluate(() => {
    const button = document.createElement('button')
    button.textContent = '点击计数'
    button.style.cssText = 'position:fixed;left:0;top:0;z-index:100;padding:8px'
    button.dataset.testClicks = '0'
    button.dataset.testLateClick = '0'
    button.dataset.testLateMouseup = '0'
    button.dataset.testDeliveredMouseup = '0'
    button.addEventListener('click', () => { button.dataset.testClicks = String(Number(button.dataset.testClicks) + 1) })
    window.addEventListener('mouseup', event => {
      if (event.isTrusted && event.target === button) button.dataset.testLateMouseup = '1'
    }, true)
    window.addEventListener('click', event => {
      if (event.isTrusted && event.detail && event.target === button) button.dataset.testLateClick = '1'
    }, true)
    button.addEventListener('mouseup', () => { button.dataset.testDeliveredMouseup = '1' })
    document.body.append(button)
  })
  const background = page.getByRole('button', { name: '点击计数' })
  // Keep a browser press pending so its mouseup and click can arrive without a new pointerdown.
  await background.hover()
  await page.mouse.down()
  await page.getByRole('button', { name: '文件操作' }).press('Enter')
  await page.getByRole('menuitem', { name: '导出' }).press('ArrowRight')
  const from = page.getByRole('menuitem', { name: 'JSON 文件' })
  const to = page.getByRole('menuitem', { name: 'CSV 表格' })
  await expect.poll(() => to.evaluate(item => {
    const { x, y, width, height } = item.getBoundingClientRect()
    return item.contains(document.elementFromPoint(x + width / 2, y + height / 2))
  })).toBe(true)
  const origin = await from.elementHandle()
  const point = (await to.boundingBox())!
  await origin!.evaluate((start, { x, y, width, height }) => {
    const box = start.getBoundingClientRect()
    const pointer = { bubbles: true, composed: true, pointerId: 17, isPrimary: true, pointerType: 'touch', button: 0 }
    start.dispatchEvent(new PointerEvent('pointerdown', { ...pointer, clientX: box.x + box.width / 2, clientY: box.y + box.height / 2 }))
    const touchStart = new Event('touchstart', { bubbles: true, cancelable: true })
    Object.defineProperty(touchStart, 'changedTouches', { value: [{ identifier: 23, target: start }] })
    start.dispatchEvent(touchStart)
    start.dispatchEvent(new PointerEvent('pointerup', { ...pointer, clientX: x + width / 2, clientY: y + height / 2 }))
  }, point)
  await expect(page.locator('.review__result').first()).toContainText('已选择 CSV 表格')
  await expect(from).not.toBeAttached()
  expect(await origin!.evaluate(async start => {
    // A detached target cannot bubble to the window. Let the click fallback expire first.
    await new Promise(resolve => setTimeout(resolve, 475))
    function ended(identifier: number) {
      const event = new Event('touchend', { bubbles: true, cancelable: true })
      Object.defineProperty(event, 'changedTouches', { value: [{ identifier, target: start }] })
      return !start.dispatchEvent(event)
    }
    return [start.isConnected, ended(99), ended(23), ended(23)]
  })).toEqual([false, false, true, false])
  await background.evaluate(button => {
    const target = button as HTMLButtonElement
    target.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }))
    target.click()
  })
  await background.press('Enter')
  await expect(background).toHaveAttribute('data-test-clicks', '3')
  await page.mouse.up()
  await expect(background).toHaveAttribute('data-test-late-mouseup', '1')
  await expect(background).toHaveAttribute('data-test-late-click', '1')
  await expect(background).toHaveAttribute('data-test-delivered-mouseup', '0')
  await expect(background).toHaveAttribute('data-test-clicks', '3')
  await background.click()
  await expect(background).toHaveAttribute('data-test-delivered-mouseup', '1')
  await expect(background).toHaveAttribute('data-test-clicks', '4')
})

test('an explicit context sheet shares controls with the anchored menu and restores the opener', async ({ page }) => {
  await page.goto('/?component=WP.context-menu')
  const document = page.locator('[data-sy-context-trigger][aria-label="工作区说明"]')
  const dialog = page.getByRole('dialog', { name: '文档操作' })
  await document.click({ button: 'right' })
  await expect(dialog).toBeVisible()
  await expect(document).toHaveAttribute('aria-expanded', 'true')
  await dialog.getByRole('checkbox', { name: '标记为常用' }).check()
  await dialog.getByRole('radio', { name: '舒展视图' }).check()
  await dialog.getByRole('button', { name: '移至文件夹' }).click()
  await expect(dialog.getByRole('button', { name: '管理员资料' })).toBeDisabled()
  await dialog.getByRole('button', { name: '设计资料' }).click()
  await expect(dialog).toBeHidden()
  await expect(document).toBeFocused()
  await expect(page.getByRole('region', { name: '文档菜单示例' }).locator('.sy-visually-hidden')).toHaveText('已移至设计资料')

  const manual = page.getByRole('button', { name: '打开文档操作' })
  await manual.click()
  await expect(dialog.getByRole('checkbox', { name: '标记为常用' })).toBeChecked()
  await dialog.getByRole('button', { name: '关闭文档操作' }).click()
  await expect(manual).toBeFocused()

  const shared = page.getByRole('group', { name: '协作资料' })
  await shared.press('Shift+F10')
  const popover = page.getByRole('menu', { name: '资料操作' })
  await expect(popover.getByRole('menuitemradio', { name: '舒展视图' })).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('Escape')
  await expect(shared).toBeFocused()
})

test.describe('compact touch menu presentation', () => {
  test.use({ hasTouch: true, viewport: { width: 385, height: 780 } })

  test('uses a modal action sheet for the project menu', async ({ page }) => {
    await page.goto('/?component=W.dropdown')
    const trigger = page.getByRole('button', { name: '项目操作' })
    await expect(trigger).toHaveAttribute('aria-haspopup', 'dialog')
    await trigger.tap()
    const sheet = page.getByRole('dialog', { name: '项目操作' })
    await expect(sheet).toBeVisible()
    await expect(sheet).toHaveAttribute('aria-modal', 'true')
    await sheet.getByRole('button', { name: '共享项目' }).tap()
    await expect(sheet).toBeHidden()
    await expect(trigger).toBeFocused()
    await expect(page.getByRole('region', { name: '项目菜单示例' }).locator('.sy-visually-hidden')).toHaveText('已生成项目共享链接')
  })

  test('opens a context sheet on a stationary hold and ignores a moving touch', async ({ page }) => {
    await page.goto('/?component=WP.context-menu')
    const trigger = page.locator('[data-sy-context-trigger][aria-label="协作资料"]')
    await expect(trigger).toHaveAttribute('aria-haspopup', 'dialog')
    const sheet = page.getByRole('dialog', { name: '资料操作' })
    const touch = { pointerType: 'touch', pointerId: 12, isPrimary: true, button: 0, clientX: 100, clientY: 160 }
    await trigger.dispatchEvent('pointerdown', touch)
    await trigger.dispatchEvent('pointermove', { ...touch, clientY: 205 })
    await page.waitForTimeout(550)
    await expect(sheet).toBeHidden()
    await trigger.dispatchEvent('pointerup', touch)
    await trigger.dispatchEvent('pointerdown', { ...touch, pointerId: 13 })
    await expect(sheet).toBeVisible()
    await trigger.dispatchEvent('pointerup', { ...touch, pointerId: 13 })
    await sheet.getByRole('button', { name: '创建文档副本' }).tap()
    await expect(sheet).toBeHidden()
    await expect(trigger).toBeFocused()
  })
})

test('a centered navbar switches sibling popovers and animates its current link', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 880 })
  await page.goto('/?component=WP.navbar')
  const nav = page.getByRole('navigation', { name: '团队交付导航' })
  const track = nav.locator('.sy-navbar__desktop-track')
  await expect(track).toBeVisible()
  const brand = nav.getByRole('link', { name: '交付中心' })
  await expect(brand.locator('img')).toHaveJSProperty('complete', true)
  expect(await brand.locator('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  const disabled = nav.getByRole('button', { name: '账单' })
  await expect(disabled).toBeDisabled()
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
  await expect(disabled).not.toHaveAttribute('href')
  const overview = nav.getByRole('link', { name: '总览' })
  await expect(overview).toHaveAttribute('data-icon-only', 'true')
  await expect(overview).toHaveText('')
  await expect.poll(() => track.evaluate(node => {
    const bar = node.closest('.sy-navbar__bar')!.getBoundingClientRect()
    const tabs = node.getBoundingClientRect()
    return Math.abs(bar.x + bar.width / 2 - (tabs.x + tabs.width / 2))
  })).toBeLessThan(2)

  const marker = nav.locator('.sy-navbar__indicator')
  const before = await marker.getAttribute('style')
  const assets = nav.getByRole('link', { name: '资产' })
  await expect(assets).toHaveAttribute('data-workspace-link', '')
  await assets.press('Enter')
  await expect(assets).toHaveAttribute('aria-current', 'page')
  await expect(marker).not.toHaveAttribute('style', before ?? '')
  await expect(marker).toHaveCSS('transition-timing-function', /cubic-bezier/)

  const resource = nav.getByRole('button', { name: '资源' })
  const support = nav.getByRole('button', { name: '支持' })
  const platform = nav.getByRole('button', { name: '平台' })
  await resource.hover()
  const calendar = nav.getByRole('menuitem', { name: '发布日历' })
  await expect(calendar).toBeVisible()
  await expect.poll(() => calendar.evaluate(item => {
    const bounds = item.getBoundingClientRect()
    return item.contains(document.elementFromPoint(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2))
  })).toBe(true)
  await support.hover()
  await expect(support).toHaveAttribute('aria-expanded', 'true')
  await expect(resource).toHaveAttribute('aria-expanded', 'false')
  await platform.press('ArrowDown')
  await expect(support).toHaveAttribute('aria-expanded', 'false')
  const platformPanel = nav.getByRole('region', { name: '平台' })
  await expect(platformPanel.getByRole('link', { name: '组件文档' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(platform).toBeFocused()
})

