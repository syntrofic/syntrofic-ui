import { expect, test } from '@playwright/test'

test('a dialog opened from a closing project menu returns to the original trigger', async ({ page }) => {
  await page.goto('/?component=W.dropdown')
  const scene = page.getByRole('region', { name: '项目菜单示例' })
  const trigger = scene.getByRole('button', { name: '项目操作', exact: true })
  await trigger.press('Enter')
  const menu = scene.getByRole('menu', { name: '项目操作', exact: true })
  const edit = menu.getByRole('menuitem', { name: '编辑项目' })
  await expect(edit).toBeFocused()
  await trigger.evaluate(node => node.addEventListener('focus', () => { node.dataset.testFocusReturned = '' }))
  await edit.press('Enter')
  const dialog = page.getByRole('dialog', { name: '编辑项目' })
  const name = dialog.getByRole('textbox', { name: '项目名称' })
  await expect(name).toBeFocused()
  await expect(menu).toHaveCount(0)
  await expect(trigger).not.toHaveAttribute('data-test-focus-returned')
  await name.fill('协作交付库')
  await dialog.getByRole('button', { name: '保存名称' }).press('Enter')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(scene.getByText('已保存 协作交付库').last()).toBeAttached()
})

