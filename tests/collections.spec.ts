import { expect, test } from '@playwright/test'

test('links select the nearest router, preserve route objects and block invalid destinations before rendering', async ({ page }) => {
  await page.goto('/?component=W.link')
  const demo = page.getByRole('region', { name: '链接路由示例' })
  const project = demo.getByRole('link', { name: '路由项目' })
  await expect(project).toHaveAttribute('data-router', 'workspace')
  await project.press('Enter')
  await expect(demo.getByRole('status')).toHaveText('/projects')
  await expect(demo.getByRole('link', { name: '交付资源' })).toHaveAttribute('data-same-location', 'true')
  await expect(demo.getByRole('link', { name: '局部设置路由' })).toHaveAttribute('data-router', 'dialog')
  await expect(demo.getByRole('link', { name: '自定义文档链接' })).toHaveAttribute('data-router', 'workspace')
  await expect(demo.getByRole('link', { name: 'Markdown 参考' })).toHaveAttribute('data-router', 'workspace')
  const native = demo.getByRole('link', { name: '原生片段' })
  await expect(native).toHaveAttribute('href', '#native-demo')
  await expect(native).not.toHaveAttribute('data-router')
  for (const label of ['已拦截链接', '未开放项目']) {
    const rejected = demo.getByRole('link', { name: label })
    await expect(rejected).toHaveAttribute('aria-disabled', 'true')
    await expect(rejected).not.toHaveAttribute('href')
    await expect(rejected).not.toHaveAttribute('data-router')
    await rejected.dispatchEvent('click')
  }
  await expect(demo.getByRole('status')).toHaveText('/projects')
})

