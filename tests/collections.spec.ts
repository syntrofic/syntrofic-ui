test('opens a popover inside a modal and restores focus after closing', async ({ page }) => {
  await page.goto('/?component=W.popover')
  const plainTrigger = page.getByRole('button', { name: '筛选项目' })
  await plainTrigger.click()
  const plainPopup = page.getByRole('dialog', { name: '筛选项目', exact: true })
  await expect(plainPopup).toBeVisible()
  await plainPopup.getByRole('button', { name: '应用' }).click()
  await expect(plainPopup).toBeHidden()
  await page.locator('.sy-dialog').evaluate(dialog => dialog.style.setProperty('--sy-motion-enter', '700ms'))
  const opener = page.getByRole('button', { name: '在弹窗中试用' })
  await opener.click()
  const modal = page.getByRole('dialog', { name: '项目筛选', exact: true })
  const nestedTrigger = modal.getByRole('button', { name: '打开筛选详情' })
  await expect(modal).not.toHaveAttribute('data-settled')
  await nestedTrigger.press('Enter')
  const popup = page.getByRole('dialog', { name: '打开筛选详情', exact: true })
  const input = popup.getByRole('textbox', { name: '负责人' })
  await expect(input).toBeFocused()
  await expect(modal).toHaveAttribute('data-settled', '')
  const anchor = (await nestedTrigger.boundingBox())!
  await expect.poll(async () => {
    const box = (await popup.boundingBox())!
    return Math.abs(box.x - anchor.x) + Math.abs(box.y - anchor.y - anchor.height - 6)
  }).toBeLessThan(3)
  await input.fill('林舟')
  await input.press('Escape')
  await expect(popup).toBeHidden()
  await expect(modal).toBeVisible()
  await expect(nestedTrigger).toBeFocused()
  await modal.getByRole('button', { name: '关闭' }).click()
  await expect(modal).toBeHidden()
  await expect(opener).toBeFocused()

  await page.goto('/?component=W.alert-dialog')
  const deleteDraft = page.getByRole('button', { name: '删除草稿' })
  await deleteDraft.click()
  const alert = page.getByRole('alertdialog', { name: '删除草稿？' })
  await expect(alert.getByRole('button', { name: '取消' })).toBeFocused()
  await page.mouse.click(8, 8)
  await expect(alert).toBeVisible()
  await alert.getByRole('button', { name: '取消' }).click()
  await expect(alert).toBeHidden()
  await expect(deleteDraft).toBeFocused()
})

test('anchored overlays grow from their trigger and alert touch presses cancel outside the action', async ({ page }) => {
  await page.goto('/?component=W.popover')
  const open = page.getByRole('button', { name: '筛选项目', exact: true })
  await open.click()
  const popup = page.getByRole('dialog', { name: '筛选项目' })
  await expect(popup).toHaveCSS('animation-name', 'sy-anchor-panel-in')
  await expect(popup).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.keyboard.press('Escape')
  await expect(popup).toBeHidden()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await open.click()
  await expect(popup).toHaveCSS('animation-name', 'none')

  await page.goto('/?component=W.alert-dialog')
  const opener = page.getByRole('button', { name: '删除草稿' })
  await opener.click()
  const alert = page.getByRole('alertdialog', { name: '删除草稿？' })
  const confirm = alert.getByRole('button', { name: '删除', exact: true })
  await confirm.evaluate(node => {
    const bounds = node.getBoundingClientRect()
    node.dispatchEvent(new PointerEvent('pointerdown', {
      bubbles: true, pointerId: 42, isPrimary: true, pointerType: 'touch', button: 0,
      clientX: bounds.left + bounds.width / 2, clientY: bounds.top + bounds.height / 2,
    }))
  })
  await expect(confirm).toHaveAttribute('data-alert-pressed', 'true')
  await confirm.evaluate(node => node.dispatchEvent(new PointerEvent('pointermove', {
    bubbles: true, pointerId: 42, isPrimary: true, pointerType: 'touch', clientX: 1, clientY: 1,
  })))
  await expect(confirm).not.toHaveAttribute('data-alert-pressed')
  await confirm.evaluate(node => {
    node.dispatchEvent(new PointerEvent('pointerup', {
      bubbles: true, pointerId: 42, isPrimary: true, pointerType: 'touch', clientX: 1, clientY: 1,
    }))
    node.dispatchEvent(new MouseEvent('click', { bubbles: true, cancelable: true, detail: 1 }))
  })
  await expect(alert).toBeVisible()
  await expect(page.getByText('草稿已删除')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(alert).toBeHidden()
  await expect(page.locator('.review__result')).toContainText('草稿已保留')
  await expect(opener).toBeFocused()
})

test('a managed popover waits for its anchor, can move while open, and keeps keyboard focus within its controls', async ({ page }) => {
  await page.goto('/?component=W.popover')
  const opener = page.getByRole('button', { name: '查看记录详情' })
  await opener.click()
  const popup = page.getByRole('dialog', { name: '记录详情' })
  const entry = popup.getByRole('textbox', { name: '记录说明' })
  const close = popup.getByRole('button', { name: '关闭记录详情' })
  await expect(entry).toBeFocused()
  await entry.fill('等待确认')
  await entry.press('Tab')
  await expect(close).toBeFocused()
  await close.press('Tab')
  await expect(entry).toBeFocused()
  await page.getByRole('button', { name: '移动到文件标记' }).click()
  const target = page.getByText('待审文件标记', { exact: true })
  await expect.poll(async () => Math.abs((await popup.boundingBox())!.x - (await target.boundingBox())!.x)).toBeLessThan(3)
  await expect(entry).toHaveValue('等待确认')
  await entry.press('Escape')
  await expect(popup).toBeHidden()
  await expect(opener).toBeFocused()
})

