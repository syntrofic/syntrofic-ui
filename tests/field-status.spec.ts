import { expect, test } from '@playwright/test'

test('field status variants preserve the control and compose its accessible description', async ({ page }) => {
  await page.goto('/?component=W.field-status')
  const review = page.getByRole('region', { name: '表单状态呈现' })
  const email = review.getByRole('textbox', { name: '工作邮箱' })
  const tipButton = review.getByRole('button', { name: '工作邮箱提示' })
  await expect(email).toHaveAccessibleDescription('请填写工作邮箱。')
  await expect(email).toHaveAttribute('aria-invalid', 'true')
  await expect(review.getByRole('tooltip')).toHaveCount(0)
  await tipButton.focus()
  await expect(tipButton).toHaveAccessibleDescription('请填写工作邮箱。')
  await expect(review.getByRole('tooltip')).toHaveText('请填写工作邮箱。')
  await page.keyboard.press('Escape')
  await expect(review.getByRole('tooltip')).toHaveCount(0)
  await expect(tipButton).toBeFocused()

  await email.fill('review@example.test')
  const select = review.getByLabel('验证反馈方式')
  await select.selectOption('attached')
  await expect(tipButton).toHaveCount(0)
  await expect(email).toHaveValue('review@example.test')
  await expect(email).toHaveAccessibleDescription('请填写工作邮箱。')
  await expect(review.locator('.sy-input-status[data-status="error"][data-variant="attached"]')).toBeVisible()
  await select.selectOption('detached')
  await expect(email).toHaveAccessibleDescription('请填写工作邮箱。')
  await expect(review.locator('.sy-input-status[data-status="error"][data-variant="detached"] svg')).toBeVisible()
})

test('the group owns one affordance and file, date, number and textarea keep their descriptions', async ({ page }) => {
  await page.goto('/?component=W.field-status')
  const review = page.getByRole('region', { name: '表单状态呈现' })
  await expect(review.getByRole('textbox', { name: '项目代号' })).toHaveAccessibleDescription('项目代号将在归档中显示。')
  await expect(review.getByRole('button', { name: '备用提示' })).toHaveCount(0)
  await expect(review.getByRole('textbox', { name: '交接说明' })).toHaveAccessibleDescription('请补充交接人。')
  await expect(review.getByRole('spinbutton', { name: '交付数量' })).toHaveAccessibleDescription('数量在预算内。')
  await expect(review.getByRole('group', { name: '交付日期' })).toHaveAccessibleDescription('请选择工作日。')
  const file = review.getByRole('button', { name: '选择交接文件' })
  await expect(file).toHaveAccessibleDescription('请上传 PDF 文件。')
  const groupTip = review.getByRole('button', { name: '代号输入提示' })
  await groupTip.focus()
  await expect(review.getByRole('tooltip')).toHaveText('项目代号将在归档中显示。')
  await expect(groupTip).toBeFocused()
})

test.describe('touch validation', () => {
  test.use({ hasTouch: true })

  test('the status tip opens and closes on touch without moving to the input', async ({ page }) => {
    await page.goto('/?component=W.field-status')
    const review = page.getByRole('region', { name: '表单状态呈现' })
    const button = review.getByRole('button', { name: '工作邮箱提示' })
    await button.tap()
    await expect(review.getByRole('tooltip')).toHaveText('请填写工作邮箱。')
    await expect(review.getByRole('textbox', { name: '工作邮箱' })).not.toBeFocused()
    await button.tap()
    await expect(review.getByRole('tooltip')).toHaveCount(0)
  })
})
