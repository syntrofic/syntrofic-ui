test('edits and submits individual date and time segments', async ({ page }) => {
  await page.goto('/?component=W.date-field')
  const date = page.getByRole('group', { name: '发布日期' })
  await date.getByRole('spinbutton', { name: '日', exact: true }).press('ArrowUp')
  await page.getByRole('button', { name: '保存' }).click()
  await expect(page.getByText('2026-11-19', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重置' }).click()
  await page.getByRole('button', { name: '保存' }).click()
  await expect(page.getByText('2026-11-18', { exact: true })).toBeVisible()

  await page.goto('/?component=W.time-field')
  const field = page.getByRole('group', { name: '上线时间' })
  const dimensions = await field.boundingBox()
  await field.getByRole('spinbutton', { name: '分钟', exact: true }).press('ArrowUp')
  expect(await field.boundingBox()).toEqual(dimensions)
  await page.getByRole('button', { name: '保存时间' }).click()
  await expect(page.getByRole('form', { name: '上线时间表单' }).locator('.review__result .sy-visually-hidden')).toHaveText('09:35:00')
  const timeSpacing = await field.evaluate(group => {
    const segments = [...group.querySelectorAll<HTMLElement>('.sy-date-segment')]
      .map(segment => ({ part: segment.dataset.syPart, text: segment.textContent, bounds: segment.getBoundingClientRect() }))
      .filter(segment => segment.bounds.width > 0)
    return {
      separators: segments.filter(segment => segment.part === 'literal').map(segment => segment.text),
      gap: Math.max(0, ...segments.slice(1).map((segment, index) => segment.bounds.left - segments[index].bounds.right)),
    }
  })
  expect(timeSpacing.separators).toEqual([':', ':'])
  expect(timeSpacing.gap).toBeLessThanOrEqual(1)
})

