import { expect, test } from '@playwright/test'

test('moving from an open calendar to the next date field leaves typing in that field', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/?component=W.date-picker')
  const trigger = page.getByRole('button', { name: '打开发布日期日历' })
  const second = page.getByRole('group', { name: '发布日期滚轮' }).getByRole('spinbutton').last()
  await trigger.press('Enter')
  const calendar = page.locator('.sy-calendar-popup[data-state="open"]')
  await expect(calendar.locator('.sy-calendar__day[tabindex="0"]')).toBeFocused()
  await trigger.evaluate(node => node.addEventListener('focus', () => { node.dataset.testFocusReturned = '' }))
  const date = Number(await second.getAttribute('aria-valuenow'))
  await second.click()
  await expect(page.locator('.sy-calendar-popup')).toHaveCount(0)
  await expect(second).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(second).toHaveAttribute('aria-valuenow', String(date + 1))
  await expect(trigger).not.toHaveAttribute('data-test-focus-returned')
  await trigger.press('Enter')
  await expect(calendar.locator('.sy-calendar__day[tabindex="0"]')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('a date wheel spins on tap and drag while keeping the form value until applied', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.addInitScript(() => {
    const pulses: number[][] = []
    Object.defineProperty(window, 'selectionPulses', { value: pulses })
    Object.defineProperty(navigator, 'vibrate', { value: (pattern: number[]) => { pulses.push(pattern); return true } })
  })
  await page.goto('/?component=W.date-picker')
  await page.getByRole('button', { name: '打开发布日期滚轮' }).click()
  const wheels = page.locator('.sy-date-wheel [role="listbox"]')
  await expect(wheels).toHaveCount(3)
  const day = wheels.nth(2)
  const apply = page.getByRole('button', { name: '应用滚轮日期' })
  const selection = () => day.locator('[role="option"][aria-selected="true"]')
  await expect(selection()).toHaveText('18')
  await day.getByRole('option', { name: '19', exact: true }).click()
  await expect(day).toHaveAttribute('data-spinning', 'true')
  await expect(apply).toBeDisabled()
  await expect(selection()).toHaveText('19')
  const pulses = () => page.evaluate(() => (window as Window & { selectionPulses?: number[][] }).selectionPulses)
  expect(await pulses()).toEqual([])

  await day.evaluate(node => {
    const box = node.getBoundingClientRect()
    const x = box.left + box.width / 2
    const y = box.top + box.height / 2
    const frame = (type: string, distance: number, time: number) => {
      const event = new PointerEvent(type, { bubbles: true, pointerType: 'touch', pointerId: 4, isPrimary: true, clientX: x, clientY: y - distance })
      Object.defineProperty(event, 'timeStamp', { value: time })
      node.dispatchEvent(event)
    }
    frame('pointerdown', 0, 0)
    frame('pointermove', 19, 200)
    frame('pointermove', 32, 400)
    frame('pointerup', 32, 401)
  })
  await expect(selection()).toHaveText('20')
  expect(await pulses()).toEqual([[5]])
  const values = page.locator('.review__result .sy-visually-hidden')
  await expect(values).toHaveText(['2026-11-18', '2026-11-18'])
  await apply.click()
  await expect(wheels).toHaveCount(0)
  await expect(values).toHaveText(['2026-11-18', '2026-11-20'])
})

