import { expect, test } from '@playwright/test'

test('compound dropdown groups keep keyboard order and expose rich item descriptions', async ({ page }) => {
  await page.goto('/?component=W.dropdown')
  const trigger = page.getByRole('button', { name: '交付列表操作' })
  await trigger.press('Enter')
  const menu = page.getByRole('menu', { name: '交付列表操作' })
  const view = menu.getByRole('group', { name: '查看' })
  const overview = view.getByRole('menuitem', { name: '打开交付摘要' })
  const folder = view.getByRole('menuitem', { name: '打开资料目录' })
  await expect(overview).toHaveAccessibleDescription('查看发布范围和待复核项。')
  await expect(overview.locator('svg path')).toBeVisible()
  await overview.press('ArrowDown')
  await expect(folder).toBeFocused()
  await folder.press('ArrowDown')
  const copy = menu.getByRole('group', { name: '输出' }).getByRole('menuitem', { name: '复制交付链接' })
  await expect(copy).toBeFocused()
  await expect(copy.locator('.sy-badge')).toHaveText('内部')
  await copy.press('Enter')
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('status', { name: '交付菜单操作结果' }).locator('.sy-visually-hidden')).toHaveText('已复制交付链接')

  const settings = page.getByRole('button', { name: '复核运行设置' })
  await settings.press('Enter')
  const choices = page.getByRole('menu', { name: '复核运行设置' })
  const radioGroup = choices.getByRole('group', { name: '选择检查速度' })
  const complete = radioGroup.getByRole('menuitemradio', { name: '完整检查' })
  await complete.press('Enter')
  await expect(complete).toHaveAttribute('aria-checked', 'true')
  const retry = choices.getByRole('group', { name: '完成后' }).getByRole('menuitemcheckbox', { name: '失败时重试' })
  await retry.press('Enter')
  await expect(retry).toHaveAttribute('aria-checked', 'true')
  await expect(choices).toBeVisible()
  await retry.press('Escape')
  await expect(settings).toBeFocused()
  await expect(page.getByRole('status', { name: '复核运行配置' }).locator('.sy-visually-hidden')).toHaveText('完整检查 · 完成后通知 · 失败时重试')
})

test('custom context items announce descriptions and retain right-click and keyboard activation', async ({ page }) => {
  await page.goto('/?component=WP.context-menu')
  const trigger = page.getByRole('group', { name: '交付记录版本' })
  await trigger.press('Shift+F10')
  const context = page.getByRole('menu', { name: '版本记录操作' })
  const item = context.getByRole('menuitem', { name: '建立记录副本' })
  await expect(item).toHaveAccessibleDescription('将当前版本复制到发布工作区。')
  await expect(item.locator('svg path')).toBeVisible()
  await expect(item.locator('kbd')).toBeVisible()
  await expect(context.getByRole('menuitem', { name: '删除锁定版本' })).toHaveAttribute('aria-disabled', 'true')
  await item.press('Enter')
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('status', { name: '版本操作结果' }).locator('.sy-visually-hidden')).toHaveText('已建立记录副本')
  await trigger.click({ button: 'right' })
  await expect(context).toBeVisible()
  await context.getByRole('menuitem', { name: '打开修改记录' }).click()
  await expect(page.getByRole('status', { name: '版本操作结果' }).locator('.sy-visually-hidden')).toHaveText('已打开修改记录')
})

test('vertical toggle groups apply single and multiple selection with arrow navigation', async ({ page }) => {
  await page.goto('/?component=W.toggle-button-group')
  const single = page.getByRole('group', { name: '侧栏记录范围' })
  const mine = single.getByRole('button', { name: '我负责的记录' })
  const all = single.getByRole('button', { name: '全部交付记录' })
  await expect(mine).toHaveAttribute('aria-pressed', 'true')
  await mine.press('ArrowDown')
  await expect(all).toBeFocused()
  await all.press('Space')
  await expect(all).toHaveAttribute('aria-pressed', 'true')
  await expect(mine).toHaveAttribute('aria-pressed', 'false')
  const multi = page.getByRole('group', { name: '交付检查项' })
  const layout = multi.getByRole('button', { name: '检查布局' })
  const copy = multi.getByRole('button', { name: '检查文案' })
  await layout.press('ArrowDown')
  await expect(copy).toBeFocused()
  await copy.press('Enter')
  await expect(copy).toHaveAttribute('aria-pressed', 'true')
  await expect(layout).toHaveAttribute('aria-pressed', 'true')
})

test('card carousels snap and fade only where more cards are available', async ({ page }) => {
  await page.goto('/?component=WP.carousel')
  const features = page.getByRole('region', { name: '交付功能卡片' })
  const edge = features.locator('.sy-carousel__window')
  await expect(edge).toHaveAttribute('data-fade-end', 'true')
  await expect(edge).not.toHaveAttribute('data-fade-start')
  const teams = page.getByRole('region', { name: '评审成员卡片' })
  const tracks = teams.locator('.sy-carousel__window')
  const next = teams.getByRole('button', { name: '后一组卡片' })
  await expect(teams.getByRole('heading', { name: '林舟' })).toBeVisible()
  await next.press('Enter')
  await expect(teams.getByRole('heading', { name: '陈禾' })).toBeVisible()
  await expect(tracks).toHaveAttribute('data-fade-start', 'true')
  const offset = () => teams.locator('.sy-carousel__viewport').evaluate(node => node.scrollLeft)
  await expect.poll(offset).toBeGreaterThan(0)
  await next.press('Enter')
  await expect(teams.getByRole('heading', { name: '方以' })).toBeVisible()
  await expect(tracks).not.toHaveAttribute('data-fade-end')
  await expect(next).toHaveAttribute('aria-disabled', 'true')
})
