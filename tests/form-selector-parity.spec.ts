import { expect, test } from '@playwright/test'

test('compound fields associate required labels, helper text and live validation', async ({ page }) => {
  await page.goto('/?component=W.text-field')
  const email = page.getByRole('textbox', { name: '工作邮箱', exact: true })
  const contact = page.getByRole('textbox', { name: '备用联系方式' })
  await expect(email).toHaveAttribute('required', '')
  await expect(contact).toHaveAccessibleDescription('跨地区电话请包含国家区号。')
  await expect(contact).not.toHaveAttribute('required')
  await email.fill('lin')
  await expect(email).toHaveAttribute('aria-invalid', 'true')
  await expect(email).toHaveAccessibleDescription('发送交付确认和访问通知。 请输入完整的邮箱地址。')
  await expect(page.getByRole('alert').filter({ hasText: '请输入完整的邮箱地址。' })).toHaveCount(1)
  await email.fill('lin@example.com')
  await expect(email).not.toHaveAttribute('aria-invalid')
  await expect(email).toHaveAccessibleDescription('发送交付确认和访问通知。 邮箱格式正确。')
  await expect(email).toBeFocused()
  await email.clear()
  await expect(email).toHaveAccessibleDescription('发送交付确认和访问通知。')
})

test('standalone labels focus controls and expose separate tooltip buttons', async ({ page }) => {
  await page.goto('/?component=W.label')
  const phone = page.getByRole('textbox', { name: '电话', exact: true })
  await page.locator('label').getByText('电话', { exact: true }).click()
  await expect(phone).toBeFocused()
  await expect(phone).toHaveAccessibleDescription('请包含国家或地区代码。')
  await expect(page.getByRole('textbox', { name: '工作区 ID' })).toBeDisabled()
  const tooltip = page.getByRole('button', { name: '接口密钥说明' })
  await tooltip.focus()
  await expect(page.getByRole('tooltip')).toHaveText('在工作区的开发者设置中生成密钥。')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toBeHidden()
  await expect(tooltip).toBeFocused()
})

test('form layouts reflow within the container and preserve edited controls', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/?component=W.form-layout')
  const settings = page.locator('[data-demo-layout="settings"]')
  const name = settings.getByRole('textbox', { name: '工作区名称' })
  const heading = settings.locator('.sy-field__heading').first()
  await name.fill('林舟工作室')
  await expect(settings).toHaveAttribute('data-compact', 'false')
  await expect(heading).toHaveCSS('grid-column-start', '1')
  await expect(name).toHaveCSS('grid-column-start', '2')
  await page.getByRole('button', { name: '标签在上方' }).click()
  await expect(settings).toHaveAttribute('data-layout', 'vertical')
  await expect(name).toHaveValue('林舟工作室')
  await page.getByRole('button', { name: '标签在左侧' }).click()
  const family = page.getByRole('textbox', { name: '姓氏' })
  const given = page.getByRole('textbox', { name: '名字' })
  await expect.poll(async () => Math.abs((await family.boundingBox())!.y - (await given.boundingBox())!.y)).toBeLessThan(1)
  await page.setViewportSize({ width: 360, height: 760 })
  await expect(settings).toHaveAttribute('data-compact', 'true')
  await expect.poll(async () => (await given.boundingBox())!.y - (await family.boundingBox())!.y).toBeGreaterThan(36)
  await expect(name).toHaveValue('林舟工作室')
  const notifications = page.getByRole('region', { name: '项目通知设置' })
  await notifications.getByRole('checkbox', { name: '站内通知' }).check()
  await notifications.getByRole('button', { name: '保存通知设置' }).click()
  await expect(notifications.getByRole('status', { name: '已保存的通知设置' })).toContainText('品牌素材 · 团队可见 · 邮件 · 站内通知')
})

test('rich select values grow by one line and compact inside input groups', async ({ page }) => {
  await page.goto('/?component=W.select')
  const compact = page.getByRole('combobox', { name: '默认单行值' })
  const rich = page.getByRole('combobox', { name: '带说明的值' })
  const grouped = page.getByRole('combobox', { name: '组合访问范围' })
  await expect(rich.getByText('只有收到邀请的人可以访问。', { exact: true }).first()).toBeAttached()
  await expect(rich.locator('small')).toBeVisible()
  await expect(grouped.locator('small')).toBeHidden()
  await expect.poll(async () => (await rich.boundingBox())!.height - (await compact.boundingBox())!.height).toBeCloseTo(16, 0)
  await rich.press('Enter')
  await page.getByRole('option', { name: '公开', exact: true }).click()
  await expect(rich).toContainText('公开')
  await expect(rich).toBeFocused()
  await expect.poll(async () => (await rich.boundingBox())!.height - (await compact.boundingBox())!.height).toBeCloseTo(0, 0)
})

test('bottom sheet single selection closes, while multiple choices stay in the sheet', async ({ page }) => {
  await page.goto('/?component=W.select')
  const single = page.getByRole('combobox', { name: '移动端访问范围' })
  await single.press('ArrowDown')
  const sheet = page.getByRole('dialog', { name: '选择访问范围' })
  await expect(sheet).toBeVisible()
  await expect(sheet).toHaveAttribute('aria-modal', 'true')
  await sheet.getByRole('option', { name: '邀请成员' }).click()
  await expect(sheet).toBeHidden()
  await expect(single).toBeFocused()
  await expect(single).toContainText('邀请成员')
  const multi = page.getByRole('combobox', { name: '移动端权限' })
  await multi.click()
  const permissions = page.getByRole('dialog', { name: '选择权限' })
  const comment = permissions.getByRole('option', { name: '发表评论' })
  await comment.click()
  await expect(comment).toHaveAttribute('aria-selected', 'true')
  await expect(permissions.getByRole('option', { name: '删除归档' })).toHaveAttribute('aria-disabled', 'true')
  await expect(permissions).toBeVisible()
  await permissions.getByRole('button', { name: '完成选择' }).click()
  await expect(multi).toBeFocused()
  await expect(multi).toContainText('浏览文件和发表评论')
})

test('filtered select all preserves other choices and native form submission', async ({ page }) => {
  await page.goto('/?component=W.select')
  const basic = page.getByRole('combobox', { name: '基本权限' })
  const save = page.getByRole('button', { name: '保存成员权限' })
  const result = page.getByRole('status', { name: '已保存的权限' })
  await save.click()
  await expect(result).toBeEmpty()
  await expect(basic).toBeFocused()
  await expect(basic).toHaveAccessibleDescription('请选择至少一项基本权限。')
  await basic.click()
  const popup = page.getByRole('dialog', { name: '基本权限' })
  const search = popup.getByRole('combobox', { name: '搜索权限' })
  await expect(search).toBeFocused()
  await search.fill('读取')
  await expect(popup.getByRole('option')).toHaveCount(2)
  await popup.getByRole('checkbox', { name: '全选匹配权限' }).check()
  await search.fill('上传')
  await search.press('ArrowDown')
  await expect(search).toHaveAttribute('aria-activedescendant')
  await search.press('Enter')
  await expect(popup.getByRole('option', { name: '上传文件' })).toHaveAttribute('aria-selected', 'true')
  await search.fill('管理')
  await expect(popup.getByRole('checkbox', { name: '全选匹配权限' })).toBeDisabled()
  await search.fill('不存在')
  await expect(popup.getByRole('status')).toHaveText('没有匹配的权限')
  await search.press('Escape')
  await expect(basic).toBeFocused()
  await save.click()
  await expect(result).toContainText('浏览文件、查看历史、上传文件')
  await page.getByRole('button', { name: '恢复初始权限' }).click()
  await expect(basic).toContainText('请选择权限')
  await expect(basic).not.toHaveAttribute('aria-invalid')
})

test('searchable select popovers allow tabbing onward and dismiss from their trigger', async ({ page }) => {
  await page.goto('/?component=W.select')
  const basic = page.getByRole('combobox', { name: '基本权限' })
  const popup = page.getByRole('dialog', { name: '基本权限' })
  await basic.press('Enter')
  const search = popup.getByRole('combobox', { name: '搜索权限' })
  await expect(search).toBeFocused()
  await search.press('Tab')
  const selectAll = popup.getByRole('checkbox', { name: '全选匹配权限' })
  await expect(selectAll).toBeFocused()
  await selectAll.press('Tab')
  await expect(popup).toBeHidden()
  await expect(page.getByRole('combobox', { name: '附加权限' })).toBeFocused()
  await basic.click()
  await expect(popup).toBeVisible()
  await basic.click()
  await expect(popup).toBeHidden()
  await expect(basic).toBeFocused()
})

test('headless selector fields move the active option while retaining input focus', async ({ page }) => {
  await page.goto('/?component=W.select')
  const owner = page.getByRole('combobox', { name: '搜索负责人' })
  await owner.fill('组件')
  await owner.press('ArrowDown')
  const choice = page.getByRole('option', { name: /许然/ })
  await expect(owner).toHaveAttribute('aria-activedescendant', (await choice.getAttribute('id'))!)
  await owner.press('Enter')
  await expect(owner).toHaveValue('许然')
  await expect(owner).toBeFocused()
  const tags = page.getByRole('combobox', { name: '搜索标签' })
  await tags.fill('工程')
  await tags.press('ArrowDown')
  await tags.press('Enter')
  await expect(page.getByRole('option', { name: /可访问性/ })).toHaveAttribute('aria-selected', 'true')
  await expect(tags).toBeFocused()
  await page.getByRole('button', { name: '移除可访问性' }).click()
  await expect(page.getByRole('option', { name: /可访问性/ })).toHaveAttribute('aria-selected', 'false')
  await expect(tags).toBeFocused()
})
