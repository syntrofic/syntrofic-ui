import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect(await page.pageErrors()).toEqual([])
})

test('tilts the holo face without changing the layout and settles into the static state', async ({ page }) => {
  await page.setViewportSize({ width: 920, height: 720 })
  await page.goto('/?component=WP.holo-card')
  const card = page.locator('.sy-holo-card[aria-label="品牌工作室成员证"]')
  const visitor = page.locator('.sy-holo-card[aria-label="工作室访客证"]')
  await expect(card).toHaveAttribute('data-active', 'true')
  await expect(visitor).toHaveAttribute('data-active', 'false')
  const original = (await card.boundingBox())!
  await page.mouse.move(original.x + original.width * .88, original.y + original.height * .25)
  const rotation = () => card.evaluate(node => Number.parseFloat(node.style.getPropertyValue('--sy-holo-ry')) || 0)
  await expect.poll(rotation).toBeGreaterThan(5)
  expect((await card.boundingBox())!.width).toBe(original.width)
  await page.mouse.move(1, 1)
  await expect.poll(rotation).toBeCloseTo(0, 1)
  await page.getByRole('switch', { name: '互动' }).click()
  await expect(card).toHaveAttribute('data-active', 'false')
  await card.hover({ position: { x: 30, y: 30 } })
  expect(await rotation()).toBe(0)
})

test('suppresses motion and releases gestures when the user requests reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 720 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=WP.holo-card')
  const card = page.locator('.sy-holo-card[aria-label="品牌工作室成员证"]')
  await expect(card).toHaveAttribute('data-static', 'true')
  await expect(card).not.toHaveAttribute('data-tilt-on-touch')
  await card.hover({ position: { x: 36, y: 30 } })
  await expect(card.locator('.sy-holo-card__rotator')).toHaveCSS('transform', 'none')
  await page.getByRole('switch', { name: '换配色' }).click()
  await expect(card.locator('.review-holo__blocks')).toHaveAttribute('data-blue', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('holds the preview on a diagonal path and swaps cards without another delay', async ({ page }) => {
  await page.setViewportSize({ width: 1030, height: 720 })
  await page.goto('/?component=WP.hover-card')
  const lin = page.getByRole('button', { name: '林芷', exact: true })
  const chen = page.getByRole('button', { name: '陈明', exact: true })
  const panel = page.getByRole('dialog', { name: '林芷预览' })
  await lin.hover()
  await expect(panel).toBeVisible()
  const bounds = (await panel.boundingBox())!
  await page.mouse.move(bounds.x + 24, bounds.y + 35, { steps: 8 })
  await expect(panel.getByText('品牌资源库')).toBeVisible()
  await chen.hover()
  const other = page.getByRole('dialog', { name: '陈明预览' })
  await expect(other).toBeVisible()
  await expect(other).toHaveAttribute('data-warm', 'true')
  await expect(panel).toBeHidden()
  await page.mouse.move(1, 1)
  await expect(other).toBeHidden()
})

test('brings keyboard focus into a preview and restores it when dismissed or after an action', async ({ page }) => {
  await page.goto('/?component=WP.hover-card')
  const trigger = page.getByRole('button', { name: '林芷', exact: true })
  const panel = page.getByRole('dialog', { name: '林芷预览' })
  await trigger.focus()
  await expect(panel).toBeVisible()
  await trigger.press('Tab')
  await expect(panel.getByRole('button', { name: '查看项目' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.press('ArrowDown')
  await expect(panel.getByRole('button', { name: '查看项目' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(trigger).toBeFocused()
  await expect(page.locator('.review-hover__result')).toContainText('已打开品牌资源库')
})

test('moves a multi-selection between board columns and restores the task focus', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 750 })
  await page.goto('/?component=WP.kanban')
  const board = page.getByRole('region', { name: '品牌项目看板' })
  const queue = board.getByRole('grid', { name: '待处理' })
  const doing = board.getByRole('grid', { name: '进行中' })
  const first = queue.getByRole('row', { name: '修订状态文案' })
  const second = queue.getByRole('row', { name: '补齐项目说明' })
  await first.press('Space')
  await second.press('Space')
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await expect(second).toHaveAttribute('aria-selected', 'true')
  await first.press('ControlOrMeta+Enter')
  await page.keyboard.press('ArrowRight')
  await expect(doing.locator('.sy-kanban__drop')).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(doing.getByRole('row', { name: '修订状态文案' })).toBeFocused()
  await expect(doing.getByRole('row', { name: '补齐项目说明' })).toHaveAttribute('aria-selected', 'true')
  await expect(queue.getByText('暂无任务')).toBeVisible()
  await expect(page.locator('.review-kanban__result')).toContainText('已将 2 项移至进行中')
})

test('drags tasks across columns, keeps locked tasks static, and adds items on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 720 })
  await page.goto('/?component=WP.kanban')
  const board = page.getByRole('region', { name: '品牌项目看板' })
  const queue = board.getByRole('grid', { name: '待处理' })
  const doing = board.getByRole('grid', { name: '进行中' })
  await queue.getByRole('row', { name: '补齐项目说明' }).dragTo(doing, { targetPosition: { x: 25, y: 30 } })
  await expect(doing.getByRole('row', { name: '补齐项目说明' })).toBeVisible()
  const done = board.getByRole('grid', { name: '已完成' })
  const locked = done.getByRole('row', { name: '更新交付记录' })
  await expect(locked).toHaveAttribute('aria-disabled', 'true')
  await locked.press('ControlOrMeta+Enter')
  await expect(board.locator('.sy-kanban__drop')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 750 })
  await page.getByRole('switch', { name: '排列为单列' }).click()
  await expect(board).toHaveAttribute('data-layout', 'stack')
  const column = board.getByRole('region', { name: '待处理', exact: true })
  await column.getByRole('button', { name: '添加任务' }).click()
  await expect(queue.getByRole('row', { name: '新任务 1' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})
