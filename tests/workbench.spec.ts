import { expect, test } from '@playwright/test'

test('sorts projects, keeps cross-page selection, and filters to an empty result', async ({ page }) => {
  await page.goto('/')
  const table = page.getByRole('table', { name: '项目列表' })
  const region = page.getByRole('region', { name: '项目列表' })
  expect(await region.evaluate(el => el.scrollWidth)).toBe(await region.evaluate(el => el.clientWidth))
  const files = table.getByRole('columnheader', { name: '文件数' })
  await files.getByRole('button').click()
  await expect(files).toHaveAttribute('aria-sort', 'ascending')
  await expect(table.getByRole('row').nth(1)).toContainText('发布工具')

  await table.getByRole('checkbox', { name: '选择发布工具' }).check()
  await expect(table.getByRole('checkbox', { name: '选择本页全部项目' })).toHaveJSProperty('indeterminate', true)
  await page.getByRole('button', { name: '下一页' }).click()
  await table.getByRole('checkbox', { name: '选择品牌资源库' }).check()
  await expect(page.getByRole('button', { name: '下一页' })).toHaveAttribute('aria-disabled', 'true')

  await page.getByRole('button', { name: '上一页' }).click()
  await expect(table.getByRole('checkbox', { name: '选择发布工具' })).toBeChecked()
  await page.getByRole('textbox', { name: '查找' }).fill('不存在的项目')
  await expect(table.getByText('没有匹配的项目')).toBeVisible()
  await expect(page.getByRole('button', { name: '归档项目' })).toHaveAttribute('aria-disabled', 'true')
})

test('archives and restores a project, with animated loading and stable focus', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('checkbox', { name: '选择品牌资源库' }).check()
  const open = page.getByRole('button', { name: '归档项目' })
  await open.click()
  const dialog = page.getByRole('dialog', { name: '归档项目？' })
  const cancel = dialog.getByRole('button', { name: '取消' })
  const confirm = dialog.getByRole('button', { name: '归档项目' })
  await expect(cancel).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(confirm).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(open).toBeFocused()

  await open.click()
  await expect(dialog).toBeVisible()
  const panel = dialog.locator('.sy-dialog__panel')
  await panel.evaluate(el => Promise.allSettled(el.getAnimations().map(animation => animation.finished)))
  const before = await confirm.evaluate(el => [el.offsetWidth, el.offsetHeight])
  await confirm.click()
  await expect(confirm).toHaveAttribute('aria-busy', 'true')
  await expect(confirm).toBeFocused()
  expect(await confirm.evaluate(el => [el.offsetWidth, el.offsetHeight])).toEqual(before)
  await expect(dialog).toBeHidden()
  await expect(open).toBeFocused()
  await expect(page.getByRole('rowheader', { name: '品牌资源库' })).toHaveCount(0)

  await page.getByRole('checkbox', { name: '查看归档' }).check()
  await page.getByRole('checkbox', { name: '选择品牌资源库' }).check()
  await page.getByRole('button', { name: '恢复项目' }).click()
  await page.getByRole('dialog').getByRole('button', { name: '恢复项目' }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByRole('rowheader', { name: '品牌资源库' })).toHaveCount(0)
  await page.getByRole('checkbox', { name: '查看归档' }).uncheck()
  await expect(page.getByRole('rowheader', { name: '品牌资源库' })).toBeVisible()
})

test('keeps the table scroll local on a narrow display and supports reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 620 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('switch', { name: '深色' }).check()
  await expect(page.locator('.workbench')).toHaveAttribute('data-sy-theme', 'dark')
  const region = page.getByRole('region', { name: '项目列表' })
  expect(await region.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)

  await page.getByRole('checkbox', { name: '选择品牌资源库' }).check()
  await page.getByRole('button', { name: '归档项目' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.sy-dialog__panel')).toHaveCSS('transform', 'none')
  const bounds = await dialog.boundingBox()
  expect(bounds?.width).toBeLessThanOrEqual(280)
  expect(bounds?.x).toBeGreaterThanOrEqual(14)
  expect((bounds?.x ?? 0) + (bounds?.width ?? 0)).toBeLessThanOrEqual(306)
  await dialog.getByRole('button', { name: '取消' }).click()
  await expect(dialog).toBeHidden()
})

test('moves one focus frame between fields and supports keyboard select', async ({ page, browserName }) => {
  await page.goto('/')
  const search = page.getByRole('textbox', { name: '查找' })
  const select = page.getByRole('combobox', { name: '分类' })
  const focus = page.locator('.sy-focus-group')
  expect((await search.boundingBox())?.y).toBe((await select.boundingBox())?.y)
  await search.focus()
  await expect(focus).toHaveAttribute('data-active', '')
  const element = focus.locator('.sy-focus-group__ring')
  const first = await element.evaluate(el => el.getBoundingClientRect().left)
  await page.keyboard.press(browserName === 'webkit' && process.platform === 'darwin' ? 'Alt+Tab' : 'Tab')
  await expect(select).toBeFocused()
  await expect(focus).toHaveAttribute('data-moving', '')
  await element.evaluate(el => Promise.allSettled(el.getAnimations().map(animation => animation.finished)))
  expect(await element.evaluate(el => el.getBoundingClientRect().left)).toBeGreaterThan(first)

  await select.press('ArrowDown')
  const menu = page.getByRole('listbox')
  await expect(menu).toBeVisible()
  await expect(menu).toHaveCSS('border-top-width', '0px')
  await expect(menu.getByRole('option', { name: '全部分类' })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('option', { name: '设计' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(menu).toBeHidden()
  await expect(select).toBeFocused()
  await expect(select).toContainText('设计')
  await expect(page.getByRole('table', { name: '项目列表' }).getByRole('row')).toHaveCount(4)
  await expect(page.getByRole('rowheader', { name: '品牌资源库' })).toBeVisible()
  await expect(page.getByRole('rowheader', { name: '发布工具' })).toHaveCount(0)

  await select.press('ArrowDown')
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(select).toBeFocused()
})
