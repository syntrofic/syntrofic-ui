import { expect, test } from '@playwright/test'

test('layout glides combine two height changes and can settle immediately', async ({ page }) => {
  await page.goto('/?component=W.motion')
  const demo = page.getByRole('region', { name: '布局变化' })
  const row = demo.locator('[data-layout-trailing]')
  const before = await row.evaluate(node => node.getBoundingClientRect().top - node.parentElement!.getBoundingClientRect().top)
  const toggle = demo.getByRole('button', { name: '切换两处内容' })
  await toggle.press('Enter')
  await expect(demo.locator('output')).toHaveText('正在滑动')
  const snapshot = page.locator('[data-layout-swap-copy]')
  await expect(snapshot).toHaveAttribute('inert', '')
  await expect(snapshot).toHaveAttribute('aria-hidden', 'true')
  const edge = await demo.locator('[data-layout-swap-next]').evaluate(node => node.getAnimations()
    .flatMap(effect => (effect.effect as KeyframeEffect).getKeyframes())
    .filter(frame => frame.clipPath !== undefined))
  expect(edge.length).toBeGreaterThan(10)
  expect(edge.at(-1)?.clipPath).toBe('inset(0%)')
  const translations = await row.evaluate(node => node.getAnimations().flatMap(animation =>
    (animation.effect as KeyframeEffect).getKeyframes().filter(frame => frame.translate !== undefined).map(frame => String(frame.translate))))
  expect(translations.length).toBeGreaterThan(10)
  expect(parseFloat(translations[0].split(' ')[1])).toBeLessThan(-24)
  expect(translations.at(-1)).toMatch(/^0px(?: 0px)?$/)
  await demo.getByRole('button', { name: '完成移动' }).press('Enter')
  await expect(snapshot).toHaveCount(0)
  await expect(demo.locator('output')).toHaveText('已更新位置')
  const after = await row.evaluate(node => ({ y: node.getBoundingClientRect().top - node.parentElement!.getBoundingClientRect().top,
    effects: node.getAnimations().length }))
  expect(after.y - before).toBeGreaterThan(24)
  expect(after.effects).toBe(0)
})

test('layout changes respect reduced motion and preserve the trigger', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=W.motion')
  const demo = page.getByRole('region', { name: '布局变化' })
  const toggle = demo.getByRole('button', { name: '切换两处内容' })
  await toggle.press('Enter')
  await expect(demo.locator('output')).toHaveText('已更新位置')
  await expect(toggle).toBeFocused()
  await expect(page.locator('[data-layout-swap-copy]')).toHaveCount(0)
  expect(await demo.locator('[data-layout-trailing]').evaluate(node => node.getAnimations().length)).toBe(0)
})

test('layout capture excludes viewport movement caused only by a nested scroll', async ({ page }) => {
  await page.goto('/?component=W.motion')
  const demo = page.getByRole('region', { name: '布局变化' })
  const scroller = demo.locator('.layout-tools-review__scroller')
  const row = demo.locator('[data-layout-trailing]')
  const withinScroll = () => row.evaluate(node => node.getBoundingClientRect().top - node.closest('.layout-tools-review__scroller')!.getBoundingClientRect().top)
  const before = await withinScroll()
  await demo.getByRole('button', { name: '滚动列表' }).press('Enter')
  const movement = await scroller.evaluate(node => node.scrollTop)
  expect(movement).toBeGreaterThan(0)
  expect(await withinScroll()).toBeCloseTo(before - movement, 0)
  await expect(demo.locator('[data-scroll-result]')).toHaveText('仅滚动')
})

test('brand motion sets named springs and timing and respects reduced motion', async ({ page }) => {
  await page.goto('/?component=W.motion')
  const demo = page.getByRole('region', { name: '品牌动效' })
  const marker = demo.locator('[data-brand-motion-marker]')
  const trigger = demo.getByRole('button', { name: '播放品牌过渡' })
  await expect(trigger).toHaveCSS('background-color', 'rgb(224, 235, 225)')
  await expect(trigger).toHaveCSS('border-top-left-radius', '11px')
  await expect(demo.locator('[data-theme-demo-badge]')).toHaveCSS('color', 'rgb(66, 88, 73)')
  await expect(demo.getByRole('button', { name: '默认次级按钮' })).not.toHaveCSS('background-color', 'rgb(224, 235, 225)')
  await trigger.press('Enter')
  await expect(marker).toHaveAttribute('data-spring', '1,190,24')
  const settings = await marker.evaluate(node => node.getAnimations().map(animation => animation.effect!.getTiming()))
  expect(settings).toContainEqual(expect.objectContaining({ duration: 387.5, easing: 'cubic-bezier(0.18, 0.72, 0.29, 1)' }))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await trigger.press('Enter')
  await expect(marker).toHaveCSS('translate', '54px')
  expect(await marker.evaluate(node => parseFloat(getComputedStyle(node).getPropertyValue('--sy-motion-replace')))).toBe(0)
})
