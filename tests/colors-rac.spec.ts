import { expect, test } from '@playwright/test'

test('localization merges regional catalogs and switches calendars independently of the locale', async ({ page }) => {
  await page.goto('/?component=W.export.rac')
  const demo = page.getByRole('region', { name: '多语言目录示例' })
  const command = demo.getByRole('searchbox', { name: 'Trouver une commande' })
  await expect(command).toHaveAttribute('placeholder', 'Filtrer les commandes')
  await expect(demo.locator('[data-catalog-sample]')).toHaveAttribute('dir', 'ltr')
  const calendar = demo.getByRole('group', { name: '项目日期' })
  await expect(calendar).toHaveAttribute('data-calendar', 'gregory')
  await demo.getByRole('checkbox', { name: '切换至波斯语' }).check()
  await expect(demo.getByRole('searchbox', { name: 'Find commands' })).toHaveAttribute('placeholder', 'Filter commands')
  await expect(demo.locator('[data-catalog-sample]')).toHaveAttribute('dir', 'rtl')
  await expect(calendar).toHaveAttribute('data-calendar', 'gregory')
  await demo.getByRole('checkbox', { name: '使用波斯日历' }).check()
  await expect(calendar).toHaveAttribute('data-calendar', 'persian')
})

test('validates modern color formats, edits channels and submits a stable color value', async ({ page }) => {
  await page.goto('/?component=W.color-field')
  const field = page.getByRole('textbox', { name: '颜色代码' })
  const channel = page.getByRole('spinbutton', { name: '红色通道' })

  await field.fill('rgb(0 30% 200 / 50%)')
  await page.getByRole('button', { name: '保存色值' }).click()
  await expect(field).toHaveValue('#004DC880')
  await expect(page.getByText('已保存 #004DC880', { exact: true })).toBeVisible()
  await channel.press('ArrowUp')
  await expect(channel).toHaveAttribute('aria-valuenow', '1')

  const format = page.getByRole('combobox', { name: '颜色格式' })
  await format.click()
  await page.getByRole('option', { name: 'HSL', exact: true }).click()
  await expect(field).toHaveValue(/^hsla?\(/)
  await field.fill('rgb(1 2 3) invalid suffix')
  await channel.focus()
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('请输入有效的颜色值。')).toBeVisible()
  expect(await field.evaluate(input => (input as HTMLInputElement).validity.valid)).toBe(false)

  await field.fill('#af48')
  await page.getByRole('button', { name: '保存色值' }).click()
  await expect(page.getByText('已保存 #AAFF4488', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重置' }).click()
  await expect(field).toHaveValue('#859589')
  await expect(field).not.toHaveAttribute('aria-invalid')
})

test('edits both axes of the color area with keyboard and pointer input', async ({ page }) => {
  await page.goto('/?component=W.color-area')
  const area = page.getByRole('group', { name: '二维调色区' })
  const x = area.getByRole('slider', { name: '饱和度' })
  const y = area.getByRole('slider', { name: '亮度' })
  await x.press('End')
  await expect(x).toHaveValue('100')
  await x.press('Tab')
  await expect(y).toBeFocused()
  await y.press('Home')
  await expect(y).toHaveValue('0')

  const board = area.locator('.sy-color-area__board')
  const bounds = (await board.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width * .35, bounds.y + bounds.height * .5)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .63, bounds.y + bounds.height * .2, { steps: 4 })
  await page.mouse.up()
  expect(Number(await x.inputValue())).toBeCloseTo(63, 0)
  expect(Number(await y.inputValue())).toBeCloseTo(80, 0)
  await expect(board).not.toHaveAttribute('data-dragging')
})

test('keeps achromatic hue, alpha and palette selection synchronized in the narrow color picker', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/?component=W.color-picker')
  const trigger = page.getByRole('button', { name: '选择品牌色' })
  await trigger.click()
  const popup = page.getByRole('dialog', { name: '选择品牌色' })
  const code = popup.getByRole('textbox', { name: '颜色代码' })
  const hue = popup.getByRole('slider', { name: '色相' })
  await code.fill('hsv(180 0% 50%)')
  await code.press('Enter')
  await expect(hue).toHaveAttribute('aria-valuenow', '180')
  await hue.press('ArrowRight')
  await expect(hue).toHaveAttribute('aria-valuenow', '181')
  await popup.getByRole('slider', { name: '饱和度' }).press('End')
  await expect(code).toHaveValue('#007D80')
  const alpha = popup.getByRole('slider', { name: '不透明度' })
  await alpha.press('Home')
  await expect(alpha).toHaveAttribute('aria-valuetext', '0%')
  await expect(code).toHaveValue('#007D8000')

  await popup.getByRole('option', { name: '雾蓝' }).click()
  await expect(code).toHaveValue('#8D9FAE')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
  await code.press('Escape')
  await expect(popup).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('exposes swatch names, transparency, selection and field composition', async ({ page }) => {
  await page.goto('/?component=W.color-swatch')
  await expect(page.getByRole('img', { name: '半透明暖灰' })).toHaveAttribute('data-transparent')
  await expect(page.getByRole('img', { name: '无颜色' })).toHaveAttribute('data-empty')

  await page.goto('/?component=W.color-swatch-picker')
  const grid = page.getByRole('listbox', { name: '品牌色板' })
  const first = grid.getByRole('option', { name: '灰绿', exact: true })
  const second = grid.getByRole('option', { name: '雾蓝', exact: true })
  await expect(first).toHaveAttribute('aria-selected', 'true')
  await first.press('ArrowRight')
  await expect(second).toBeFocused()
  await second.press('Enter')
  await expect(second).toHaveAttribute('aria-selected', 'true')
  await expect(grid.getByRole('option', { name: '浅灰', exact: true })).toHaveAttribute('aria-disabled', 'true')

  await page.goto('/?component=W.export.color-input-group')
  const code = page.getByRole('textbox', { name: '自定义颜色' })
  await code.fill('broken')
  await expect(code).toHaveAttribute('aria-invalid', 'true')
  await code.fill('#8d9fae')
  await expect(code).not.toHaveAttribute('aria-invalid')
  await expect(page.locator('.sy-color-input-group')).toContainText('HEX')
})

test('runs the Vue helper entry through virtual lists, RTL, routing and interaction state', async ({ page }) => {
  await page.goto('/?component=W.export.rac')
  const viewport = page.getByRole('region', { name: '虚拟文档列表' })
  await expect(viewport).toHaveAttribute('tabindex', '0')
  await expect(viewport.getByText('品牌文档 1', { exact: true })).toBeVisible()
  await viewport.evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(viewport.getByText('品牌文档 120', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '加载更多文档' }).click()
  await expect(page.getByText('160 份文档', { exact: true })).toBeVisible()
  const query = page.getByRole('textbox', { name: '查找文档' })
  await query.fill('品牌文档 157')
  await expect(viewport.getByText('品牌文档 157', { exact: true })).toBeVisible()
  await query.clear()

  const key = page.getByRole('button', { name: '标记文档' })
  await key.press('Enter')
  await expect(key).toHaveAttribute('aria-pressed', 'true')
  await key.press('Space')
  await expect(key).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('link', { name: '打开文档详情' }).click()
  await expect(page.getByRole('status').filter({ hasText: '已打开文档详情' })).toBeVisible()
  expect(page.url()).toContain('component=W.export.rac')

  const overlay = page.getByRole('button', { name: '快捷面板', exact: true })
  await overlay.click()
  await page.getByRole('button', { name: '关闭快捷面板', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '快捷面板' })).toBeHidden()
  await expect(overlay).toBeFocused()
  await page.getByRole('button', { name: '文档说明' }).click()
  await page.getByRole('button', { name: '收起说明' }).click()
  await expect(page.getByRole('button', { name: '文档说明' })).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('button', { name: '文档说明' })).toBeFocused()

  await page.getByRole('switch', { name: '从右往左阅读' }).click()
  await expect(page.locator('[lang="ar"]')).toHaveAttribute('dir', 'rtl')
  await expect(viewport).toContainText('ملف')
})
