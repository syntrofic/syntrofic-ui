import { reviewHref, reviewItems } from '../preview/review-catalog'

test('opens each component example from its own responsive review URL', async ({ page }) => {
  test.setTimeout(Math.max(40_000, reviewItems.length * 1_000))
  const errors: string[] = []
  page.on('pageerror', error => errors.push(`${new URL(page.url()).search}: ${error.message}`))
  await page.setViewportSize({ width: 320, height: 680 })
  const contentReady: Record<string, string> = {
    'W.vega-chart': '.sy-vega-chart svg.marks',
    'W.sankey-chart': '.sy-sankey svg',
    'W.webgl-chart': '.sy-webgl-chart canvas',
    'W.code-editor': '.sy-code-editor textarea',
    'WP.rich-text-editor': '.sy-rich-text__editable[contenteditable="true"]',
    'WP.markdown': '.sy-markdown h2',
    'WP.code-block': '.sy-code-block pre code',
    'WP.map': '.sy-map[data-ready="true"] .sy-map__cluster',
  }
  for (const [id, label] of reviewItems) {
    await page.goto('/' + reviewHref(id), { waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: label, exact: true })).toBeVisible()
    const sample = page.getByRole('region', { name: '组件示例' })
    await expect.poll(() => sample.locator(':scope > *').count(), { message: id }).toBeGreaterThan(0)
    if (contentReady[id]) await expect(sample.locator(contentReady[id]).first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth), id).toBe(320)
  }
  expect(errors).toEqual([])
})

