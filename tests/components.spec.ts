  expect(await tracks()).toEqual(before)
  await expect(table.locator('tbody .sy-table__row-index')).toHaveText(['7', '8', '9'])
  await expect(top.getByRole('button', { name: '下一页' })).toBeDisabled()
  await expect(bottom.getByRole('button', { name: '下一页' })).toBeDisabled()
  await example.getByRole('checkbox', { name: '显示归档总数' }).check()
