test('table column resize previews the neighbor and commits controls in both directions', async ({ page }) => {
  await page.goto('/?component=W.table')
  await page.getByRole('button', { name: '加载更多的表格' }).click()
  const sample = page.getByRole('region', { name: '列宽调整示例' })
  const table = sample.getByRole('table', { name: '可调列宽资料' })
  const titleGrip = table.getByRole('separator', { name: '调整列宽 · 名称' })
  const version = table.locator('[data-resize-column="revision"]')
  const heading = table.locator('[data-resize-column="title"]')
  await expect(titleGrip).toHaveAttribute('aria-valuenow', '140')
  await expect(table.getByRole('separator', { name: '调整列宽 · 状态' })).toHaveCount(0)
  await titleGrip.evaluate(async element => {
    const animations = element.closest('.sy-disclosure__content')?.getAnimations() ?? []
    await Promise.allSettled(animations.map(animation => animation.finished))
    element.scrollIntoView({ block: 'center', behavior: 'instant' })
  })
  await expect.poll(() => titleGrip.evaluate(element => {
    const edge = element.getBoundingClientRect()
    return element.contains(element.ownerDocument.elementFromPoint(edge.x + edge.width / 2, edge.y + edge.height / 2))
  })).toBe(true)
  const neighborWidth = (await version.boundingBox())!.width
  const tableWidth = (await table.boundingBox())!.width
  const box = (await titleGrip.boundingBox())!
  expect(box.width).toBeCloseTo(16, 0)
  const x = box.x + 2
  const y = box.y + box.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 32, y, { steps: 4 })
  await expect(titleGrip).toHaveAttribute('aria-valuenow', '172')
  await expect(sample).toContainText('已保存 0 次列宽')
  await page.mouse.up()
  await expect(sample).toContainText('已保存 1 次列宽')
  await expect.poll(async () => Math.round((await heading.boundingBox())!.width)).toBe(172)
  expect(Math.abs((await version.boundingBox())!.width - (neighborWidth - 32))).toBeLessThan(2)
  expect(Math.abs((await table.boundingBox())!.width - tableWidth)).toBeLessThan(2)

  await titleGrip.press('ArrowRight')
  await expect(titleGrip).toHaveAttribute('aria-valuenow', '180')
  await titleGrip.press('Escape')
  await expect(titleGrip).toHaveAttribute('aria-valuenow', '172')
  await expect(sample).toContainText('已保存 1 次列宽')
  await sample.getByRole('checkbox', { name: '从右向左布局' }).check()
  await titleGrip.press('ArrowLeft')
  await expect(titleGrip).toHaveAttribute('aria-valuenow', '180')
  await titleGrip.press('Enter')
  await expect(sample).toContainText('已保存 2 次列宽')
})

