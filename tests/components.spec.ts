  const bottom = example.getByRole('navigation', { name: '归档分页（底部）' })
  const table = example.getByRole('table', { name: '归档记录' })
  const tracks = () => table.locator('thead tr').evaluate(row =>
    Array.from((row as HTMLTableRowElement).cells, cell => cell.getBoundingClientRect().width))
  await expect(top.locator('..')).toHaveAttribute('data-align', 'start')
  expect(await top.evaluate(node => Math.abs(node.getBoundingClientRect().left - node.parentElement!.getBoundingClientRect().left))).toBeLessThan(1)
  await expect(table.getByRole('rowheader')).toHaveText(['归档记录 1', '归档记录 2', '归档记录 3'])
  const before = await tracks()
  await top.getByRole('button', { name: '下一页' }).click()
  await expect(table.getByRole('rowheader')).toHaveText(['归档记录 4', '归档记录 5', '归档记录 6'])
  expect(await tracks()).toEqual(before)
