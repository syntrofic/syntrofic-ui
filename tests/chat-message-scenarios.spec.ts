import { expect, test } from '@playwright/test'

test('consecutive bubbles keep logical grouping, an independent ghost surface, and animated density', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?component=WP.chat-message')
  const sample = page.getByRole('region', { name: '连续气泡与回执' })
  const log = sample.getByRole('log', { name: '发布对话气泡' })
  const user = log.getByRole('article', { name: '发布同事' })
  const bubbles = user.locator('.sy-chat-message-bubble')
  await expect(bubbles).toHaveCount(3)
  await expect(bubbles.nth(0)).toHaveAttribute('data-group', 'first')
  await expect(bubbles.nth(1)).toHaveAttribute('data-group', 'middle')
  await expect(bubbles.nth(2)).toHaveAttribute('data-group', 'last')
  const shape = () => bubbles.nth(1).evaluate(node => {
    const style = getComputedStyle(node)
    return [parseFloat(style.borderTopLeftRadius), parseFloat(style.borderTopRightRadius)]
  })
  await expect.poll(async () => { const [left, right] = await shape(); return left - right }).toBeGreaterThan(0)
  await log.evaluate(node => node.setAttribute('dir', 'rtl'))
  await expect.poll(async () => { const [left, right] = await shape(); return right - left }).toBeGreaterThan(0)
  const ghost = log.getByRole('article', { name: '校对助手' }).locator('.sy-chat-message-bubble[data-variant="ghost"]')
  await expect(ghost).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(ghost).toContainText('两份发布说明已校对')
  await sample.getByRole('button', { name: '宽松气泡' }).press('Enter')
  await expect(bubbles.first()).toHaveCSS('padding-block-start', '9px')
  await sample.getByRole('button', { name: '紧凑气泡' }).press('Enter')
  await expect(bubbles.first()).toHaveCSS('padding-block-start', '4px')
  expect(await log.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
})

test('message receipts expose changes to time and delivery while footer actions remain keyboard accessible', async ({ page }) => {
  await page.goto('/?component=WP.chat-message')
  const sample = page.getByRole('region', { name: '连续气泡与回执' })
  const user = sample.getByRole('article', { name: '发布同事' })
  const receipt = user.locator('.sy-chat-metadata [data-status]')
  const button = sample.getByRole('button', { name: '推进发送回执' })
  await expect(receipt).toHaveAttribute('data-status', 'sending')
  await expect(receipt.locator('.sy-chat-metadata__icon')).toHaveCSS('animation-name', 'sy-chat-pulse')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(receipt.locator('.sy-chat-metadata__icon')).toHaveCSS('animation-name', 'none')
  for (const [index, [state, text]] of [['sent', '已发送'], ['delivered', '已送达'], ['read', '已读'], ['error', '发送失败']].entries()) {
    await button.press('Enter')
    await expect(receipt).toHaveAttribute('data-status', state)
    await expect(receipt.locator('.sy-visually-hidden')).toHaveText(text)
    await expect(user.locator('time')).toHaveAttribute('datetime', `2026-11-22T14:${27 + index}:00+08:00`)
  }
  const toolbar = sample.getByRole('group', { name: '校对摘要操作' })
  const refresh = toolbar.getByRole('button', { name: '重新核对' })
  await refresh.press('Enter')
  await expect(refresh).toBeFocused()
  await expect(sample.getByRole('status', { name: '摘要操作结果' }).locator('.sy-visually-hidden')).toHaveText('已更新校对摘要')
  const like = toolbar.getByRole('button', { name: '摘要有用' })
  await like.press('Space')
  await expect(like).toHaveAttribute('aria-pressed', 'true')
})

test('system dividers are named and mentions use the longest match and keep their theme colors', async ({ page }) => {
  await page.goto('/?component=WP.chat-message')
  const sample = page.getByRole('region', { name: '系统消息与彩色引用' })
  await expect(sample.getByRole('separator', { name: '11 月 22 日' })).toBeAttached()
  await expect(sample.getByRole('separator', { name: '复核记录' })).toBeAttached()
  await expect(sample.locator('.sy-chat-system-message__icon .sy-avatar')).toBeVisible()
  const update = sample.locator('.sy-chat-system-message__text [aria-live="polite"]')
  await expect(update).toHaveText('发布负责人已加入对话')
  await sample.getByRole('button', { name: '下一条发布事件' }).press('Enter')
  await expect(update).toHaveText('交付目录已设为只读')
  await sample.getByRole('button', { name: '下一条发布事件' }).press('Enter')
  await expect(update).toHaveText('发布记录已归档')
  const badges = sample.getByRole('article', { name: '发布记录' }).locator('.sy-badge')
  await expect(badges).toHaveText(['校对组', '校对', '发布范围', '核对状态'])
  await expect(badges.first()).toHaveAttribute('data-tone', 'blue')
  const status = badges.last()
  await expect(status).toHaveAttribute('data-tone', 'red')
  const red = await status.evaluate(node => getComputedStyle(node).color)
  await sample.getByRole('switch', { name: '引用已核对' }).click()
  await expect(status).toHaveAttribute('data-tone', 'green')
  await expect.poll(() => status.evaluate(node => getComputedStyle(node).color)).not.toBe(red)
})

