test('tool calls account for every state and preserve expanded results when the group is folded', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 840 })
  await page.goto('/?component=WP.chat-tool')
  const sample = page.getByRole('region', { name: '工具记录与结果详情' })
  const group = sample.getByRole('list', { name: '本次工具调用' })
  await expect(group.getByRole('listitem')).toHaveCount(5)
  const build = group.locator('[data-call="build"] .sy-chat-call__summary')
  await expect(build).toHaveAttribute('data-status', 'pending')
  const step = sample.getByRole('button', { name: '推进构建状态' })
  await step.press('Enter')
  await expect(build).toHaveAttribute('data-status', 'running')
  await expect(build.locator('.sy-chat-loader__dots > i')).toHaveCount(3)
  await step.press('Enter')
  await expect(build).toHaveAttribute('data-status', 'complete')
  await expect(build.locator('.sy-visually-hidden').filter({ hasText: '1.8 s' })).toHaveCount(1)
  await step.press('Enter')
  await expect(build).toHaveAttribute('data-status', 'error')
  await expect(group.locator('[data-call="build"] .sy-chat-call__error .sy-visually-hidden')).toHaveText('草稿缺少发布标题，补齐后可重试。')

  const edit = group.getByRole('button', { name: /日期格式更新/ })
  await expect(edit).toHaveAccessibleName(/发布工作区/)
  await expect(edit.locator('[data-stat="add"] .sy-visually-hidden')).toHaveText('+4')
  await expect(edit.locator('[data-stat="remove"] .sy-visually-hidden')).toHaveText('−1')
  await edit.press('Enter')
  await expect(edit).toHaveAttribute('aria-expanded', 'true')
  await expect(group.locator('.sy-diff-viewer')).toContainText('export const formatDay')
  const report = group.getByRole('button', { name: /检查发布记录/ })
  await report.press('Enter')
  await expect(group.getByRole('button', { name: '复制检查输出' })).toBeVisible()
  const toggle = sample.getByRole('button', { name: /本次工具调用/ })
  await toggle.press('Enter')
  await expect(group).toHaveCount(0)
  await toggle.press('Enter')
  await expect(edit).toHaveAttribute('aria-expanded', 'true')
  await expect(report).toHaveAttribute('aria-expanded', 'true')
  const earlier = sample.getByRole('button', { name: /之前的工具调用/ })
  await expect(earlier).toHaveAttribute('aria-expanded', 'false')
  await earlier.press('Enter')
  await expect(sample.getByRole('list', { name: '之前的工具调用' }).getByRole('listitem')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)
})
