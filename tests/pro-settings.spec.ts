import { expect, test } from '@playwright/test'

test('keeps color changes provisional until applied and returns focus on dismissal', async ({ page }) => {
  await page.goto('/?component=WP.cell-color-picker')
  const row = page.getByRole('button', { name: '品牌主题色', exact: true })
  await expect(row).toHaveAccessibleDescription('#718373')
  await row.press('Enter')
  const panel = page.getByRole('dialog')
  const code = panel.getByRole('textbox', { name: '颜色代码' })
  await expect(code).toHaveValue('#718373')
  await panel.getByRole('option', { name: '雾蓝' }).click()
  await expect(code).toHaveValue('#8193A5')
  await expect(row).toHaveAccessibleDescription('#718373')
  await code.press('Escape')
  await expect(panel).toBeHidden()
  await expect(row).toBeFocused()

  await row.click()
  await expect(code).toHaveValue('#718373')
  await code.fill('invalid')
  await panel.getByRole('button', { name: '应用颜色' }).click()
  await expect(code).toHaveAttribute('aria-invalid', 'true')
  await expect(panel).toBeVisible()
  await code.fill('#A18579')
  await code.press('Enter')
  await expect(panel).toBeHidden()
  await expect(row).toBeFocused()
  await expect(row).toHaveAccessibleDescription('#A18579')

  await row.click()
  await panel.getByRole('option', { name: '灰紫' }).click()
  await panel.getByRole('button', { name: '取消颜色修改' }).press('Enter')
  await expect(panel).toBeHidden()
  await expect(row).toHaveAccessibleDescription('#A18579')
  await expect(page.getByRole('button', { name: '归档标记' })).toBeDisabled()
})

test('selects table-cell options with Enter, cancels with Escape and preserves width', async ({ page }) => {
  await page.goto('/?component=WP.cell-select')
  const row = page.getByRole('combobox', { name: '界面语言' })
  await expect(row).toContainText('简体中文')
  const width = (await row.boundingBox())!.width
  await row.press('Enter')
  const list = page.getByRole('listbox')
  await expect(list.getByRole('option', { name: 'Français' })).toBeDisabled()
  await list.getByRole('option', { name: 'English' }).press('Escape')
  await expect(list).toBeHidden()
  await expect(row).toHaveText(/简体中文/)
  await expect(row).toBeFocused()
  await row.press('Enter')
  await list.getByRole('option', { name: 'English' }).press('Enter')
  await expect(list).toBeHidden()
  await expect(row).toContainText('English')
  await expect(row).toBeFocused()
  expect((await row.boundingBox())!.width).toBe(width)
})

test('adjusts bounded cell sliders with pointer and keys', async ({ page }) => {
  await page.goto('/?component=WP.cell-slider')
  const volume = page.getByRole('slider', { name: '提醒音量' })
  await expect(volume).toHaveAttribute('aria-valuenow', '65')
  await volume.press('ArrowRight')
  await expect(volume).toHaveAttribute('aria-valuenow', '70')
  await volume.press('End')
  await volume.press('ArrowRight')
  await expect(volume).toHaveAttribute('aria-valuenow', '100')
  const slider = volume.locator('xpath=ancestor::*[contains(@class, "sy-cell-slider")]').locator('.sy-slider__track')
  const runway = (await slider.boundingBox())!
  await slider.click({ position: { x: runway.width * .4, y: 4 } })
  await expect(volume).toHaveAttribute('aria-valuenow', '40')
  await expect(page.getByRole('slider', { name: '管理员音量' })).toHaveAttribute('aria-disabled', 'true')
})

test('clicks the full cell switch row, exposes its description and resets selections', async ({ page }) => {
  await page.goto('/?component=WP.cell-switch')
  const reminders = page.getByRole('switch', { name: '到期提醒' })
  const report = page.getByRole('switch', { name: '每周简报' })
  await expect(reminders).toBeChecked()
  await expect(reminders).toHaveAccessibleDescription('在任务到期前发送通知。')
  const cell = (await reminders.boundingBox())!
  await page.mouse.click(cell.x + 8, cell.y + cell.height / 2)
  await expect(reminders).not.toBeChecked()
  await expect(reminders).toBeFocused()
  await report.press('Space')
  await expect(report).toBeChecked()
  await expect(page.getByRole('switch', { name: '账户安全通知' })).toBeDisabled()
  await page.getByRole('button', { name: '恢复通知设置' }).click()
  await expect(reminders).toBeChecked()
  await expect(report).not.toBeChecked()
})

test('keeps inline single and multiple selections in sentence flow', async ({ page }) => {
  await page.goto('/?component=WP.inline-select')
  const cadence = page.getByRole('combobox', { name: '发送频率' })
  const sentence = cadence.locator('xpath=ancestor::p')
  await expect(sentence).toContainText('摘要按')
  const initial = await cadence.boundingBox()
  await cadence.press('Enter')
  await page.getByRole('option', { name: '每周一次' }).click()
  await expect(cadence).toContainText('每周一次')
  expect((await cadence.boundingBox())!.width).toBe(initial!.width)
  const topics = page.getByRole('combobox', { name: '包含主题' })
  await topics.press('Enter')
  await page.getByRole('option', { name: '产品' }).click()
  await expect(page.getByRole('option', { name: '产品' })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Escape')
  await expect(topics).toBeFocused()
  await expect(topics).toContainText(/设计.*产品/)
})

test('submits and resets a native select, keeping disabled options and required validation', async ({ page }) => {
  await page.goto('/?component=WP.native-select')
  const language = page.getByLabel('首选语言')
  const zone = page.getByLabel('工作时区')
  await expect(language).toHaveAccessibleDescription('语言列表由系统选择控件打开。')
  await expect(language.locator('option', { hasText: 'Français' })).toBeDisabled()
  await expect(page.getByLabel('历史语言')).toBeDisabled()
  await page.getByRole('button', { name: '保存偏好' }).click()
  await expect(zone).toHaveAttribute('aria-invalid', 'true')
  await expect(zone).toHaveAccessibleDescription('请选择时区。')
  await language.selectOption('en')
  await zone.selectOption('UTC+08:00')
  await expect(zone).not.toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: '保存偏好' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已保存 English · UTC+08:00')
  await page.getByRole('button', { name: '重置偏好' }).click()
  await expect(language).toHaveValue('zh')
  await expect(zone).toHaveValue('')
})
