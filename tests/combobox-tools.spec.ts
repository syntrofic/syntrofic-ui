import { expect, test, type Locator } from '@playwright/test'

async function expectActive(trigger: Locator, item: Locator) {
  await expect(trigger).toHaveAttribute('aria-activedescendant', (await item.getAttribute('id'))!)
  await expect(trigger).toBeFocused()
}

test('the headless editable combobox wraps, skips disabled entries and preserves the field focus', async ({ page }) => {
  await page.goto('/?component=W.combo-box')
  await page.getByRole('button', { name: '查找文件' }).click()
  const dialog = page.getByRole('dialog', { name: '选择文件' })
  const input = dialog.getByRole('combobox', { name: '文件名' })
  const list = dialog.getByRole('listbox', { name: '匹配的文件' })
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.press('ArrowDown')
  await expect(input).toHaveAttribute('aria-controls', (await list.getAttribute('id'))!)
  await expectActive(input, list.getByRole('option', { name: '品牌手册' }))
  await input.press('ArrowUp')
  await expectActive(input, list.getByRole('option', { name: '颜色令牌' }))
  await input.press('ArrowDown')
  await input.press('ArrowDown')
  await expectActive(input, list.getByRole('option', { name: '版式网格' }))
  await input.press('Enter')
  const result = dialog.getByLabel('文件操作结果').locator('.sy-visually-hidden')
  await expect(result).toHaveText('版式网格')
  await expect(list).toBeHidden()

  await input.press('ArrowDown')
  const token = list.getByRole('option', { name: '颜色令牌' })
  await token.hover()
  await expectActive(input, token)
  await token.click()
  await expect(input).toBeFocused()
  await expect(result).toHaveText('颜色令牌')
})

test('empty and composing comboboxes keep native field commands and dismiss the nested list first', async ({ page }) => {
  await page.goto('/?component=W.combo-box')
  await page.getByRole('button', { name: '查找文件' }).click()
  const dialog = page.getByRole('dialog', { name: '选择文件' })
  const input = dialog.getByRole('combobox', { name: '文件名' })
  const empty = dialog.locator('p').filter({ hasText: '没有匹配的文件' })
  await input.fill('没有这个名字')
  await expect(empty).toBeVisible()
  await expect(dialog.getByRole('status').filter({ hasText: '没有匹配的文件' })).toBeAttached()
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  expect(await input.getAttribute('aria-controls')).toBeNull()
  expect(await input.getAttribute('aria-activedescendant')).toBeNull()
  expect(await input.evaluate(node => node.dispatchEvent(new KeyboardEvent('keydown', {
    key: 'Home', bubbles: true, cancelable: true,
  })))).toBe(true)
  await input.press('Shift+Enter')
  await expect(dialog.getByLabel('文件操作结果').locator('.sy-visually-hidden')).toHaveText('保留查询')
  await input.evaluate(node => {
    const event = new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true })
    Object.defineProperty(event, 'isComposing', { value: true })
    node.dispatchEvent(event)
  })
  await expect(empty).toBeVisible()
  await input.press('Alt+Escape')
  await expect(empty).toBeHidden()
  await expect(dialog).toBeVisible()
  await input.press('Escape')
  await expect(dialog).toBeHidden()
})

test('the headless multi-combobox activates RTL grid actions independently of selection', async ({ page }) => {
  await page.goto('/?component=W.select')
  const review = page.getByRole('region', { name: '自定义多选网格' })
  await review.getByRole('switch', { name: '从右向左' }).click()
  const trigger = review.getByRole('combobox', { name: '选择资源' })
  const grid = review.getByRole('grid', { name: '资源选择' })
  const brand = grid.getByRole('gridcell', { name: '品牌手册', exact: true })
  const archive = grid.getByRole('gridcell', { name: '归档模板', exact: true })
  const layout = grid.getByRole('gridcell', { name: '版式网格', exact: true })
  await trigger.press('ArrowDown')
  await expectActive(trigger, brand)
  await trigger.press('Space')
  await expect(brand.locator('..')).toHaveAttribute('aria-selected', 'true')
  await trigger.press('ArrowDown')
  await expectActive(trigger, layout)
  await trigger.press('ArrowLeft')
  await expectActive(trigger, grid.getByRole('gridcell', { name: '查看版式网格' }))
  await trigger.press('Enter')
  const result = review.getByLabel('资源操作结果').locator('.sy-visually-hidden')
  await expect(result).toHaveText('查看版式网格')
  await expect(layout.locator('..')).toHaveAttribute('aria-selected', 'false')
  await trigger.press('ArrowRight')
  await expectActive(trigger, layout)
  await trigger.press('Enter')
  await expect(layout.locator('..')).toHaveAttribute('aria-selected', 'true')
  await expect(grid).toBeVisible()
  await expect(archive).toHaveAttribute('aria-disabled', 'true')
  const archiveAction = grid.getByRole('gridcell', { name: '查看归档模板' })
  await archiveAction.hover()
  await expectActive(trigger, archiveAction)
  await trigger.press('Enter')
  await expect(result).toHaveText('查看归档模板')
  await trigger.press('Escape')
  await expect(grid).toBeHidden()
  await trigger.press('Backspace')
  await expect(trigger).toHaveText('选择资源')
  await trigger.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: '颜', bubbles: true, cancelable: true })))
  await expectActive(trigger, grid.getByRole('gridcell', { name: '颜色令牌', exact: true }))
})
