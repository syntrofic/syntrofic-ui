import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect((await page.pageErrors()).map(error => error.message)).toEqual([])
})

test('retains a moving selection indicator across keyboard choices, form submission and reset', async ({ page }) => {
  await page.goto('/?component=WP.segment')
  const group = page.getByRole('group', { name: '统计范围' })
  const week = group.getByRole('button', { name: '最近一周' })
  const month = group.getByRole('button', { name: '本月' })
  const indicator = group.locator('.sy-segment__indicator')
  await expect(week).toHaveAttribute('aria-pressed', 'true')
  await expect(group).toHaveAttribute('data-indicator', '')
  const indicatorNode = await indicator.elementHandle()
  const x = await group.evaluate(rail => (rail as HTMLElement).style.getPropertyValue('--sy-segment-x'))
  const width = (await group.boundingBox())!.width
  await week.press('ArrowRight')
  await expect(month).toBeFocused()
  await expect(week).toHaveAttribute('aria-pressed', 'true')
  await month.press('Space')
  await expect(month).toHaveAttribute('aria-pressed', 'true')
  expect(await group.evaluate(rail => (rail as HTMLElement).style.getPropertyValue('--sy-segment-x'))).not.toBe(x)
  expect(await indicatorNode?.evaluate(node => node === node.parentElement?.querySelector('.sy-segment__indicator'))).toBe(true)
  expect((await group.boundingBox())!.width).toBeCloseTo(width, 1)
  await expect(group.getByRole('button', { name: '本年度' })).toBeDisabled()
  await month.press('ArrowRight')
  await expect(group.getByRole('button', { name: '今天' })).toBeFocused()
  await page.getByRole('button', { name: '保存统计范围' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已保存范围 · 本月')
  await page.getByRole('button', { name: '恢复默认' }).click()
  await expect(week).toHaveAttribute('aria-pressed', 'true')

  const filter = page.getByRole('group', { name: '状态筛选' })
  const draft = filter.getByRole('button', { name: '草稿' })
  await expect(filter).not.toHaveAttribute('data-indicator', '')
  await draft.click()
  await expect(draft).toHaveAttribute('aria-pressed', 'true')
  await expect(filter).toHaveAttribute('data-indicator', '')
  await draft.click()
  await expect(draft).toHaveAttribute('aria-pressed', 'false')
  await expect(filter).not.toHaveAttribute('data-indicator', '')
  await expect(filter.locator('.sy-segment__indicator')).toHaveCSS('opacity', '0')
})

test('dragging the active segment previews its neighbour and updates selection only on release', async ({ page }) => {
  await page.goto('/?component=WP.segment')
  const group = page.getByRole('group', { name: '统计范围' })
  const week = group.getByRole('button', { name: '最近一周' })
  const month = group.getByRole('button', { name: '本月' })
  const first = (await week.boundingBox())!
  const target = (await month.boundingBox())!
  const y = first.y + first.height / 2
  await page.mouse.move(first.x + first.width / 2, y)
  await page.mouse.down()
  await expect(group).toHaveAttribute('data-lifted', 'true')
  await page.mouse.move(target.x + target.width / 2, y, { steps: 6 })
  await expect(month).toHaveAttribute('data-preview-selected', 'true')
  await expect(week).toHaveAttribute('aria-pressed', 'true')
  await page.mouse.up()
  await expect(month).toHaveAttribute('aria-pressed', 'true')
  await expect(group).not.toHaveAttribute('data-dragging')
})

test('moves between reachable steps and exposes current, completed and partial progress states', async ({ page }) => {
  await page.goto('/?component=WP.stepper')
  const list = page.getByRole('list', { name: '发布流程' })
  const details = list.getByRole('button', { name: '资料' })
  const access = list.getByRole('button', { name: '权限' })
  const review = list.getByRole('button', { name: '确认' })
  const release = list.getByRole('button', { name: '发布' })
  await expect(access).toHaveAttribute('aria-current', 'step')
  await expect(details).toHaveAccessibleDescription(/已完成/)
  await expect(review).toBeDisabled()
  await access.press('ArrowLeft')
  await expect(details).toBeFocused()
  await expect(access).toHaveAttribute('aria-current', 'step')
  await details.press('Enter')
  await expect(details).toHaveAttribute('aria-current', 'step')
  const previous = page.getByRole('button', { name: '上一步' })
  const next = page.getByRole('button', { name: '下一步' })
  await expect(previous).toBeDisabled()
  await next.click()
  await next.click()
  await expect(review).toHaveAttribute('aria-current', 'step')
  await expect(release).toBeDisabled()
  await next.click()
  await expect(release).toHaveAttribute('aria-current', 'step')
  await expect(next).toBeDisabled()
  await access.click()
  await expect(access).toHaveAttribute('aria-current', 'step')
  await expect(release).toBeEnabled()
  const tracking = page.getByRole('list', { name: '交付记录' })
  await expect(tracking.getByRole('button')).toHaveCount(0)
  await expect(tracking.locator('[data-status="current"] .sy-stepper__connector')).toHaveAttribute('style', /0\.42/)
})

test('opens a context menu by pointer, changes checkbox and radio items and follows a submenu', async ({ page }) => {
  await page.goto('/?component=WP.context-menu')
  const trigger = page.locator('[data-sy-context-trigger][aria-label="品牌资源库"]')
  await trigger.click({ button: 'right', position: { x: 24, y: 12 } })
  const menu = page.getByRole('menu', { name: '文件操作' })
  await expect(menu).toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  const pin = menu.getByRole('menuitemcheckbox', { name: '固定到顶部' })
  await expect(pin).toHaveAttribute('aria-checked', 'true')
  await pin.click()
  await expect(pin).toHaveAttribute('aria-checked', 'false')
  const complete = menu.getByRole('menuitemradio', { name: '完整内容' })
  await complete.click()
  await expect(complete).toHaveAttribute('aria-checked', 'true')
  await expect(menu.getByRole('menuitemradio', { name: '摘要' })).toHaveAttribute('aria-checked', 'false')
  await menu.getByRole('menuitem', { name: '移动到' }).press('ArrowRight')
  await expect(page.getByRole('menuitem', { name: '受限目录' })).toBeDisabled()
  await page.getByRole('menuitem', { name: '团队目录' }).press('Enter')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已移动到团队目录')
})

test('restores focus after keyboard and controlled menus and keeps the disabled area closed', async ({ page }) => {
  await page.goto('/?component=WP.context-menu')
  const trigger = page.locator('[data-sy-context-trigger][aria-label="品牌资源库"]')
  const menu = page.getByRole('menu', { name: '文件操作' })
  await trigger.press('Shift+F10')
  await expect(menu.getByRole('menuitem', { name: '打开详情' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.press('Control+Enter')
  await expect(menu).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await page.getByRole('button', { name: '打开文件操作' }).click()
  await expect(menu).toBeVisible()
  await menu.getByRole('menuitem', { name: '打开详情' }).click()
  await expect(trigger).toBeFocused()
  await page.getByRole('group', { name: '交付历史' }).click({ button: 'right' })
  await expect(menu).toBeHidden()
})

test('opens on a stationary touch hold and cancels a moving touch', async ({ page }) => {
  await page.goto('/?component=WP.context-menu')
  const trigger = page.locator('[data-sy-context-trigger][aria-label="品牌资源库"]')
  const menu = page.getByRole('menu', { name: '文件操作' })
  const touch = { pointerType: 'touch', pointerId: 11, isPrimary: true, button: 0, clientX: 140, clientY: 120 }
  await trigger.dispatchEvent('pointerdown', touch)
  await trigger.dispatchEvent('pointermove', { ...touch, clientY: 160 })
  await page.waitForTimeout(550)
  await expect(menu).toBeHidden()
  await trigger.dispatchEvent('pointerup', touch)
  await trigger.dispatchEvent('pointerdown', { ...touch, pointerId: 12 })
  await expect(menu).toBeVisible()
  await trigger.dispatchEvent('pointerup', { ...touch, pointerId: 12 })
  await page.keyboard.press('Escape')
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
})
