import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect(await page.pageErrors()).toEqual([])
})

test('sorts, expands and edits grid rows with the keyboard and resizes columns', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 790 })
  await page.goto('/?component=WP.data-grid')
  const grid = page.getByRole('treegrid', { name: '项目资料网格' })
  const brand = grid.getByRole('rowheader', { name: /品牌交付/ }).locator('..')
  const owner = brand.locator('[id$="-owner"]')
  await expect(grid.getByRole('rowheader', { name: '品牌手册' })).toBeVisible()
  await grid.getByRole('button', { name: '收起品牌交付' }).click()
  await expect(grid.getByRole('rowheader', { name: '品牌手册' })).toHaveCount(0)
  await brand.getByRole('rowheader').press('Enter')
  await expect(grid.getByRole('rowheader', { name: '品牌手册' })).toBeVisible()

  await owner.press('F2')
  const editor = brand.getByRole('textbox', { name: '负责人' })
  await expect(editor).toBeFocused()
  await editor.fill('许澄')
  await editor.press('Enter')
  await expect(owner).toBeFocused()
  await expect(owner).toHaveAccessibleName('许澄')
  await owner.press('Enter')
  await editor.fill('未提交')
  await editor.press('Escape')
  await expect(owner).toHaveAccessibleName('许澄')

  await grid.evaluate(root => {
    const animate = HTMLElement.prototype.animate
    HTMLElement.prototype.animate = function (frames, options) {
      if (this.tagName === 'TR' && root.contains(this) && Array.isArray(frames) && frames.some(frame => frame?.translate)) {
        root.setAttribute('data-test-grid-row-motion', 'true')
      }
      return animate.call(this, frames, options)
    }
  })
  const pages = grid.getByRole('columnheader', { name: /页数/ })
  await pages.getByRole('button', { name: '页数' }).click()
  await expect(pages).toHaveAttribute('aria-sort', 'ascending')
  await expect(grid.getByRole('rowheader').first()).toHaveAccessibleName('评审记录')
  await expect(grid).toHaveAttribute('data-test-grid-row-motion', 'true')
  const handle = grid.getByRole('separator', { name: '调整资料宽度' })
  await expect(handle).toHaveAttribute('aria-valuenow', '137')
  await handle.scrollIntoViewIfNeeded()
  const area = (await handle.locator('.sy-shell-resize__grab').boundingBox())!
  expect(area.width).toBeCloseTo(16, 0)
  const x = area.x + 2
  const y = area.y + area.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 8, y, { steps: 3 })
  await page.mouse.up()
  await expect(handle).toHaveAttribute('aria-valuenow', '145')
  await handle.press('ArrowRight')
  await expect(handle).toHaveAttribute('aria-valuenow', '153')
})

test('reorders and filters rows and applies a bulk action to selected rows', async ({ page }) => {
  await page.goto('/?component=WP.data-grid')
  const grid = page.getByRole('treegrid', { name: '项目资料网格' })
  const source = grid.getByRole('rowheader', { name: '组件清单' })
  await source.press('ControlOrMeta+Enter')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(grid.getByRole('rowheader').last()).toHaveAccessibleName('组件清单')
  await expect(source).toBeFocused()
  await grid.getByRole('checkbox', { name: '组件清单' }).check()
  await page.getByRole('button', { name: '确认选中项' }).click()
  await expect(source.locator('..').getByRole('gridcell', { name: '已确认' })).toBeVisible()
  const search = page.getByRole('searchbox', { name: '筛选资料' })
  await search.fill('手册')
  await expect(grid.getByRole('rowheader', { name: '品牌手册' })).toBeVisible()
  await expect(source).toHaveCount(0)
  await search.fill('无此项目')
  await expect(grid.getByText('没有匹配的资料')).toBeVisible()
})

test('keeps pinned columns visible with virtualized rows and loads more at the end', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 750 })
  await page.goto('/?component=WP.data-grid')
  await page.getByRole('switch', { name: '长列表' }).click()
  const grid = page.getByRole('treegrid', { name: '项目资料网格' })
  const scroll = page.locator('.sy-data-grid__scroll')
  await expect(grid).toHaveAttribute('aria-rowcount', '97')
  const first = grid.getByRole('rowheader', { name: '设计记录 1', exact: true })
  await expect(first).toBeVisible()
  const left = (await first.boundingBox())!.x
  await scroll.evaluate(node => { node.scrollLeft = 300 })
  await expect.poll(async () => (await scroll.evaluate(node => node.scrollLeft))).toBeGreaterThan(0)
  await expect.poll(async () => (await first.boundingBox())!.x).toBeCloseTo(left, 0)
  expect(await grid.locator('tbody tr[data-index]').count()).toBeLessThan(25)
  await scroll.evaluate(node => { node.scrollTop = node.scrollHeight })
  await expect.poll(async () => Number(await grid.getAttribute('aria-rowcount'))).toBeGreaterThan(97)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('expands and moves tree items with the keyboard and activates a file', async ({ page }) => {
  await page.goto('/?component=WP.file-tree')
  const tree = page.getByRole('tree', { name: '项目文件' })
  const design = tree.getByRole('treeitem', { name: '设计资料' })
  const file = tree.getByRole('treeitem', { name: '品牌手册' })
  const folder = tree.getByRole('treeitem', { name: '参考资料' })
  await expect(design).toHaveAttribute('aria-expanded', 'true')
  await design.press('ArrowRight')
  await expect(file).toBeFocused()
  await file.press('Space')
  await expect(file).toHaveAttribute('aria-selected', 'true')
  await file.press('ControlOrMeta+Enter')
  await page.keyboard.press('ArrowDown')
  await expect(folder).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(folder).toHaveAttribute('data-drop', 'inside')
  await page.keyboard.press('Enter')
  await expect(file).toHaveAttribute('aria-level', '3')
  await expect(file).toBeFocused()
  await file.press('Enter')
  await expect(page.locator('.review-file-tree output')).toContainText('已打开品牌手册')
  const disabled = tree.getByRole('treeitem', { name: '上一版手册' })
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
})

test('moves multiple selected tree files into a folder with a pointer drag', async ({ page }) => {
  await page.goto('/?component=WP.file-tree')
  const tree = page.getByRole('tree', { name: '项目文件' })
  const a = tree.getByRole('treeitem', { name: '品牌手册' })
  const b = tree.getByRole('treeitem', { name: '项目概览' })
  const into = tree.getByRole('treeitem', { name: '发布目录' })
  await a.click()
  await b.click()
  await expect(a).toHaveAttribute('aria-selected', 'true')
  await expect(b).toHaveAttribute('aria-selected', 'true')
  await a.dragTo(into)
  await expect(into).toHaveAttribute('aria-expanded', 'true')
  await expect(b).toHaveAttribute('aria-level', '2')
  await expect(page.locator('.review-file-tree output')).toContainText('已移动 2 项')
})

test('follows scroll position and returns focus after choosing or dismissing the TOC', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 760 })
  await page.goto('/?component=WP.floating-toc')
  const trigger = page.getByRole('button', { name: '打开目录' })
  await trigger.press('ArrowDown')
  const toc = page.getByRole('navigation', { name: '文档目录' })
  const overview = toc.getByRole('link', { name: '项目概览' })
  await expect(overview).toBeFocused()
  await expect(overview).toHaveAttribute('aria-current', 'location')
  await overview.press('ArrowDown')
  await expect(toc.getByRole('link', { name: '收录范围' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(toc).toBeHidden()
  await expect(page.getByRole('heading', { name: '收录范围' })).toBeFocused()
  const doc = page.getByRole('region', { name: '文档预览' })
  await doc.evaluate(node => { node.scrollTop = node.scrollHeight })
  await trigger.click()
  await expect(toc.getByRole('link', { name: '维护与归档' })).toHaveAttribute('aria-current', 'location')
  await toc.getByRole('link', { name: '维护与归档' }).press('Escape')
  await expect(trigger).toBeFocused()
  await expect(toc).toBeHidden()
})

test('opens a virtual directory on hover and navigates to its final section', async ({ page }) => {
  await page.setViewportSize({ width: 1080, height: 780 })
  await page.goto('/?component=WP.floating-toc')
  await page.getByRole('switch', { name: '点击展开' }).click()
  await page.getByRole('switch', { name: '长目录' }).click()
  const trigger = page.getByRole('button', { name: '打开目录' })
  await trigger.hover()
  const toc = page.getByRole('navigation', { name: '文档目录' })
  const start = toc.getByRole('link', { name: '交付记录 1', exact: true })
  await expect(start).toBeVisible()
  expect(await toc.getByRole('link').count()).toBeLessThan(18)
  await start.press('End')
  const last = toc.getByRole('link', { name: '交付记录 48', exact: true })
  await expect(last).toBeFocused()
  await last.press('Enter')
  await expect(page.getByRole('heading', { name: '交付记录 48' })).toBeFocused()
})
