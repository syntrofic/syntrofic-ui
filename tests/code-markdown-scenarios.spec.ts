import { expect, test } from '@playwright/test'

test('code highlights source lines without breaking multi-line syntax or changing the original clipboard text', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText: async (text: string) => { document.body.dataset.highlightCopy = text } },
    })
  })
  await page.goto('/?component=WP.code-block')
  const sample = page.getByRole('region', { name: '行高亮与受限代码区' })
  const region = sample.getByRole('region', { name: '发布记录代码' })
  const rows = region.locator('.sy-code-block__line')
  await expect(rows).toHaveCount(10)
  await expect(region.locator('.sy-code-block__line[data-highlighted]')).toHaveCount(3)
  await expect(region.locator('.sy-code-block__gutter [data-highlighted]')).toHaveText(['6', '7', '9'])
  await expect(rows.nth(5).locator('.hljs-comment')).toHaveText('/* UTC values stay stable across')
  await expect(rows.nth(6).locator('.hljs-comment')).toHaveText('all workspace locales. */')
  const marked = rows.nth(5)
  const background = await marked.evaluate(node => getComputedStyle(node).backgroundColor)
  await sample.getByRole('switch', { name: '标出修改行' }).press('Space')
  await expect(marked).not.toHaveAttribute('data-highlighted')
  await expect(marked).not.toHaveCSS('background-color', background)
  const value = await region.locator('pre code').textContent()
  expect(value?.split('\n')).toHaveLength(10)
  await sample.getByRole('button', { name: '复制发布记录示例' }).press('Enter')
  await expect(page.locator('body')).toHaveAttribute('data-highlight-copy', value!)
  await expect(sample.getByRole('button', { name: 'Copied', exact: true })).toBeFocused()
})

test('scrollable code supports keyboard navigation and the terminal uses isolated syntax colors', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 780 })
  await page.goto('/?component=WP.code-block')
  const tall = page.getByRole('region', { name: '长列表代码视口' })
  await expect(tall).toHaveCSS('max-block-size', '112px')
  expect(await tall.evaluate(node => node.scrollHeight - node.clientHeight)).toBeGreaterThan(150)
  await tall.press('PageDown')
  await expect.poll(() => tall.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  await page.getByRole('switch', { name: '限制代码区高度' }).click()
  await expect(tall).toHaveCSS('max-block-size', '276px')
  const sample = page.getByRole('region', { name: '命令、配置与语法主题' })
  const readout = sample.getByRole('status', { name: '关键字颜色' })
  await expect(readout).toHaveAttribute('data-preset', '墨蓝')
  const color = await readout.locator('code').evaluate(node => getComputedStyle(node).color)
  await sample.getByRole('switch', { name: '深色代码表面' }).click()
  await expect(readout).toHaveAttribute('data-preset', '墨蓝紫')
  await expect(readout.locator('code')).not.toHaveCSS('color', color)
  const shell = sample.getByRole('region', { name: '发布校验命令' }).locator('..')
  await expect(shell.locator('figcaption > span').first()).toBeEmpty()
  await expect(sample.locator('.sy-code-block').filter({ hasText: '构建终端' }).locator('pre')).toContainText('$ pnpm check:catalog')
  await expect(sample.locator('.sy-code-block').filter({ hasText: 'release.json' }).locator('.hljs-attr').first()).toHaveText('"channel"')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

test('Markdown citations support repeated numbers, keyboard preview and native links without altering explicit Markdown', async ({ page }) => {
  await page.goto('/?component=WP.markdown')
  const sample = page.getByRole('region', { name: '带引用的 Markdown' })
  await expect(sample.getByRole('heading', { level: 4, name: '发布资料' })).toHaveAttribute('id', 'evidence-发布资料')
  await expect(sample.getByRole('heading', { level: 5, name: '复核记录' })).toBeVisible()
  const citation = sample.getByRole('link', { name: '标准设计对照清单' })
  await expect(citation).toHaveCount(2)
  await expect(citation.first()).toHaveAttribute('href', '/docs/standard-design/examples/')
  await citation.first().focus()
  await expect(page.getByText('列出组件、公开示例与对应的官网入口。')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(citation.first()).toBeFocused()
  await sample.getByRole('switch', { name: '显示引用编号' }).click()
  await expect(sample.getByRole('link', { name: '引用 1：标准设计对照清单' })).toHaveCount(2)
  await expect(sample.getByRole('link', { name: '引用 2：接入文档' })).toHaveCount(1)
  await expect(sample.getByRole('link', { name: 'catalog', exact: true })).toHaveAttribute('href', '/docs/')
  await expect(sample.locator('code')).toHaveText('[catalog]')
  await expect(sample.locator('li').nth(1)).toContainText('与 [guide]。')
})

test('compact Markdown retains semantic emphasis, aligned cells, tasks and the code footer when density changes', async ({ page }) => {
  await page.goto('/?component=WP.markdown')
  const sample = page.getByRole('region', { name: '交付摘要与数据表' })
  const body = sample.locator('.sy-markdown')
  await expect(body).toHaveAttribute('data-density', 'compact')
  await expect(body.locator('strong')).toHaveText('两份源文件')
  await expect(body.locator('em')).toHaveText('发布批次')
  await expect(sample.getByRole('heading', { name: '本周交付摘要', level: 4 })).toBeVisible()
  const table = sample.getByRole('region', { name: '交付数量表' }).getByRole('table')
  await expect(table.getByRole('cell', { name: '12', exact: true })).toHaveCSS('text-align', 'right')
  await expect(table.getByRole('cell', { name: '已核对', exact: true })).toHaveCSS('text-align', 'center')
  await expect(body.getByRole('checkbox').first()).toBeChecked()
  await expect(body.getByRole('checkbox').last()).toBeDisabled()
  expect(await body.locator('blockquote').count()).toBe(1)
  await sample.getByRole('switch', { name: '紧凑排版' }).press('Space')
  await expect(body).toHaveAttribute('data-density', 'default')
  await expect(table).toBeVisible()
  await expect(sample.getByRole('button', { name: '复制发布配置' })).toBeEnabled()
})
