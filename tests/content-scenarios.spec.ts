import { expect, test } from '@playwright/test'

test('empty states clear result filters and lead into first-project setup', async ({ page }) => {
  await page.goto('/?component=WP.empty-state')
  const search = page.getByRole('region', { name: '资料筛选结果' })
  const input = search.getByRole('textbox', { name: '查找归档资料' })
  await expect(search.getByRole('heading', { name: '找不到归档资料' })).toBeVisible()
  await search.getByRole('button', { name: '查找交付资料' }).press('Enter')
  await expect(search.getByRole('listitem')).toHaveText('交付说明')
  await expect(input).toBeFocused()
  await input.fill('未知资料')
  await search.getByRole('button', { name: '清除资料筛选' }).click()
  await expect(search.getByRole('listitem')).toHaveCount(3)
  await expect(input).toHaveValue('')
  await expect(page.getByText('没有新的评审通知')).toBeVisible()
  await page.getByRole('button', { name: '创建交付项目' }).click()
  await page.getByRole('textbox', { name: '新项目名称' }).fill('网站发布')
  await page.getByRole('button', { name: '保存项目' }).press('Enter')
  await expect(page.getByRole('status').locator('.sy-visually-hidden')).toHaveText('已创建项目「网站发布」')
})

test('confirmation dialogs retain their pending layout, then retry in the same dialog after a failure', async ({ page }) => {
  await page.goto('/?component=W.alert-dialog')
  await page.getByRole('switch', { name: '交付目录可用' }).click()
  const trigger = page.getByRole('button', { name: '删除过期记录' })
  await trigger.click()
  const dialog = page.getByRole('alertdialog', { name: '删除过期记录？' })
  const confirm = dialog.getByRole('button', { name: '确认删除记录' })
  await expect(dialog.getByRole('button', { name: '保留记录' })).toBeFocused()
  const initial = await confirm.evaluate(node => (node as HTMLElement).offsetWidth)
  await confirm.press('Enter')
  await expect(confirm).toHaveAttribute('aria-busy', 'true')
  await expect(confirm.locator('[data-spinning]')).toBeVisible()
  expect(await confirm.evaluate(node => (node as HTMLElement).offsetWidth)).toBe(initial)
  await expect(dialog.getByRole('status').locator('.sy-visually-hidden')).toHaveText('交付目录暂不可用，请恢复连接后重试。')
  await dialog.getByRole('button', { name: '恢复示例连接' }).click()
  await confirm.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('status', { name: '过期记录操作结果' }).locator('.sy-visually-hidden')).toHaveText('已删除过期记录')
})

test('dividers distinguish semantic labels, vertical layout and full-bleed card edges', async ({ page }) => {
  await page.goto('/?component=W.separator')
  const region = page.getByRole('region', { name: '横向和纵向分隔线' })
  await expect(region.getByRole('separator', { name: '或' })).toHaveAttribute('aria-orientation', 'horizontal')
  const decorative = region.locator('[data-orientation="vertical"]')
  await expect(decorative).toHaveAttribute('aria-hidden', 'true')
  const card = region.locator('.sy-card')
  const subtle = card.locator('[data-tone="subtle"]')
  const strong = card.locator('[data-tone="strong"]')
  expect(await subtle.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe(await strong.evaluate(node => getComputedStyle(node).backgroundColor))
  const cardBounds = (await card.boundingBox())!
  const ruleBounds = (await strong.boundingBox())!
  expect(ruleBounds.x).toBeCloseTo(cardBounds.x + 1, 0)
  expect(ruleBounds.width).toBeCloseTo(cardBounds.width - 2, 0)
})

test('quotes can be plain, credited to a person or associated with a linked source', async ({ page }) => {
  await page.goto('/?component=W.blockquote')
  const region = page.getByRole('region', { name: '引文与来源' })
  await expect(region.locator('blockquote')).toHaveCount(4)
  await expect(region.locator('figcaption cite').first()).toHaveText('林舟，品牌设计')
  const link = region.getByRole('link', { name: '发布流程说明' })
  await expect(region.locator('blockquote[cite="#发布流程来源"]')).toBeVisible()
  await link.press('Enter')
  await expect(page).toHaveURL(/#(?:发布流程来源|%E5%8F%91)/)
})

test('headings retain their levels and inline code matches the enclosing text size', async ({ page }) => {
  await page.goto('/?component=W.typography')
  const section = page.getByRole('region', { name: '发布手册标题' })
  await expect(section.getByRole('heading', { name: '发布手册', level: 1 })).toBeVisible()
  await expect(section.getByRole('heading', { name: '准备 release 目录', level: 2 })).toBeVisible()
  await expect(section.getByRole('heading', { name: '核对发布入口', level: 3 })).toBeVisible()
  const matching = await section.locator('code').evaluateAll(elements => elements.map(node => getComputedStyle(node).fontSize === getComputedStyle(node.parentElement!).fontSize))
  expect(matching).toEqual([true, true, true, true, true])
  const titles = page.getByLabel('截断标题卡片')
  const title = titles.getByRole('heading', { name: '品牌交付与数字标识系统的跨端适配验证' })
  await expect(title).toHaveAttribute('tabindex', '0')
  await title.focus()
  await expect(page.getByRole('tooltip').filter({ hasText: '品牌交付与数字标识系统的跨端适配验证' })).toBeVisible()
})

test('visually hidden text names a region and announces progress independently of visible decoration', async ({ page }) => {
  await page.goto('/?component=W.visually-hidden')
  await expect(page.getByRole('button', { name: '了解当前选项' })).toBeVisible()
  const region = page.getByRole('region', { name: '发布进度统计' })
  await expect(region.getByRole('heading', { name: '发布进度统计', level: 3 })).toHaveClass(/sy-visually-hidden/)
  const status = region.getByRole('status')
  await expect(status).toHaveAttribute('aria-live', 'polite')
  await expect(status).toHaveText('本周已完成 4 项交付')
  await region.getByRole('button', { name: '登记完成项' }).press('Enter')
  await expect(status).toHaveText('本周已完成 5 项交付')
  await expect(region.getByText('比上周增加 12%', { exact: true })).toHaveClass(/sy-visually-hidden/)
})
