import { expect, test } from '@playwright/test'

test.afterEach(async ({ page }) => {
  expect(await page.pageErrors()).toEqual([])
})

test('opens the command palette from a shortcut, filters, and returns focus after execution', async ({ page }) => {
  await page.goto('/?component=WP.command')
  const trigger = page.getByRole('button', { name: '打开命令面板' })
  await trigger.focus()
  await page.keyboard.press('ControlOrMeta+k')
  const dialog = page.getByRole('dialog', { name: '快捷命令' })
  const input = dialog.getByRole('combobox', { name: '搜索命令' })
  await expect(input).toBeFocused()
  await input.fill('opn project')
  const result = dialog.getByRole('option', { name: /打开项目/ })
  await expect(result).toBeVisible()
  await expect(dialog.getByRole('option')).toHaveCount(1)
  await expect(input).toHaveAttribute('aria-activedescendant', await result.getAttribute('id') ?? '')
  await input.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(page.getByRole('region', { name: '组件示例' }).locator('output')).toContainText('已执行「打开项目」')
})

test('navigates command groups and nested pages, clears search, and handles an empty result', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.goto('/?component=WP.command')
  const trigger = page.getByRole('button', { name: '打开命令面板' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '快捷命令' })
  const input = dialog.getByRole('combobox', { name: '搜索命令' })
  await expect(input).toBeFocused()
  await input.press('ArrowUp')
  await expect(dialog.getByRole('option', { name: '新建', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(dialog.getByRole('option', { name: /邀请成员/ })).toHaveAttribute('aria-disabled', 'true')
  await input.press('Enter')
  await expect(dialog.getByRole('option', { name: '新建文档' })).toBeVisible()
  await input.fill('不存在')
  await expect(dialog.getByRole('status')).toHaveText('没有匹配的命令。')
  await dialog.getByRole('button', { name: '清空' }).click()
  await expect(input).toHaveValue('')
  await input.press('Escape')
  await expect(dialog.getByRole('option', { name: '新建', exact: true })).toHaveAttribute('aria-selected', 'true')
  await input.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('resizes with the keyboard and pointer, preserves pixels, and restores the persisted layout', async ({ page }) => {
  await page.setViewportSize({ width: 1040, height: 740 })
  await page.goto('/?component=WP.resizable')
  const group = page.getByRole('group', { name: '文档工作区' })
  const handle = group.getByRole('separator', { name: '调整文档面板' })
  const pane = group.locator('[data-panel="files"]')
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(144)
  await handle.press('ArrowRight')
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(152)
  await page.setViewportSize({ width: 970, height: 740 })
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(152)
  const handleBox = (await handle.boundingBox())!
  await page.mouse.move(handleBox.x + handleBox.width / 2, handleBox.y + 28)
  await page.mouse.down()
  await page.mouse.move(handleBox.x + handleBox.width / 2 + 20, handleBox.y + 28, { steps: 4 })
  await page.mouse.up()
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(172)
  await page.reload()
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(172)
  await handle.press('Enter')
  await expect(pane).toHaveAttribute('data-collapsed', 'true')
  await expect(group.getByRole('button', { name: '品牌色板' })).toHaveCount(0)
  await expect(group.getByRole('button', { name: '展开文件列表' })).toBeVisible()
  await handle.press('Enter')
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(172)
})

test('snaps a panel closed when dragged past its minimum and adjusts vertically', async ({ page }) => {
  await page.setViewportSize({ width: 960, height: 730 })
  await page.goto('/?component=WP.resizable')
  const group = page.getByRole('group', { name: '文档工作区' })
  const pane = group.locator('[data-panel="files"]')
  const handle = group.getByRole('separator', { name: '调整文档面板' })
  await expect.poll(async () => Math.round((await pane.boundingBox())!.width)).toBe(144)
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + 24)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 - 124, box.y + 24, { steps: 6 })
  await page.mouse.up()
  await expect(pane).toHaveAttribute('data-collapsed', 'true')
  await page.getByRole('button', { name: '纵向' }).click()
  await expect(handle).toHaveAttribute('aria-orientation', 'horizontal')
  const before = Number(await handle.getAttribute('aria-valuenow'))
  await handle.press('ArrowDown')
  await expect.poll(async () => Math.round(Number(await handle.getAttribute('aria-valuenow')) - before)).toBe(8)
  await handle.press('Home')
  await expect.poll(async () => Number(await handle.getAttribute('aria-valuenow'))).toBe(48)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(960)
})

test('updates the action count without shifting buttons and restores focus on dismissal and bulk actions', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 760 })
  await page.goto('/?component=WP.action-bar')
  const example = page.getByRole('region', { name: '组件示例' })
  const toolbar = example.getByRole('toolbar', { name: '文件批量操作' })
  const clear = toolbar.getByRole('button', { name: '取消', exact: true })
  const share = toolbar.getByRole('button', { name: '设为共享' })
  await expect(toolbar).toHaveCount(0)
  await example.getByRole('checkbox', { name: '组件规范' }).check()
  await expect(toolbar).toBeVisible()
  await expect(example.locator('.sy-action-bar > [role="status"]')).toHaveText('已选 1 项')
  const geometry = () => share.evaluate(button => ({
    width: button.offsetWidth, offset: button.offsetLeft,
  }))
  await expect.poll(async () => (await geometry()).width).toBeGreaterThan(20)
  const initial = await geometry()
  await example.getByRole('checkbox', { name: '产品演示' }).check()
  await expect(example.locator('.sy-action-bar > [role="status"]')).toHaveText('已选 2 项')
  await expect.poll(geometry).toEqual(initial)
  await share.press('ArrowRight')
  await expect(toolbar.getByRole('button', { name: '归档' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(clear).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(toolbar).toHaveCount(0)
  await expect(example.getByRole('button', { name: '全选' })).toBeFocused()
  await expect(example.getByRole('checkbox', { name: '组件规范' })).not.toBeChecked()

  await example.getByRole('switch', { name: '浮动' }).click()
  await example.getByRole('checkbox', { name: '组件规范' }).check()
  await share.click()
  await expect(example.getByRole('listitem').filter({ hasText: '组件规范' })).toContainText('共享')
  await expect(toolbar).toHaveCount(0)
  await expect(example.getByRole('button', { name: '全选' })).toBeFocused()
  await example.getByRole('checkbox', { name: '产品演示' }).check()
  await toolbar.getByRole('button', { name: '归档' }).click()
  await expect(example.getByRole('checkbox', { name: '产品演示' })).toHaveCount(0)
  await expect(example.locator('output')).toContainText('已归档 1 项')
})
