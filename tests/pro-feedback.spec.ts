import { expect, test } from '@playwright/test'

test('formats readouts and reserves space across a digit boundary', async ({ page }) => {
  await page.goto('/?component=WP.number-value')
  const sample = page.getByRole('region', { name: '组件示例' })
  const income = sample.locator('.sy-number-value__readout').first()
  const spoken = income.locator('.sy-visually-hidden')
  await expect(spoken).toHaveText('¥999')
  const before = await income.boundingBox()
  await sample.getByRole('button', { name: '切换数据' }).click()
  await expect(spoken).toHaveText('¥1,001')
  await expect(income.locator('.sy-motion-text__place[data-motion="roll"]')).toHaveCount(4)
  const after = await income.boundingBox()
  expect(Math.abs((before?.width ?? 0) - (after?.width ?? 0))).toBeLessThan(1)
  await expect(sample.getByText('9,007,199,254,740,993', { exact: true }).first()).toBeAttached()
})

test('exposes trend direction and keeps its indicator in the same reserved slot', async ({ page }) => {
  await page.goto('/?component=WP.trend-chip')
  const sample = page.getByRole('region', { name: '组件示例' })
  const trend = sample.locator('.sy-trend-chip').first()
  await expect(trend).toHaveAttribute('data-trend', 'up')
  await expect(trend.locator('.sy-visually-hidden').first()).toHaveText('上升')
  const width = (await trend.boundingBox())?.width ?? 0
  await sample.getByRole('button', { name: '切换趋势' }).click()
  await expect(trend).toHaveAttribute('data-trend', 'down')
  await expect(trend.locator('.sy-visually-hidden').first()).toHaveText('下降')
  expect(Math.abs(((await trend.boundingBox())?.width ?? 0) - width)).toBeLessThan(1)
})

test('reflects pointer and keyboard presses, ignores disabled actions, and reduces motion', async ({ page }) => {
  await page.goto('/?component=WP.pressable-feedback')
  const sample = page.getByRole('region', { name: '组件示例' })
  const ripple = sample.getByRole('button', { name: '从按压处扩散' })
  await ripple.hover()
  await page.mouse.down()
  await expect(ripple).toHaveAttribute('data-pressed', 'true')
  await page.mouse.up()
  await expect(ripple).not.toHaveAttribute('data-pressed')
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已标记')
  await sample.getByRole('button', { name: '不可用操作' }).dispatchEvent('click')
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已标记')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const scale = sample.getByRole('button', { name: '轻缩反馈' })
  await scale.focus()
  await page.keyboard.down('Space')
  await expect(scale).toHaveAttribute('data-pressed', 'true')
  await expect.poll(() => scale.evaluate(node => getComputedStyle(node).scale)).toBe('none')
  await page.keyboard.up('Space')
  await expect(scale).not.toHaveAttribute('data-pressed')
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已添加')

  const hold = sample.getByRole('button', { name: '按住确认归档' })
  await hold.hover()
  await page.mouse.down()
  await expect(hold).toHaveAttribute('data-running', 'true')
  await page.mouse.up()
  await expect(hold).not.toHaveAttribute('data-running')
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已添加')
  await hold.focus()
  await page.keyboard.down('Space')
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已确认归档')
  await page.keyboard.up('Space')

  const progress = sample.getByRole('button', { name: '校验更新' })
  const spinner = progress.locator('.sy-button__spinner-slot')
  const beforeProgress = await spinner.evaluate(node => getComputedStyle(node).transform)
  await progress.click()
  await expect(progress).toHaveAttribute('aria-busy', 'true')
  await expect(spinner).toHaveCSS('transform', beforeProgress)
  await expect(sample.locator('.review__result .sy-visually-hidden')).toHaveText('已完成校验')
  await expect(progress).toHaveAttribute('data-complete', 'true')
})

test('shared press feedback distinguishes a scroll from a deliberate touch', async ({ page }) => {
  await page.goto('/?component=WP.pressable-feedback')
  const sample = page.getByRole('region', { name: '滚动区域按压反馈' })
  const button = sample.getByRole('button', { name: '查看交付记录' })
  const press = (type: string, x = 20) => button.dispatchEvent(type, {
    pointerId: 14, pointerType: 'touch', isPrimary: true, bubbles: true, button: 0, clientX: x, clientY: 36,
  })
  await expect(button).toHaveAttribute('data-sy-pressable', '')
  await press('pointerdown')
  await expect(button).not.toHaveAttribute('data-sy-press')
  await press('pointermove', 55)
  await expect(button).toHaveAttribute('data-sy-press', 'cancelled')
  await press('pointerup', 55)
  await expect(button).not.toHaveAttribute('data-sy-press')

  await press('pointerdown')
  await expect(button).toHaveAttribute('data-sy-press', 'held')
  await press('pointerup')
  await expect(button).not.toHaveAttribute('data-sy-press')
  const quickTap = await button.evaluate(node => {
    const event = (type: string) => new PointerEvent(type, {
      pointerId: 15, pointerType: 'touch', isPrimary: true, bubbles: true, button: 0,
    })
    node.dispatchEvent(event('pointerdown'))
    const before = node.getAttribute('data-sy-press')
    node.dispatchEvent(event('pointerup'))
    return [before, node.getAttribute('data-sy-press')]
  })
  expect(quickTap).toEqual([null, 'held'])
  await expect(button).not.toHaveAttribute('data-sy-press')
})
