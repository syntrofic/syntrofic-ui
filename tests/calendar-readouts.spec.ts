import { expect, test } from '@playwright/test'

test('calendar constrains workdays and eases month changes in the direction of travel', async ({ page }) => {
  await page.goto('/?component=W.calendar')
  const calendar = page.getByRole('group', { name: '项目日历' })
  const day = (iso: string) => calendar.locator(`.sy-calendar__day[data-value="${iso}"]:not([data-outside-view])`)
  await page.getByRole('button', { name: '仅开放工作日' }).click()
  await expect(day('2026-11-17')).toHaveAttribute('aria-disabled', 'true')
  await expect(day('2026-11-21')).toHaveAttribute('aria-disabled', 'true')
  await day('2026-11-19').click()
  await expect(day('2026-11-19')).toHaveAttribute('data-selected')
  const next = calendar.getByRole('button', { name: '下个月' })
  const effects = await next.evaluate(async button => {
    const trigger = button as HTMLButtonElement
    trigger.click()
    await Promise.resolve()
    return button.closest('.sy-calendar')?.querySelector('.sy-calendar__months')?.getAnimations().map(animation => ({
      easing: animation.effect?.getTiming().easing,
      offset: (animation.effect as KeyframeEffect).getKeyframes()[0].translate,
    }))
  })
  expect(effects).toContainEqual({ easing: expect.stringContaining('cubic-bezier'), offset: expect.stringMatching(/^8px/) })
  await expect(day('2026-12-12')).toHaveAttribute('aria-disabled', 'true')
  await expect(day('2026-12-11')).not.toHaveAttribute('aria-disabled', 'true')
})

test('two month range calendar preserves a selected cross-month span', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/?component=W.range-calendar')
  await page.getByRole('button', { name: '跨月选择' }).click()
  const calendar = page.getByRole('group', { name: '交付日期范围' })
  await expect(calendar.locator('.sy-calendar__month')).toHaveCount(2)
  const day = (iso: string) => calendar.locator(`.sy-calendar__day[data-value="${iso}"]:not([data-outside-view])`)
  await day('2026-11-26').click()
  await day('2026-12-02').hover()
  await expect(day('2026-11-30')).toHaveAttribute('data-highlighted')
  await day('2026-12-02').click()
  await expect(day('2026-11-26')).toHaveAttribute('data-selection-start')
  await expect(day('2026-12-02')).toHaveAttribute('data-selection-end')
  await expect(page.locator('.review__result [aria-live]')).toHaveText('2026-11-26 至 2026-12-02')
})

test('calendar hook grid moves real focus across months and applies booking rules', async ({ page }) => {
  await page.goto('/?component=W.calendar')
  const scene = page.getByRole('region', { name: '日历组合式工具' })
  const day = (iso: string) => scene.getByRole('button', { name: iso, exact: true })
  await day('2026-11-30').press('ArrowRight')
  await expect(day('2026-12-01')).toBeFocused()
  await expect(scene.getByRole('status', { name: '待聚焦日期' })).toHaveCount(0)
  await day('2026-12-01').press('ArrowLeft')
  await expect(day('2026-11-30')).toBeFocused()
  await scene.getByLabel('停业日').selectOption('1')
  await expect(day('2026-11-30')).toBeDisabled()
  await day('2026-11-27').press('Enter')
  await expect(scene.locator('.review__result [aria-live]')).toHaveText('2026-11-25 至 2026-11-27')
  await expect(day('2026-11-26')).toHaveAttribute('data-in-range', 'true')
  await scene.getByRole('button', { name: '重选入住' }).click()
  await day('2026-11-24').press('Enter')
  await expect(scene.locator('.review__result [aria-live]')).toHaveText('2026-11-24 · 请选择离店日期')
})

test('timer advances clock digits, shares minute precision with its compact format and inherits inline type', async ({ page }) => {
  const now = new Date('2026-11-22T12:00:00Z')
  await page.clock.install({ time: now })
  await page.clock.pauseAt(new Date(now.getTime() + 1000))
  await page.goto('/?component=W.timer')
  const clock = page.locator('[data-timer-clock]')
  const elapsed = page.locator('[data-timer-elapsed]')
  const inline = page.locator('[data-timer-inline]')
  const digits = clock.locator('.sy-motion-text > .sy-visually-hidden')
  await expect(digits).toHaveText('1:02:33')
  await expect(clock).toHaveAttribute('datetime', 'PT3753S')
  await expect(elapsed).toHaveAttribute('datetime', 'PT3720S')
  await expect(inline).toHaveCSS('font-weight', '600')
  await expect(inline).toHaveCSS('color', await inline.locator('..').evaluate(node => getComputedStyle(node).color))
  await page.clock.runFor(1000)
  await expect(digits).toHaveText('1:02:34')
  await expect(clock.locator('[data-motion="roll"]').first()).toBeAttached()
  await expect(elapsed).toHaveAttribute('datetime', 'PT3720S')
  await page.getByRole('button', { name: '重新计时' }).press('Enter')
  await expect(digits).toHaveText('0:00')
})

test('timestamp switches zone text, preserves machine formats and explains relative dates in a tooltip', async ({ page }) => {
  await page.goto('/?component=W.timestamp')
  const scene = page.getByRole('region', { name: '时间戳用法' })
  const system = scene.locator('[data-format="system_date_time"]')
  const display = scene.locator('[data-format="date_time"]')
  await expect(system).toHaveText('2026-03-21 18:15:00')
  await expect(display).toHaveText(/GMT\+8/)
  await scene.getByRole('combobox', { name: '显示时区' }).click()
  await page.getByRole('option', { name: '纽约' }).click()
  await expect(system).toHaveText('2026-03-21 06:15:00')
  await expect(display).toHaveText(/EDT/)
  await expect(scene.locator('[data-auto="recent"]')).toContainText('分钟前')
  await expect(scene.locator('[data-auto="older"]')).not.toContainText('前')
  const colors = scene.locator('[aria-label="时间戳颜色"] time')
  expect(await colors.evaluateAll(items => items.map(item => item.getAttribute('data-color')))).toEqual(['primary', 'secondary', 'disabled', 'accent'])
  const recent = scene.getByRole('button', { name: /秒钟?前/ })
  await recent.press('Enter')
  await expect(page.locator('.sy-timestamp-details')).toBeVisible()
  await expect(page.locator('.sy-timestamp-details li')).toHaveCount(1)
})
