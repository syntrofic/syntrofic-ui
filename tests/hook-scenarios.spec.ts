import { expect, test } from '@playwright/test'

test('announces only the settled result and supports opt-in single-key shortcuts outside inputs', async ({ page }) => {
  await page.goto('/?component=W.interaction-tools')
  const sample = page.getByRole('region', { name: '资料筛选与全局快捷键' })
  const input = sample.getByRole('searchbox', { name: '搜索品牌资料' })
  await sample.getByRole('button', { name: '查看快捷键' }).focus()
  await page.keyboard.press('/')
  await expect(input).toBeFocused()
  await input.press('/')
  await expect(input).toHaveValue('/')
  await input.fill('品牌')
  await expect(sample.getByRole('listitem')).toHaveCount(2)
  await input.fill('日志')
  const status = page.locator('body > [aria-atomic="true"][role="status"]')
  await expect(status).toHaveCount(0)
  await expect(status).toHaveText('1 项匹配')
  await input.fill('不存在')
  await expect(status).toHaveText('无匹配结果')
  await input.press('?')
  await expect(page.getByRole('dialog', { name: '资料筛选快捷键' })).toHaveCount(0)
  await sample.getByRole('button', { name: '查看快捷键' }).press('?')
  await expect(page.getByRole('dialog', { name: '资料筛选快捷键' })).toBeVisible()
  await page.keyboard.press('Escape')
  const enabled = sample.getByRole('switch', { name: '启用单键快捷键' })
  await enabled.press('Space')
  await enabled.press('/')
  await expect(input).not.toBeFocused()
})

test('clipboard shares the displayed address, announces success and resets after the latest copy', async ({ page }) => {
  await page.addInitScript(() => {
    const writes: string[] = []
    Object.defineProperty(window, 'clipboardWrites', { value: writes })
    Object.defineProperty(navigator, 'clipboard', { value: { async writeText(text: string) { writes.push(text) } } })
  })
  await page.goto('/?component=W.interaction-tools')
  const sample = page.getByRole('region', { name: '分享复核邀请' })
  const button = sample.getByRole('button')
  const status = page.locator('body > [aria-atomic="true"][role="status"]')
  await button.click()
  await expect(button).toHaveAccessibleName('已复制链接')
  await expect(status).toHaveText('邀请链接已复制')
  await page.waitForTimeout(850)
  await button.press('Enter')
  await page.waitForTimeout(850)
  await expect(button).toHaveAccessibleName('已复制链接')
  const invite = await sample.locator('code').textContent()
  expect(await page.evaluate(() => (window as Window & { clipboardWrites?: string[] }).clipboardWrites)).toEqual([invite, invite])
  await expect(button).toHaveAccessibleName('复制邀请链接')
})

test('quick edit traps keyboard focus and the full menu restores the scroll position', async ({ page }) => {
  await page.goto('/?component=W.modal')
  const sample = page.getByRole('region', { name: '自定义浮层行为' })
  const opener = sample.getByRole('button', { name: '快速编辑名称' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '快速编辑交付名称' })
  const name = dialog.getByRole('textbox', { name: '新的交付名称' })
  await expect(name).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '退出快速编辑' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(name).toBeFocused()
  await name.fill('新版交付记录')
  await name.press('Enter')
  await expect(opener).toBeFocused()
  await expect(sample.getByRole('status', { name: '自定义浮层结果' }).locator('.sy-visually-hidden')).toHaveText('已更新为新版交付记录')
  await opener.press('Enter')
  await expect(name).toHaveValue('新版交付记录')
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()

  const menu = sample.getByRole('button', { name: '打开全屏资料菜单' })
  await menu.scrollIntoViewIfNeeded()
  await menu.focus()
  const previous = await page.evaluate(() => window.scrollY)
  await menu.press('Enter')
  const full = page.getByRole('dialog', { name: '全屏资料菜单' })
  await expect(full.getByRole('button', { name: '关闭资料菜单' })).toBeFocused()
  await expect(page.locator('html')).toHaveCSS('overflow-y', 'hidden')
  await page.mouse.wheel(0, 360)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(previous)
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(page.locator('html')).not.toHaveCSS('overflow-y', 'hidden')
  expect(await page.evaluate(() => window.scrollY)).toBe(previous)
})

test('project card navigation keeps selections and nested actions independent', async ({ page }) => {
  await page.goto('/?component=W.clickable-card')
  const sample = page.getByRole('region', { name: '可点击项目卡片' })
  const body = sample.getByText('这里记录版本规则、复核状态和交付时间。', { exact: true })
  await body.evaluate(node => {
    const range = document.createRange()
    range.selectNodeContents(node)
    document.getSelection()?.addRange(range)
  })
  await body.dispatchEvent('click')
  expect(new URL(page.url()).hash).toBe('')
  await body.evaluate(() => document.getSelection()?.removeAllRanges())
  await sample.getByRole('button', { name: '收藏计划' }).click()
  await expect(sample.getByRole('button', { name: '已收藏计划' })).toHaveAttribute('aria-pressed', 'true')
  expect(new URL(page.url()).hash).toBe('')
  await sample.getByRole('link', { name: '查看负责人' }).click()
  await expect(page).toHaveURL(/#hook-project-owner$/)
  await body.click()
  await expect(page).toHaveURL(/#hook-project-details$/)
  const popup = page.waitForEvent('popup')
  await body.click({ button: 'middle' })
  const opened = await popup
  await expect(opened).toHaveURL(/#hook-project-details$/)
  await opened.close()
})

