test('scroll hooks track logical edges, update with content and add a tab stop on overflow', async ({ page }) => {
  await page.goto('/?component=W.scroll-shadow')
  const filters = page.getByRole('region', { name: '筛选条件横向滚动' })
  const strip = filters.getByRole('region', { name: '当前筛选条件' })
  const start = filters.locator('[data-edge="start"]')
  const end = filters.locator('[data-edge="end"]')
  await expect(end).not.toHaveAttribute('data-visible')
  const add = filters.getByRole('button', { name: '增加筛选条件' })
  for (let index = 0; index < 5; index++) await add.press('Enter')
  await expect(end).toHaveAttribute('data-visible', 'true')
  await strip.evaluate(node => { node.scrollLeft = (node.scrollWidth - node.clientWidth) / 2 })
  await expect(start).toHaveAttribute('data-visible', 'true')
  await expect(end).toHaveAttribute('data-visible', 'true')
  await filters.getByRole('switch', { name: '反转筛选条件方向' }).press('Space')
  await strip.evaluate(node => { node.scrollLeft = -node.scrollWidth })
  await expect(start).toHaveAttribute('data-visible', 'true')
  await expect(end).not.toHaveAttribute('data-visible')
  const remove = filters.getByRole('button', { name: '移除筛选条件' })
  for (let index = 0; index < 5; index++) await remove.press('Enter')
  await expect(start).not.toHaveAttribute('data-visible')
  await expect(end).not.toHaveAttribute('data-visible')

  await page.goto('/?component=W.scrollable-area')
  const logSample = page.getByRole('region', { name: '交付活动日志滚动' })
  const log = logSample.getByRole('region', { name: '交付活动日志' })
  await expect(log).toHaveAttribute('tabindex', '-1')
  await expect(log).toHaveCSS('overscroll-behavior-y', 'contain')
  const append = logSample.getByRole('button', { name: '添加活动日志' })
  for (let index = 0; index < 5; index++) await append.press('Enter')
  await expect(log).toHaveAttribute('tabindex', '0')
  await expect(logSample.locator('[data-edge="bottom"]')).toHaveAttribute('data-visible', 'true')
  await log.press('End')
  await expect(logSample.locator('[data-edge="top"]')).toHaveAttribute('data-visible', 'true')
  await expect(logSample.locator('[data-edge="bottom"]')).not.toHaveAttribute('data-visible')
})

test('file actions stay in keyboard order and removing a revealed row moves focus', async ({ page, browserName }) => {
  await page.goto('/?component=W.thumbnail')
  const sample = page.getByRole('region', { name: '悬停显示的文件操作' })
  const edit = sample.getByRole('button', { name: '编辑交付附件清单' })
  await expect(edit).toHaveCSS('opacity', '0')
  await edit.focus()
  await expect(edit).toHaveCSS('opacity', '1')
  const remove = sample.getByRole('button', { name: '移除交付附件清单' })
  expect(await remove.evaluate(button => (button as HTMLElement).tabIndex)).toBe(0)
  await page.keyboard.press(browserName === 'webkit' && process.platform === 'darwin' ? 'Alt+Tab' : 'Tab')
  await expect(remove).toBeFocused()
  await remove.press('Enter')
  await expect(sample.getByRole('button', { name: '编辑版本复核记录' })).toBeFocused()
  await expect(edit).toHaveCount(0)
})

test('streaming hook plays each burst and can restart the reply', async ({ page }) => {
  await page.goto('/?component=WP.markdown')
  const sample = page.getByRole('region', { name: '可重新生成的流式回复' })
  const reply = sample.locator('[aria-label="回复正文"]')
  const generate = sample.getByRole('button', { name: '重新生成回复' })
  await generate.click()
  await expect(reply).toHaveAttribute('aria-busy', 'true')
  await expect(reply).toContainText('复核已完成')
  await expect(reply).not.toContainText('请核对发布范围后归档')
  await expect(reply).not.toHaveAttribute('aria-busy')
  await expect(reply).toContainText('请核对发布范围后归档')
  await generate.press('Enter')
  await expect(reply).toHaveAttribute('aria-busy', 'true')
  await expect(reply).not.toHaveAttribute('aria-busy')
  await expect(sample.locator('[aria-live="polite"]')).toContainText('请核对发布范围后归档')
})
