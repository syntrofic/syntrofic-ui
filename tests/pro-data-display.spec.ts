test('navigates the carousel with keyboard, thumbnails, drag and the looping modal', async ({ page }) => {
  await page.setViewportSize({ width: 900, height: 760 })
  await page.goto('/?component=WP.carousel')
  const gallery = page.getByRole('region', { name: '莫兰迪配色' })
  const next = gallery.getByRole('button', { name: '下一张' })
  const previous = gallery.getByRole('button', { name: '上一张' })
  const snap = (index: number) => gallery.getByRole('button', { name: `第 ${index} 张，共 4 张` })
  await expect(previous).toHaveAttribute('aria-disabled', 'true')
  await expect(snap(1)).toHaveAttribute('aria-current', 'true')
  await gallery.locator('.sy-carousel__viewport').press('ArrowRight')
  await expect(snap(2)).toHaveAttribute('aria-current', 'true')
  await snap(3).click()
  await expect(snap(3)).toHaveAttribute('aria-current', 'true')
  const viewport = gallery.locator('.sy-carousel__viewport')
  const selectedSlide = gallery.getByRole('group', { name: /陶土/ })
  const box = (await viewport.boundingBox())!
  await expect.poll(async () => {
    const slide = await selectedSlide.boundingBox()
    return slide ? Math.abs(slide.x - box.x) : Number.POSITIVE_INFINITY
  }).toBeLessThan(1)
  await page.mouse.move(box.x + box.width * .8, box.y + 55)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .15, box.y + 55, { steps: 10 })
  await page.mouse.up()
  await expect(snap(4)).toHaveAttribute('aria-current', 'true')
  await expect(next).toHaveAttribute('aria-disabled', 'true')

  const opener = page.getByRole('button', { name: '放大' })
  await opener.click()
  const modal = page.getByRole('dialog', { name: '配色预览' })
  await modal.getByRole('button', { name: '下一张' }).click()
  await expect(modal.getByRole('button', { name: '第 1 张，共 4 张' })).toHaveAttribute('aria-current', 'true')
  await page.keyboard.press('Escape')
  await expect(modal).toBeHidden()
  await expect(opener).toBeFocused()
  await expect(snap(1)).toHaveAttribute('aria-current', 'true')
})

test('keeps rotation controls stable, pauses for the user and presents multiple slides', async ({ page }) => {
  await page.goto('/?component=WP.carousel')
  const gallery = page.getByRole('region', { name: '莫兰迪配色' })
  const switcher = page.getByRole('switch', { name: '自动播放' })
  await switcher.click()
  const pause = gallery.getByRole('button', { name: '暂停', exact: true })
  const play = gallery.getByRole('button', { name: '播放', exact: true })
  const dots = page.locator('.review-gallery > .sy-carousel [data-sy-carousel-page][aria-current="true"]')
  await expect(pause).toBeVisible()
  await page.mouse.move(1, 1)
  await expect(dots).toHaveAttribute('data-sy-carousel-page', '1', { timeout: 4500 })
  const width = await pause.evaluate(button => button.offsetWidth)
  await pause.click()
  await expect(play).toBeVisible()
  expect(await play.evaluate(button => button.offsetWidth)).toBe(width)
  const pausedAt = await dots.getAttribute('data-sy-carousel-page')
  await page.mouse.move(1, 1)
  await page.waitForTimeout(1550)
  await expect(dots).toHaveAttribute('data-sy-carousel-page', pausedAt ?? '')
  await page.getByRole('button', { name: '并排' }).click()
  await expect(gallery.locator('[data-sy-carousel-page]')).toHaveCount(3)
  await expect(gallery.locator('.sy-carousel__slide:not([inert])')).toHaveCount(2)
  await page.getByRole('button', { name: '放大' }).click()
  const modal = page.getByRole('dialog', { name: '配色预览' })
  const last = modal.getByRole('button', { name: '第 4 张，共 4 张' })
  await last.click()
  await expect(last).toHaveAttribute('aria-current', 'true')
  await expect(dots).toHaveAttribute('data-sy-carousel-page', '2')
  await modal.getByRole('button', { name: '下一张' }).click()
  await expect(modal.getByRole('button', { name: '第 1 张，共 4 张' })).toHaveAttribute('aria-current', 'true')
})

test('carousel paging advances a view or one item, hands mouse wheels back, and mirrors touch in RTL', async ({ page }) => {
  await page.setViewportSize({ width: 900, height: 850 })
  await page.goto('/?component=WP.carousel')
  const gallery = page.getByRole('region', { name: '按距离吸附轮播' })
  const viewport = gallery.locator('.sy-carousel__viewport')
  const selected = gallery.locator('[data-sy-carousel-page][aria-current="true"]')
  const leadingSlide = (index: number) => gallery.locator('.sy-carousel__slide').nth(index)
  async function alignment(index: number, rtl = false) {
    const area = (await viewport.boundingBox())!
    const slide = await leadingSlide(index).boundingBox()
    return slide ? Math.abs(rtl ? slide.x + slide.width - area.x - area.width : slide.x - area.x) : Infinity
  }
  async function trackpad(direction: number) {
    for (let index = 0; index < 25; index++) await viewport.dispatchEvent('wheel', { deltaX: direction * 14, deltaMode: 0, cancelable: true })
  }
  await expect(gallery).toHaveAttribute('data-snap-paging', 'true')
  await expect(selected).toHaveAttribute('data-sy-carousel-page', '0')
  await trackpad(1)
  await expect(selected).toHaveAttribute('data-sy-carousel-page', '2')
  await expect.poll(() => alignment(2)).toBeLessThan(2)
  await expect(viewport).not.toHaveAttribute('data-snap-held')
  await page.getByRole('button', { name: '每次一项' }).press('Space')
  await trackpad(1)
  await expect(selected).toHaveAttribute('data-sy-carousel-page', '3')
  await expect.poll(() => alignment(3)).toBeLessThan(2)
  await expect(viewport).not.toHaveAttribute('data-snap-held')

  await viewport.scrollIntoViewIfNeeded()
  await viewport.press('Home')
  await expect.poll(() => alignment(0)).toBeLessThan(2)
  await viewport.hover()
  await page.mouse.wheel(400, 0)
  await expect.poll(() => viewport.evaluate(node => node.scrollLeft)).toBeGreaterThan(180)
  await expect(selected).not.toHaveAttribute('data-sy-carousel-page', '0')

  await page.getByRole('switch', { name: '从右向左分页' }).click()
  await viewport.press('Home')
  await expect.poll(() => alignment(0, true)).toBeLessThan(2)
  await viewport.evaluate(async node => {
    const send = (type: string, x: number) => node.dispatchEvent(new PointerEvent(type, {
      bubbles: true, cancelable: true, pointerId: 9, pointerType: 'touch', isPrimary: true,
      button: 0, buttons: type === 'pointerup' ? 0 : 1, clientX: x, clientY: 30,
    }))
    send('pointerdown', 40)
    await new Promise(resolve => requestAnimationFrame(resolve))
    send('pointermove', 180)
    await new Promise(resolve => requestAnimationFrame(resolve))
    send('pointermove', 290)
    send('pointerup', 290)
  })
  await expect(selected).toHaveAttribute('data-sy-carousel-page', '1')
  await expect.poll(() => alignment(1, true)).toBeLessThan(2)
  await expect(viewport).not.toHaveAttribute('data-snap-held')
})

test('shows initial, empty and error scenes and keeps focus through recovery', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 720 })
  await page.goto('/?component=WP.empty-state')
  const sample = page.getByRole('region', { name: '组件示例' })
  await expect(sample.getByRole('heading', { name: '项目还没有资料' })).toBeVisible()
  await sample.getByRole('button', { name: '添加资料' }).press('Enter')
  const back = sample.getByRole('button', { name: '返回' })
  await expect(back).toBeFocused()
  await back.click()
  await sample.getByRole('button', { name: '无结果' }).click()
  await expect(sample.getByRole('heading', { name: '没有匹配的成员' })).toBeVisible()
  await sample.getByRole('button', { name: '异常' }).click()
  const retry = sample.getByRole('button', { name: '重试' })
  await retry.click()
  await expect(retry).toHaveAttribute('aria-busy', 'true')
  await expect(sample.getByText('品牌手册').first()).toBeVisible()
  await expect(back).toBeFocused()
})
