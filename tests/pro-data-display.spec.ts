test('renders overlapping and cross-day agenda events and switches between month, week and day', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 850 })
  await page.goto('/?component=WP.agenda')
  const agenda = page.getByRole('region', { name: '项目日程' })
  const wednesday = agenda.locator('[data-agenda-day="2026-11-18"]')
  const thursday = agenda.locator('[data-agenda-day="2026-11-19"]')
  await expect(wednesday.getByRole('button', { name: /发布观察/ })).toHaveAccessibleName('发布观察 · 16:00 – 18:00')
  await expect(thursday.getByRole('button', { name: /发布观察/ })).toHaveAccessibleName('发布观察 · 08:00 – 09:45')
  const review = wednesday.getByRole('button', { name: /组件评审/ })
  const overlap = wednesday.getByRole('button', { name: /可访问性走查/ })
  await expect(review).toBeVisible()
  expect((await overlap.boundingBox())!.x).toBeGreaterThan((await review.boundingBox())!.x)
  await review.click()
  await expect(review).toHaveAttribute('aria-pressed', 'true')
  const allDay = agenda.getByRole('button', { name: '全天', exact: true })
  await allDay.click()
  await expect(agenda.getByRole('button', { name: '设计交付周' })).toHaveCount(0)
  await expect(allDay).toHaveAttribute('aria-expanded', 'false')
  await allDay.click()
  await expect(agenda.getByRole('button', { name: '设计交付周' })).toBeVisible()

  await agenda.getByRole('button', { name: '月', exact: true }).click()
  await expect(agenda).toHaveAttribute('data-view', 'month')
  await expect(agenda.getByRole('button', { name: '设计交付周' })).toHaveCount(1)
  await agenda.getByRole('button', { name: /2026年11月19日/ }).click()
  await expect(agenda).toHaveAttribute('data-view', 'day')
  await expect(agenda.locator('[data-agenda-day]')).toHaveCount(1)
  await expect(thursday.getByRole('button', { name: /发布观察/ })).toBeVisible()
})

test('moves, resizes and adds events, keeping read-only events intact', async ({ page }) => {
  await page.setViewportSize({ width: 1100, height: 830 })
  await page.goto('/?component=WP.agenda')
  const agenda = page.getByRole('region', { name: '项目日程' })
  const source = agenda.locator('[data-agenda-day="2026-11-18"]')
  const destination = agenda.locator('[data-agenda-day="2026-11-19"]')
  const event = agenda.getByRole('button', { name: /组件评审/ })
  await expect(source.getByRole('button', { name: /组件评审/ })).toBeVisible()
  const readOnly = agenda.getByRole('button', { name: /项目同步/ })
  await readOnly.press('Delete')
  await expect(readOnly).toBeVisible()
  const box = (await event.boundingBox())!
  const dest = (await destination.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + 8)
  await page.mouse.down()
  await page.mouse.move(dest.x + dest.width / 2, box.y + 8, { steps: 5 })
  await page.mouse.up()
  await expect(destination.getByRole('button', { name: /组件评审/ })).toHaveAccessibleName('组件评审 · 09:15 – 11:00')
  await event.press('Alt+Shift+ArrowDown')
  await expect(event).toHaveAccessibleName('组件评审 · 09:15 – 11:15')
  const edge = (await event.locator('[data-agenda-resize]').boundingBox())!
  const range = (await destination.boundingBox())!
  const x = edge.x + edge.width / 2
  const y = edge.y + edge.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x, range.y + range.height * .35 - 1.5, { steps: 5 })
  await page.mouse.up()
  await expect(event).toHaveAccessibleName('组件评审 · 09:15 – 11:30')
  await agenda.getByRole('button', { name: '新增日程' }).click()
  const added = agenda.getByRole('button', { name: /新日程/ })
  await expect(added).toHaveAttribute('aria-pressed', 'true')
  await added.press('Delete')
  await expect(added).toHaveCount(0)
})

