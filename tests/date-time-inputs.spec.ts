import { expect, test } from '@playwright/test'

test('static input group affixes focus an independently labeled and described field', async ({ page }) => {
  await page.goto('/?component=W.input-group')
  const price = page.getByRole('group', { name: '单次授权价格' })
  const amount = price.getByRole('textbox', { name: '授权金额' })
  await expect(amount).toHaveAccessibleDescription('按美元记录，可输入两位小数。')
  await price.getByText('USD', { exact: true }).click()
  await expect(amount).toBeFocused()
  await expect(price).toHaveCSS('outline-width', '2px')
  await expect(price).toHaveCSS('outline-offset', '-2px')
  await expect(price).toHaveCSS('--sy-field-ring-paint', 'transparent')
  await amount.fill('19.50')
  await expect(amount).toHaveValue('19.50')

  const site = page.getByRole('group', { name: '交付站点' })
  await site.getByText('https://', { exact: true }).click()
  await expect(site.getByRole('textbox', { name: '站点名称' })).toBeFocused()
  await expect(site.getByText('.example.com', { exact: true })).toBeVisible()
})

test('a range trigger shows two months and applies only eligible presets', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/?component=W.date-range-picker')
  const scene = page.getByRole('region', { name: '统计周期预设' })
  const trigger = scene.getByRole('button', { name: /^设置报告周期/ })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.sy-calendar__month')).toHaveCount(2)
  const presets = dialog.getByRole('group', { name: '常用统计周期' })
  await expect(presets.getByRole('button', { name: '近 90 天' })).toBeDisabled()
  await presets.getByRole('button', { name: '近 30 天' }).click()
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(scene.locator('.review__result')).toContainText('2026-10-26 至 2026-11-24')
  await trigger.press('Enter')
  await expect(presets.getByRole('button', { name: '近 30 天' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await expect(scene.getByRole('button', { name: /^设置待调整的档期/ })).toHaveAccessibleDescription('此时段已被占用。')
})

test('desktop date-time popover edits and clears one combined value', async ({ page }) => {
  await page.goto('/?component=W.date-time-input')
  const scene = page.getByRole('region', { name: '日期时间组合用法' })
  const trigger = scene.getByRole('button', { name: '设置交付时间' })
  const result = scene.locator('.review__result')
  await trigger.click()
  const popup = page.getByRole('dialog', { name: '设置交付时间' })
  await expect(popup.locator('.sy-calendar__day[data-value="2026-11-21"]')).toBeFocused()
  await expect(popup.locator('.sy-calendar__day[data-value="2026-11-17"]')).toHaveAttribute('aria-disabled', 'true')
  await popup.locator('.sy-calendar__day[data-value="2026-11-24"]').click()
  await expect(result).toContainText('2026-11-24T15:30:00')
  const time = popup.getByRole('group', { name: '时刻', exact: true })
  const minute = time.getByRole('spinbutton', { name: '分钟', exact: true })
  await minute.press('ArrowUp')
  await expect(result).toContainText('2026-11-24T15:45:00')
  await popup.getByRole('button', { name: '完成', exact: true }).click()
  await expect(trigger).toBeFocused()
  await scene.getByRole('button', { name: '清除交付时间' }).click()
  await expect(result).toContainText('尚未设置交付时间')
  await expect(scene.getByRole('group', { name: '交付时间', exact: true }).getByRole('spinbutton').first()).toBeFocused()
  await trigger.click()
  await expect(popup.getByRole('group', { name: '时刻', exact: true })).toHaveAttribute('aria-disabled', 'true')
})

test('desktop time segments retain an out-of-range draft until it is corrected', async ({ page }) => {
  await page.goto('/?component=W.time-field')
  const scene = page.getByRole('region', { name: '时间格式和时段' })
  const field = scene.getByRole('group', { name: '预约时刻' })
  const hour = field.getByRole('spinbutton', { name: '小时', exact: true })
  const minute = field.getByRole('spinbutton', { name: '分钟', exact: true })
  await hour.press('0')
  await hour.press('8')
  await minute.press('0')
  await minute.press('0')
  await expect(field).toHaveAttribute('aria-invalid', 'true')
  await expect(hour).toHaveAttribute('aria-valuenow', '8')
  await expect(scene.locator('.review__result')).toContainText('尚未预约')
  await hour.press('ArrowUp')
  await expect(field).not.toHaveAttribute('aria-invalid', 'true')
  await minute.press('ArrowUp')
  await expect(scene.locator('.review__result')).toContainText('预约 09:15:00')
})

test.describe('touch scheduling', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })

  test('touch time uses a native picker with constraints while formats retain segmented editing', async ({ page }) => {
    await page.goto('/?component=W.time-field')
    const scene = page.getByRole('region', { name: '时间格式和时段' })
    const appointment = scene.getByLabel('预约时刻', { exact: true })
    await expect(appointment).toHaveAttribute('type', 'time')
    await expect(appointment).toHaveAttribute('min', '09:00')
    await expect(appointment).toHaveAttribute('max', '17:30')
    await expect(appointment).toHaveAttribute('step', '900')
    await appointment.fill('08:00')
    await expect(appointment).toHaveAttribute('aria-invalid', 'true')
    await expect(appointment).toHaveValue('08:00')
    await expect(scene.locator('.review__result')).toContainText('尚未预约')
    await appointment.fill('09:15')
    await expect(appointment).not.toHaveAttribute('aria-invalid', 'true')
    await expect(scene.locator('.review__result')).toContainText('预约 09:15:00')
    await expect(scene.getByRole('group', { name: '12 小时制' }).locator('[data-sy-part="dayPeriod"]')).toHaveCount(1)
    await expect(scene.getByRole('group', { name: '24 小时制' }).locator('[data-sy-part="dayPeriod"]')).toHaveCount(0)
    await expect(scene.getByRole('group', { name: '精确到秒' }).locator('[data-sy-part="second"]')).toHaveCount(1)
  })

  test('touch date and time use a sheet with animated tabs and restore the opener', async ({ page }) => {
    await page.goto('/?component=W.date-time-input')
    const scene = page.getByRole('region', { name: '日期时间组合用法' })
    const trigger = scene.getByRole('button', { name: '设置交付时间' })
    await trigger.tap()
    const sheet = page.getByRole('dialog', { name: '设置交付日期和时间' })
    await expect(sheet).toHaveAttribute('aria-modal', 'true')
    await expect.poll(async () => (await sheet.boundingBox())!.height).toBeLessThan(520)
    await expect(sheet.getByRole('tab', { name: '日期' })).toHaveAttribute('aria-selected', 'true')
    await sheet.locator('.sy-calendar__day[data-value="2026-11-20"]').tap()
    await sheet.getByRole('tab', { name: '时刻' }).tap()
    const panel = sheet.getByRole('tabpanel', { name: '时刻' })
    await expect(panel).toHaveCSS('animation-name', 'sy-tab-reveal')
    await panel.getByRole('spinbutton', { name: '分钟', exact: true }).press('ArrowDown')
    await expect(scene.locator('.review__result')).toContainText('2026-11-20T15:15:00')
    await sheet.getByRole('button', { name: '完成', exact: true }).tap()
    await expect(sheet).toBeHidden()
    await expect(trigger).toBeFocused()
  })
})
