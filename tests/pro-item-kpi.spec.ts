import { expect, test } from '@playwright/test'

test('keeps resource controls independent and preserves the button and row sizes during a download', async ({ page }) => {
  await page.goto('/?component=WP.item-card')
  const sample = page.getByRole('region', { name: '组件示例' })
  const lead = sample.getByRole('button', { name: '品牌交付包' })
  const download = sample.getByRole('button', { name: '下载', exact: true })
  const card = sample.locator('.sy-item-card').first()
  const size = await card.boundingBox()
  const buttonSize = await download.boundingBox()
  await expect(lead).toHaveAccessibleDescription('允许团队下载整理后的文件。')
  await download.click()
  await expect(download).toHaveAttribute('aria-busy', 'true')
  expect(await card.boundingBox()).toEqual(size)
  expect(await download.boundingBox()).toEqual(buttonSize)
  await expect(sample.getByRole('status')).not.toContainText('已打开')
  await expect(card.locator('.sy-item-card__status .sy-visually-hidden')).toHaveText('存档 3 份')
  await expect(download).not.toHaveAttribute('aria-busy', 'true')
  expect(await card.boundingBox()).toEqual(size)
  expect(await download.boundingBox()).toEqual(buttonSize)
  await lead.press('Enter')
  await expect(sample.getByRole('status')).toContainText('已打开品牌交付包')
  const toggle = sample.getByRole('switch', { name: '自动同步' })
  await expect(toggle).toBeChecked()
  await toggle.press('Space')
  await expect(toggle).not.toBeChecked()
  await expect(sample.getByRole('link', { name: '历史快照' })).toBeDisabled()
  await sample.getByRole('combobox', { name: '共享范围' }).press('ArrowDown')
  await page.getByRole('option', { name: '指定成员' }).click()
  await expect(sample.getByRole('combobox', { name: '共享范围' })).toContainText('指定成员')
})

test('groups resources in semantic lists and adapts the tile width to the actual container', async ({ page }) => {
  await page.setViewportSize({ width: 1360, height: 850 })
  await page.goto('/?component=WP.item-card-group')
  const rows = page.getByRole('region', { name: '交付文件' }).getByRole('listitem')
  const gallery = page.getByRole('region', { name: '项目资料库' })
  const tiles = page.locator('.review-resource-grid .sy-item-card')
  await expect(rows).toHaveCount(3)
  await expect(gallery.getByRole('listitem')).toHaveCount(3)
  await expect(page.getByRole('region', { name: '交付文件' }).getByRole('list')).toHaveCSS('background-color', 'rgb(248, 248, 248)')
  expect(await rows.nth(1).evaluate(node => getComputedStyle(node, '::before').content)).toBe('none')
  const wide = await tiles.evaluateAll(items => items.map(item => item.getBoundingClientRect().y))
  expect(new Set(wide).size).toBe(1)
  await gallery.evaluate(node => { node.style.inlineSize = '33rem' })
  const middle = await tiles.evaluateAll(items => items.map(item => item.getBoundingClientRect().y))
  expect(new Set(middle).size).toBe(2)
  await gallery.evaluate(node => { node.style.inlineSize = '' })
  await page.setViewportSize({ width: 390, height: 780 })
  const narrow = await tiles.evaluateAll(items => items.map(item => item.getBoundingClientRect().y))
  expect(new Set(narrow).size).toBe(3)
  const sample = page.getByRole('region', { name: '组件示例' })
  expect(await sample.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
})

test('inspects KPI chart gaps with the keyboard and connects gaps without moving the numeric region', async ({ page }) => {
  await page.goto('/?component=WP.kpi')
  const card = page.getByRole('article', { name: '资源下载量' })
  const plot = card.getByRole('slider', { name: '每日下载趋势' })
  const path = card.locator('.sy-kpi-sparkline__series path')
  const size = await card.boundingBox()
  await expect(path).toHaveAttribute('d', /M.*M/)
  await plot.press('Home')
  await expect(plot).toHaveAttribute('aria-valuetext', '11 月 14 日 · 24')
  await plot.press('ArrowRight')
  await plot.press('ArrowRight')
  await expect(plot).toHaveAttribute('aria-valuetext', '11 月 16 日 · 无记录')
  await expect(card.locator('.sy-kpi-sparkline__mark')).toHaveAttribute('data-gap', 'true')
  await plot.press('Escape')
  await expect(card.locator('.sy-kpi-sparkline__text')).toHaveCount(0)
  const toggle = card.getByRole('switch', { name: '连接缺口' })
  await toggle.click()
  await expect(path).toHaveCount(1)
  await expect(path).not.toHaveAttribute('d', /M.*M/)
  expect(await card.boundingBox()).toEqual(size)
  await expect(page.getByRole('progressbar', { name: '已校验文件' })).toHaveAttribute('aria-valuenow', '72')
  await expect(page.getByRole('img', { name: '近期响应时间趋势' })).toHaveCount(1)
})

test('updates only changed digits and keeps a repeated chart update consistent with reduced motion', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=WP.kpi')
  const card = page.getByRole('article', { name: '资源下载量' })
  const value = card.locator('.sy-kpi__value .sy-number-value__readout')
  const sample = await value.locator('.sy-motion-text__glyph').first().elementHandle()
  expect(sample).not.toBeNull()
  const path = card.locator('.sy-kpi-sparkline__series path')
  const initialPath = await path.getAttribute('d')
  const valueBounds = await value.boundingBox()
  const button = card.getByRole('button', { name: '切换周期' })
  await button.click()
  await expect(value.locator('.sy-visually-hidden')).toHaveText('1,468')
  expect(await value.boundingBox()).toEqual(valueBounds)
  expect(await value.locator('.sy-motion-text__glyph').first().evaluate((node, before) => node === before, sample)).toBe(true)
  expect(await path.getAttribute('d')).not.toEqual(initialPath)
  await button.click()
  await expect(value.locator('.sy-visually-hidden')).toHaveText('1,428')
  await expect(path).toHaveAttribute('d', initialPath ?? '')
})

test('keeps horizontal KPI tiles equal and stacks the group on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 1360, height: 850 })
  await page.goto('/?component=WP.kpi-group')
  const weekly = page.getByRole('region', { name: '本周交付' })
  const tiles = page.locator('.review-metric-groups__weekly .sy-kpi')
  await expect(weekly.getByRole('article')).toHaveCount(3)
  const size = () => tiles.evaluateAll(items => items.map(item => {
    const { y, width } = item.getBoundingClientRect()
    return { y, width }
  }))
  const wide = await size()
  expect(new Set(wide.map(box => box.y)).size).toBe(1)
  expect(Math.max(...wide.map(box => box.width)) - Math.min(...wide.map(box => box.width))).toBeLessThan(1)
  const archive = page.getByRole('region', { name: '归档情况' })
  await expect(archive).toHaveAttribute('data-orientation', 'vertical')
  await page.setViewportSize({ width: 390, height: 760 })
  const narrow = await size()
  expect(new Set(narrow.map(box => box.y)).size).toBe(3)
  expect(new Set(narrow.map(box => box.width)).size).toBe(1)
  expect(await weekly.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
})
