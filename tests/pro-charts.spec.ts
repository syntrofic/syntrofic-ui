import { expect, test } from '@playwright/test'

test('WebGL dots share scale and selection with the other series in a composed chart', async ({ page }) => {
  await page.goto('/?component=WP.composed-chart')
  const plot = page.getByRole('slider', { name: '交付量与通过率', exact: true })
  const svgDot = plot.locator('g[data-series="audit"] circle').first()
  await expect(svgDot).toBeVisible()
  await page.getByRole('switch', { name: '使用 WebGL 散点' }).click()
  const canvas = plot.locator('canvas[data-series="audit"]')
  await expect(canvas).toBeVisible()
  const supportsWebGL = await page.evaluate(() => Boolean(document.createElement('canvas').getContext('webgl2')))
  if (supportsWebGL) {
    await expect(canvas).toHaveAttribute('data-ready', 'true')
    await expect(svgDot).toBeHidden()
    const bounds = await canvas.boundingBox()
    if (!bounds) throw new Error('Missing composed plot bounds')
    await page.mouse.move(bounds.x + Number(await svgDot.getAttribute('cx')), bounds.y + Number(await svgDot.getAttribute('cy')))
    await expect(plot).toHaveAttribute('aria-valuetext', /周三.*抽查通过率 74/)
  } else {
    await expect(svgDot).toBeVisible()
  }
  await expect(plot.locator('[data-mark="bar"] rect').first()).toBeVisible()
  await plot.press('End')
  await expect(plot).toHaveAttribute('aria-valuetext', /周日.*抽查通过率 94/)
})

