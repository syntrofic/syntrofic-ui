test('formats tooltip rows by unit and changes only updated digits without moving its control', async ({ page }) => {
  await page.goto('/?component=WP.chart-tooltip')
  const card = page.locator('.review-tooltip-card')
  const value = card.locator('.sy-chart-tooltip__row').first().locator('dd')
  const firstDigit = await value.locator('.sy-motion-text__glyph').first().elementHandle()
  const change = page.getByRole('button', { name: '切换批次' })
  const buttonSize = await change.boundingBox()
  await expect(card.locator('.sy-chart-tooltip__row').last()).toContainText('无记录')
  await change.click()
  await expect(value.locator('.sy-visually-hidden')).toHaveText('1,468 份')
  expect(await value.locator('.sy-motion-text__glyph').first().evaluate((node, before) => node === before, firstDigit)).toBe(true)
  expect(await change.boundingBox()).toEqual(buttonSize)
  const plot = page.getByRole('slider', { name: '处理量趋势' })
  await plot.press('Home')
  await expect(page.locator('.review-charts__main .sy-chart-tooltip__footer')).toHaveText('当日校验快照')
  await page.setViewportSize({ width: 390, height: 760 })
  await plot.press('End')
  const bounds = await plot.boundingBox()
  const tooltip = page.locator('.review-charts__main .sy-chart__inspection')
  await expect.poll(async () => {
    const panel = await tooltip.boundingBox()
    return bounds && panel && panel.x >= bounds.x - 1 && panel.x + panel.width <= bounds.x + bounds.width + 1
  }).toBe(true)
})

test('renders distinct marks and units on independent axes while exposing the exact values in a table', async ({ page }) => {
  await page.goto('/?component=WP.composed-chart')
  const plot = page.getByRole('slider', { name: '交付量与通过率' })
  await expect(plot.locator('path.sy-chart__area')).toHaveCount(2)
  await expect(plot.locator('[data-mark="bar"] rect')).toHaveCount(7)
  await expect(plot.locator('[data-whiskers="interval"] path')).toHaveCount(6)
  await expect(plot.locator('[data-whiskers="interval"] path[data-index="2"]')).toHaveCount(0)
  await expect(plot.locator('[data-mark="dot"] circle')).toHaveCount(3)
  await expect(plot.locator('[data-mark="dot"] path')).toHaveCount(0)
  await expect(plot.locator('.sy-chart__reference-bands rect')).toHaveCount(1)
  const reviewDay = plot.locator('.sy-chart__reference').filter({ hasText: '评审日' }).locator('line')
  expect(await reviewDay.getAttribute('x1')).toBe(await reviewDay.getAttribute('x2'))
  await expect(plot.locator('.sy-chart__reference').filter({ hasText: '通过率目标' })).toBeVisible()
  await expect(plot.locator('[data-mark="line"] path')).toHaveAttribute('stroke-dasharray', '5 4')
  await expect(plot.locator('[data-axis="right"]')).toContainText('100%')
  const bottomEdge = plot.locator('[data-edge="bottom"] .sy-chart-axis__line').first()
  await expect(bottomEdge).toHaveCSS('stroke-width', '1px')
  expect(await bottomEdge.evaluate(node => node.getBoundingClientRect().width)).toBeGreaterThan(0)
  await expect(plot.locator('.sy-chart__grid line')).toHaveCount(11)
  const legend = page.getByRole('list', { name: '系列', exact: true })
  await expect(legend.locator('[data-indicator="square"]')).toHaveCount(1)
  await expect(legend.locator('[data-indicator="dashed"]')).toHaveCount(1)
  await expect.poll(async () => {
    const [legendBounds, chartBounds] = await Promise.all([legend.boundingBox(), plot.boundingBox()])
    return Boolean(legendBounds && chartBounds && legendBounds.y + legendBounds.height <= chartBounds.y)
  }).toBe(true)
  await plot.press('End')
  await expect(plot).toHaveAttribute('aria-valuetext', /周日, 目标 45 份, 交付 52 份, 通过率 92%/)
  await page.getByRole('button', { name: '查看数据' }).click()
  const table = page.getByRole('table', { name: '交付量与通过率' })
  await expect(table.getByRole('rowheader', { name: '周日' })).toBeVisible()
  await expect(table.getByRole('cell', { name: '92%', exact: true })).toBeVisible()
})

test('continuous chart positions samples by time and preserves exact ticks for an empty streaming window', async ({ page }) => {
  await page.goto('/?component=WP.composed-chart')
  const plot = page.getByRole('slider', { name: '实时采样' })
  const dots = plot.locator('.sy-chart__point')
  const axis = plot.locator('[data-edge="bottom"]')
  const getPositions = () => dots.evaluateAll(nodes => nodes.map(node => Number(node.getAttribute('cx'))))
  await expect(dots).toHaveCount(3)
  const [first, second, last] = await getPositions()
  expect(first).toBeGreaterThan(48)
  expect((second - first) / (last - first)).toBeCloseTo(1 / 3)
  await expect(axis.locator('text')).toHaveText(['08:00', '09:00', '10:00', '11:00'])
  await expect(plot.locator('.sy-chart__reference-bands rect')).toHaveAttribute('x', String(second))
  await expect(plot.locator('[data-sample-marker]')).toHaveAttribute('x1', String(second))
  await expect(plot.locator('[data-edge="left"]')).toContainText(/[-−]40/)
  await plot.press('Home')
  await expect(plot).toHaveAttribute('aria-valuetext', '08:00, 通过量 20 份')
  await plot.press('ArrowRight')
  await expect(plot).toHaveAttribute('aria-valuetext', '09:00, 通过量 32 份')
  await page.getByRole('switch', { name: '缩小时间窗口' }).check()
  await expect(dots).toHaveCount(2)
  await plot.press('Home')
  await expect(plot).toHaveAttribute('aria-valuetext', '09:00, 通过量 32 份')
  await expect(axis.locator('text')).toHaveText(['09:00', '09:40', '10:20', '11:00'])
  await page.getByRole('switch', { name: '清空采样' }).check()
  const empty = page.getByRole('img', { name: '实时采样 · 暂无数据' })
  await expect(empty.locator('[data-edge="bottom"] text')).toHaveText(['09:00', '09:40', '10:20', '11:00'])
  await expect(empty.locator('.sy-chart__point')).toHaveCount(0)
})

