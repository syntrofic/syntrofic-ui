test('changes radial values and arc lengths without resizing the plot or its switch', async ({ page }) => {
  await page.goto('/?component=WP.radial-chart')
  const plot = page.getByRole('slider', { name: '项目推进' })
  const marks = plot.locator('path.sy-chart__arc')
  await expect(marks).toHaveCount(3)
  const original = await marks.first().getAttribute('d')
  const before = await plot.boundingBox()
  const switcher = page.getByRole('switch', { name: '查看本组进度' })
  const button = await switcher.boundingBox()
  await switcher.check()
  await expect(plot).toHaveAccessibleDescription(/复核进度 88%/)
  await expect(marks.first()).not.toHaveAttribute('d', original ?? '')
  expect(await plot.boundingBox()).toEqual(before)
  expect(await switcher.boundingBox()).toEqual(button)
  await plot.press('End')
  await expect(plot).toHaveAttribute('aria-valuetext', '归档, 完成率 62%')
  const full = page.getByRole('slider', { name: '单项归档进度' })
  await expect(full.locator('.sy-chart__track')).toHaveAttribute('d', /A.*A/)
})
