import { expect, test } from '@playwright/test'

test('edits half-step ratings with pointer and keyboard and restores native form values', async ({ page }) => {
  await page.goto('/?component=WP.rating')
  const slider = page.getByRole('slider', { name: '编辑评分' })
  const row = page.locator('.rating-showcase__row').first()
  const fourth = row.locator('.sy-rating__cell').nth(3)
  await expect(slider).toHaveValue('3.5')
  await expect(fourth).toHaveCSS('--sy-rating-fill', '50%')
  await slider.press('ArrowRight')
  await expect(slider).toHaveValue('4')
  await fourth.click({ position: { x: 4, y: 8 } })
  await expect(slider).toBeFocused()
  await expect(slider).toHaveAttribute('aria-valuetext', '3.5 / 5 分')
  await slider.press('Home')
  await expect(slider).toHaveValue('0')
  await slider.press('End')
  await expect(slider).toHaveValue('5')
  await page.getByRole('button', { name: '提交评分' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已提交 5 分')
  await page.getByRole('button', { name: '恢复初始值' }).click()
  await expect(slider).toHaveValue('3.5')
  await slider.press('Delete')
  await expect(slider).toHaveValue('0')
  await expect(page.getByRole('slider', { name: '平均评分' })).toHaveCount(0)
  await expect(page.getByRole('slider', { name: '评分已关闭' })).toBeDisabled()
})

test('searches localized emoji, switches tone and category, and navigates a virtual grid', async ({ page }) => {
  await page.goto('/?component=WP.emoji-picker')
  const grid = page.getByRole('grid', { name: '表情结果' })
  const search = page.getByRole('searchbox', { name: '搜索表情' })
  await expect(grid.getByRole('gridcell').first()).toBeVisible()
  expect(await grid.getByRole('gridcell').count()).toBeLessThan(80)
  expect(Number(await grid.getAttribute('aria-rowcount'))).toBeGreaterThan(100)
  await grid.focus()
  await grid.press('Control+End')
  const active = await grid.getAttribute('aria-activedescendant')
  await expect(grid.locator(`[id="${active}"]`)).toBeInViewport()
  const category = page.getByRole('combobox', { name: '表情类别' })
  await category.selectOption({ label: '动物与自然' })
  await expect(category.locator('option:checked')).toHaveText('动物与自然')
  await search.fill('挥手')
  await page.getByRole('combobox', { name: '肤色' }).selectOption('3')
  const hand = grid.getByRole('gridcell', { name: /挥手.*中等肤色/ })
  await expect(hand).toHaveText('👋🏽')
  await search.press('ArrowDown')
  await expect(grid).toBeFocused()
  await grid.press('Enter')
  await expect(page.locator('.review__result')).toContainText('👋🏽')
  await page.getByRole('button', { name: '最近使用' }).click()
  await expect(hand).toBeVisible()
})

test('selects emoji from a mobile popover and restores the trigger on select and Escape', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 680 })
  await page.goto('/?component=WP.emoji-picker')
  const trigger = page.getByRole('button', { name: '打开浮层选择器' })
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog', { name: '打开浮层选择器' })
  const search = dialog.getByRole('searchbox', { name: 'Search emoji' })
  await expect(search).toBeFocused()
  expect((await dialog.boundingBox())!.width).toBeLessThanOrEqual(300)
  await search.fill('fox')
  await expect(dialog.getByRole('gridcell', { name: 'fox', exact: true })).toBeVisible()
  await search.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  await expect(page.locator('.review__result')).toContainText('🦊')
  await trigger.press('Space')
  await search.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
})

test('updates reactions without changing button width and adds or undoes a picked reaction', async ({ page }) => {
  await page.goto('/?component=WP.emoji-reaction-button')
  const likes = page.getByRole('button', { name: /赞，\d+ 个反应/ })
  await expect(likes).toHaveAccessibleName('赞，99 个反应')
  const width = (await likes.boundingBox())!.width
  await likes.click()
  await expect(likes).toHaveAccessibleName('赞，100 个反应')
  await expect(likes).toHaveAttribute('aria-pressed', 'true')
  expect((await likes.boundingBox())!.width).toBeCloseTo(width, 1)
  await likes.press('Space')
  await expect(likes).toHaveAccessibleName('赞，99 个反应')
  await expect(likes).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: /举双手/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: /闪光/ })).toHaveCount(0)

  await page.getByRole('button', { name: '添加表情' }).click()
  const dialog = page.getByRole('dialog', { name: '添加表情' })
  await dialog.getByRole('searchbox', { name: '搜索表情' }).fill('火箭')
  await dialog.getByRole('gridcell', { name: '火箭', exact: true }).click()
  await expect(dialog).toBeHidden()
  const rocket = page.getByRole('button', { name: /火箭/ })
  await expect(rocket).toHaveAccessibleName('火箭，1 个反应')
  await expect(rocket).toHaveAttribute('aria-pressed', 'true')
  await rocket.press('Enter')
  await expect(rocket).toHaveAccessibleName('火箭，0 个反应')
  await expect(rocket).toHaveAttribute('aria-pressed', 'false')
})
