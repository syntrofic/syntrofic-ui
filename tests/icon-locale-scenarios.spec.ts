import { expect, test } from '@playwright/test'

test('icon samples render semantic and named colors, size tokens and status artwork', async ({ page }) => {
  await page.goto('/?component=W.icon')
  const icons = page.getByRole('region', { name: '图标颜色、尺寸与状态' })
  const semantic = icons.getByRole('list', { name: '语义颜色' })
  await expect(semantic.locator('svg path')).toHaveCount(8)
  const named = icons.getByRole('list', { name: '指定颜色' })
  await expect(named.locator('svg[data-color]')).toHaveCount(10)
  expect(await named.locator('[data-color="pink"]').evaluate(icon => getComputedStyle(icon).color))
    .not.toBe(await named.locator('[data-color="purple"]').evaluate(icon => getComputedStyle(icon).color))
  const sizes = icons.getByRole('list', { name: '图标尺寸' }).locator('svg')
  await expect(sizes.first()).toHaveCSS('width', '12px')
  await expect(sizes.last()).toHaveCSS('width', '24px')
  const statuses = icons.getByRole('list', { name: '发布状态' })
  await expect(statuses.getByRole('listitem').filter({ hasText: '校验失败' }).locator('svg')).toHaveAttribute('data-color', 'error')
  await expect(statuses.getByRole('img')).toHaveCount(0)
})

test('theme switching updates resolved tokens without changing nested themes or control state', async ({ page }) => {
  await page.goto('/?component=W.brand-theme')
  const stage = page.getByRole('region', { name: '应用与切换主题' })
  const outer = stage.getByRole('region', { name: '外层工作区' })
  const nested = stage.getByRole('region', { name: '局部出版区' })
  const sameContent = page.getByRole('region', { name: '并列主题对照' })
  const token = (region: typeof outer) => region.locator('dd .sy-visually-hidden').last()
  await expect(outer.locator('dd .sy-visually-hidden').first()).toHaveText('studio-sage')
  await expect(nested.locator('dd .sy-visually-hidden').first()).toHaveText('studio-ink')
  const sage = await token(outer).textContent()
  const ink = await token(nested).textContent()
  expect(sage).not.toBe(ink)
  await expect(token(sameContent.getByRole('region', { name: '灰绿工作区' }))).toHaveText(sage!)
  await expect(token(sameContent.getByRole('region', { name: '灰紫工作区' }))).toHaveText(ink!)
  const save = outer.getByRole('button', { name: '保存此主题示例' })
  await save.click()
  await stage.getByRole('button', { name: '陶土' }).click()
  await expect(outer.locator('dd .sy-visually-hidden').first()).toHaveText('studio-clay')
  await expect(token(outer)).not.toHaveText(sage!)
  await expect(token(nested)).toHaveText(ink!)
  await expect(save).toHaveAttribute('aria-pressed', 'true')
})

