test('explicit RTL changes pagination order while the direction hook flips a chart', async ({ page }) => {
  await page.goto('/?component=W.internationalization-provider')
  const sample = page.getByRole('region', { name: '双向布局与分页' })
  const pagination = sample.getByRole('navigation', { name: '发布记录分页' })
  const previous = pagination.getByRole('button', { name: '前一页发布记录' })
  const next = pagination.getByRole('button', { name: '后一页发布记录' })
  const chart = sample.getByRole('img', { name: '按阅读方向显示的发布量趋势' })
  await expect(chart).toHaveAttribute('data-direction', 'ltr')
  expect((await previous.boundingBox())!.x).toBeLessThan((await next.boundingBox())!.x)
  await sample.getByRole('button', { name: '从右往左' }).click()
  await expect(sample.locator('[data-explicit-direction]')).toHaveAttribute('dir', 'rtl')
  await expect(chart).toHaveAttribute('data-direction', 'rtl')
  await expect(chart.locator('g')).toHaveCSS('transform', 'matrix(-1, 0, 0, 1, 0, 0)')
  expect((await previous.boundingBox())!.x).toBeGreaterThan((await next.boundingBox())!.x)
  await next.press('Enter')
  await expect(pagination).toContainText('3')
})

test('narrow labels follow their own script while mixed labels follow the layout', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 820 })
  await page.goto('/?component=W.internationalization-provider')
  const sample = page.getByRole('region', { name: '窄控件的双向文字' })
  const preview = sample.locator('[data-label-direction-preview]')
  const labels = preview.locator('.sy-button__label, .sy-badge__label, .sy-chip__label, [data-segment-value="review"] .sy-segment__text, '
    + '.sy-navbar__brand-title, .sy-chat-tool__title, [data-table-cut]')
  const expectDirections = async (direction: 'rtl' | 'ltr', explicit = true) => {
    await expect(labels).toHaveCount(8)
    for (const label of await labels.all()) {
      if (explicit) await expect(label).toHaveAttribute('dir', direction)
      else await expect(label).not.toHaveAttribute('dir')
      await expect(label).toHaveCSS('direction', direction)
    }
  }
  const arabic = 'مراجعة مستندات الإصدار والإتاحة ٢٠٢٦'
  const button = preview.locator('[data-sample-button]')
  await expect(preview.getByRole('button', { name: arabic, exact: true }).first()).toBeVisible()
  await expect(preview.getByRole('columnheader', { name: arabic, exact: true })).toBeVisible()
  await preview.evaluate(() => document.fonts.ready)
  await expectDirections('rtl')
  const clipped = preview.locator('.sy-button__label, .sy-badge__label, .sy-chip__label, [data-segment-value="review"] .sy-segment__text, '
    + '.sy-navbar__brand-title .sy-motion-text__truncated:not(.sy-truncated-text-leave-active), .sy-chat-tool__title, [data-table-cut]')
  const expectClipped = async () => {
    await expect(clipped).toHaveCount(8)
    for (const label of await clipped.all()) {
      await expect(label).toHaveCSS('text-overflow', 'ellipsis')
      await expect.poll(() => label.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
    }
  }
  await expectClipped()
  const layout = () => button.evaluate(node => {
    const button = node.getBoundingClientRect()
    const icon = node.querySelector('.sy-button__start')!.getBoundingClientRect()
    return { width: button.width, height: button.height, start: icon.x - button.x }
  })
  const before = await layout()
  const brand = preview.locator('.sy-navbar__brand-title')
  await brand.evaluate(element => element.addEventListener('transitionrun', event => {
    if (event.target instanceof HTMLElement && event.propertyName === 'opacity') {
      element.setAttribute('data-test-label-easing', getComputedStyle(event.target).transitionTimingFunction)
    }
  }))
  await sample.getByRole('button', { name: '希伯来文' }).press('Enter')
  await expectDirections('rtl')
  await expectClipped()
  await expect(brand).toHaveAttribute('data-test-label-easing', /cubic-bezier/)
  expect(await layout()).toEqual(before)

  await sample.getByRole('button', { name: '混合文字' }).press('Enter')
  await expectDirections('ltr', false)
  await page.getByRole('region', { name: '双向布局与分页' }).getByRole('button', { name: '从右往左' }).press('Enter')
  await expectDirections('rtl', false)
  await sample.getByRole('button', { name: '拉丁文' }).press('Enter')
  await expectDirections('ltr')
  await expect(preview.getByRole('cell', { name: '+2026 Release accessibility review', exact: true })).toBeVisible()
  const reversed = await layout()
  expect(reversed.width).toBe(before.width)
  expect(reversed.height).toBe(before.height)
  expect(reversed.start).toBeGreaterThan(before.start)

  await page.emulateMedia({ reducedMotion: 'reduce' })
  await sample.getByRole('button', { name: '阿拉伯文' }).press('Enter')
  const currentLabel = brand.locator('.sy-motion-text__truncated:not(.sy-truncated-text-leave-active)')
  await expect(currentLabel).toHaveText(arabic)
  await expect(currentLabel).toHaveCSS('opacity', '1')
  await expect(brand.locator('.sy-motion-text__truncated')).toHaveCount(1)
  expect(await brand.evaluate(node => node.getAnimations({ subtree: true }).length)).toBe(0)
})

test('changing calendar systems preserves the ISO value and selecting a date updates it', async ({ page }) => {
  await page.goto('/?component=W.internationalization-provider')
  const sample = page.getByRole('region', { name: '多历法日期选择' })
  const calendar = sample.getByRole('group', { name: '交付日历' })
  const output = sample.getByRole('status', { name: '日期保存值' }).locator('.sy-visually-hidden')
  const year = sample.getByRole('spinbutton', { name: 'year' })
  await expect(calendar).toHaveAttribute('data-calendar', 'japanese')
  await expect(year).toHaveAttribute('aria-valuenow', '8')
  await expect(output).toHaveText('2026-11-22')
  await sample.getByRole('button', { name: '佛历' }).click()
  await expect(calendar).toHaveAttribute('data-calendar', 'buddhist')
  await expect(year).toHaveAttribute('aria-valuenow', '2569')
  await expect(output).toHaveText('2026-11-22')
  await sample.getByRole('spinbutton', { name: 'day', exact: true }).press('ArrowUp')
  await expect(output).toHaveText('2026-11-23')
  await sample.getByRole('button', { name: '公历' }).click()
  await expect(calendar).toHaveAttribute('data-calendar', 'gregory')
  await expect(output).toHaveText('2026-11-23')
  const day = calendar.locator('[data-value="2026-11-25"]')
  await day.click()
  await expect(output).toHaveText('2026-11-25')
})
