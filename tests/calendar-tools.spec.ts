import { expect, test } from '@playwright/test'

test('calendar tools build fixed and variable grids across calendar systems', async ({ page }) => {
  await page.goto('/?component=W.calendar')
  const sample = page.getByRole('region', { name: '日历组合式工具' })
  const grid = sample.getByRole('table', { name: '月份日期' })
  await expect(grid).toHaveAttribute('data-count', '42')
  await expect(grid.getByRole('columnheader').first()).toHaveText('Mon')
  await expect(grid.locator('td').first()).toHaveAttribute('data-date', '2026-10-26')
  await sample.getByRole('checkbox', { name: '周一开头' }).uncheck()
  await expect(grid.getByRole('columnheader').first()).toHaveText('Sun')
  await expect(grid.locator('td').first()).toHaveAttribute('data-date', '2026-11-01')
  await sample.getByRole('checkbox', { name: '固定六周' }).uncheck()
  await expect(grid).toHaveAttribute('data-count', '35')
  await sample.getByLabel('日历系统').selectOption('coptic')
  await expect(grid).toHaveAttribute('data-count', '7')
  await expect(grid.locator('td:not([data-outside])').first()).toHaveAttribute('data-date', '2026-09-06')
  await expect(grid.locator('td:not([data-outside])').first()).toHaveText('1')
  await sample.getByLabel('日历系统').selectOption('hebrew')
  const month = sample.locator('time')
  await expect(month).toHaveAttribute('datetime', '2024-03-11')
  await expect(month).toContainText('Adar II')
  await sample.getByRole('button', { name: '上个月' }).click()
  await expect(month).toHaveAttribute('datetime', '2024-02-10')
  await expect(month).toContainText('Adar I')
})

test('calendar constraints compose with controlled paging and cross-month focus', async ({ page }) => {
  await page.goto('/?component=W.calendar')
  const sample = page.getByRole('region', { name: '日历组合式工具' })
  const cells = sample.getByRole('table')
  const day = (iso: string) => cells.getByRole('button', { name: iso, exact: true })
  await expect(day('2026-11-19')).toBeDisabled()
  await expect(day('2026-11-24')).toBeDisabled()
  await expect(day('2026-11-25')).toBeEnabled()
  await expect(day('2026-11-29')).toBeDisabled()
  await expect(day('2026-11-30')).toBeEnabled()
  await sample.getByRole('checkbox', { name: '限制范围长度' }).uncheck()
  await expect(day('2026-11-24')).toBeEnabled()
  await sample.getByRole('button', { name: '移至下周' }).click()
  await expect(sample.locator('time')).toHaveAttribute('datetime', '2026-12-01')
  await expect(sample.locator('time')).toHaveText('December 2026 – January 2027')
  await expect(sample.getByRole('status', { name: '待聚焦日期' })).toHaveText('2026-12-06')
  await expect(day('2026-12-12')).toBeEnabled()
  await expect(day('2026-12-13')).toBeDisabled()
  await sample.getByRole('button', { name: '清除日期' }).click()
  await expect(sample.getByRole('status', { name: '待聚焦日期' })).toHaveCount(0)
})
