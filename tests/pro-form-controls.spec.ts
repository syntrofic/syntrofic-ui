import { expect, test } from '@playwright/test'

test('validates checkbox card selections and includes every checked value in the form', async ({ page }) => {
  await page.goto('/?component=WP.checkbox-button-group')
  const design = page.getByRole('checkbox', { name: '设计动态' })
  const product = page.getByRole('checkbox', { name: '产品简报' })
  const save = page.getByRole('button', { name: '保存订阅' })
  await expect(design).toBeChecked()
  await expect(design).toHaveAccessibleDescription('设计文件和规范更新')
  await expect(page.getByRole('checkbox', { name: '安全公告' })).toBeDisabled()
  await expect(page.getByRole('checkbox', { name: '电子邮件' })).toBeDisabled()

  await design.press('Space')
  await save.click()
  expect(await design.evaluate(input => (input as HTMLInputElement).validity.customError)).toBe(true)
  await product.press('Space')
  await design.press('Space')
  await save.click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText(/设计动态.*产品简报|产品简报.*设计动态/)
  await page.getByRole('button', { name: '恢复初始值' }).click()
  await expect(design).toBeChecked()
  await expect(product).not.toBeChecked()
})

test('moves the focus ring through radio cards and preserves exclusive form selection', async ({ page }) => {
  await page.goto('/?component=WP.radio-button-group')
  const digital = page.getByRole('radio', { name: '电子交付' })
  const paper = page.getByRole('radio', { name: '纸质邮寄' })
  await expect(digital).toBeChecked()
  const group = page.locator('.sy-choice-buttons').first()
  await digital.focus()
  await expect(group).toHaveAttribute('data-active', '')
  const first = await group.evaluate(node => (node as HTMLElement).style.getPropertyValue('--sy-focus-y'))
  await digital.press('ArrowDown')
  await expect(paper).toBeChecked()
  await expect(digital).not.toBeChecked()
  await expect(paper).toBeFocused()
  await expect(group).toHaveAttribute('data-moving', '')
  expect(await group.evaluate(node => (node as HTMLElement).style.getPropertyValue('--sy-focus-y'))).not.toBe(first)
  await page.getByRole('button', { name: '保存交付方式' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已保存 纸质邮寄')
  await page.getByRole('button', { name: '恢复初始值' }).click()
  await expect(digital).toBeChecked()
})

test('steps with pointer and keyboard, keeps width across digits and caps a held press', async ({ page }) => {
  await page.goto('/?component=WP.number-stepper')
  const count = page.getByRole('spinbutton', { name: '访客人数' })
  const plus = page.getByRole('button', { name: '增加人数' })
  const row = page.locator('.sy-number-stepper').first()
  await expect(count).toHaveValue('9')
  const width = (await row.boundingBox())!.width
  await plus.click()
  await expect(count).toHaveValue('10')
  expect((await row.boundingBox())!.width).toBe(width)
  await count.fill('47')
  await count.press('Tab')
  await expect(count).toHaveValue('47')
  await plus.hover()
  await page.mouse.down()
  await expect(count).toHaveValue('50')
  await page.mouse.up()
  await expect(plus).toBeDisabled()
  await count.press('ArrowDown')
  await expect(count).toHaveValue('49')
  await count.press('Home')
  await expect(count).toHaveValue('1')
  await expect(page.getByRole('button', { name: '减少人数' })).toBeDisabled()
  const speed = page.getByRole('spinbutton', { name: '播放倍速' })
  await page.getByRole('button', { name: '加快速度' }).click()
  await expect(speed).toHaveValue('1.50')
  await expect(page.getByRole('button', { name: '增加名额' })).toBeDisabled()
  await page.getByRole('button', { name: '重置数字' }).click()
  await expect(count).toHaveValue('9')
  await expect(speed).toHaveValue('1.25')
})

test('filters keyboard-picked files, reports failures, retries and submits accepted files', async ({ page }) => {
  await page.goto('/?component=WP.drop-zone')
  const browse = page.getByRole('button', { name: '选择文件', exact: true })
  const input = page.locator('input[type=file][name=attachments]')
  await expect(page.getByRole('button', { name: '选择归档附件' })).toBeDisabled()
  await browse.focus()
  const opening = page.waitForEvent('filechooser')
  await browse.press('Enter')
  const picker = await opening
  await picker.setFiles([
    { name: 'retry-agenda.pdf', mimeType: 'application/pdf', buffer: Buffer.from('agenda') },
    { name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('notes') },
  ])
  const files = page.getByRole('list', { name: '拖放文件' })
  await expect(files.locator('li')).toHaveCount(1)
  await expect(files).toContainText('retry-agenda.pdf')
  await expect(page.locator('.sy-drop-zone__validation .sy-visually-hidden').first()).toContainText('notes.txt · 类型不支持')
  const retry = page.getByRole('button', { name: '重试 retry-agenda.pdf' })
  await expect(retry).toBeEnabled()
  await retry.press('Enter')
  const remove = page.getByRole('button', { name: '移除 retry-agenda.pdf' })
  await expect(remove).toBeFocused()
  await expect(files.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100')
  await page.getByRole('button', { name: '登记附件' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已登记 retry-agenda.pdf')
  await remove.press('Enter')
  await expect(browse).toBeFocused()
  await expect(files.locator('li')).toHaveCount(0)
  expect(await input.evaluate(element => (element as HTMLInputElement).files?.length)).toBe(0)
})

test('uses the same size and count limits for dropped files and preserves accepted files', async ({ page }) => {
  await page.goto('/?component=WP.drop-zone')
  const zone = page.getByRole('group', { name: '拖放文件' })
  const entered = await zone.evaluate(async area => {
    const payload = new DataTransfer()
    payload.items.add(new File(['a'], 'brand.png', { type: 'image/png' }))
    payload.items.add(new File([new Uint8Array(2_000_001)], 'oversize.pdf', { type: 'application/pdf' }))
    payload.items.add(new File(['b'], 'brief.pdf', { type: 'application/pdf' }))
    payload.items.add(new File(['c'], 'preview.jpg', { type: 'image/jpeg' }))
    payload.items.add(new File(['d'], 'extra.pdf', { type: 'application/pdf' }))
    area.dispatchEvent(new DragEvent('dragenter', { dataTransfer: payload, bubbles: true, cancelable: true }))
    await Promise.resolve()
    const highlighted = area.hasAttribute('data-dragging')
    area.dispatchEvent(new DragEvent('drop', { dataTransfer: payload, bubbles: true, cancelable: true }))
    return highlighted
  })
  expect(entered, 'dragging highlights the file target').toBe(true)
  await expect(zone).not.toHaveAttribute('data-dragging', 'true')
  const list = page.getByRole('list', { name: '拖放文件' })
  await expect(list.locator('li')).toHaveCount(3)
  const errors = page.locator('.sy-drop-zone__validation .sy-visually-hidden').first()
  await expect(errors).toContainText('oversize.pdf · 超过文件大小限制')
  await expect(errors).toContainText('extra.pdf · 达到文件数量上限')
  await page.getByRole('button', { name: '登记附件' }).click()
  await expect(page.locator('.review__result .sy-visually-hidden')).toHaveText('已登记 brand.png、brief.pdf、preview.jpg')
})
