import { expect, test } from '@playwright/test'

test('category badges use separate tones and announce a changing unread count', async ({ page }) => {
  await page.goto('/?component=W.badge')
  const categories = page.getByRole('group', { name: '团队和优先级' })
  const colors = await categories.locator('.sy-badge').evaluateAll(badges => badges.map(badge => getComputedStyle(badge).color))
  expect(colors).toHaveLength(9)
  expect(new Set(colors).size).toBe(9)
  await expect(page.getByRole('group', { name: '发布状态' }).locator('.sy-badge__dot')).toHaveCount(5)
  const counter = page.getByLabel('5 条未读回复')
  await expect(counter).toHaveAttribute('role', 'status')
  await page.getByRole('button', { name: '标记为已读' }).press('Enter')
  await expect(page.getByLabel('没有未读回复').locator('.sy-visually-hidden')).toHaveText('0')
})

test('chips present separate activation and removal actions and keep disabled colors visible', async ({ page }) => {
  await page.goto('/?component=W.chip')
  const colorOptions = page.getByRole('group', { name: '禁用标签颜色' }).getByRole('button')
  await expect(colorOptions).toHaveCount(11)
  for (const control of await colorOptions.all()) await expect(control).toBeDisabled()
  const filter = page.getByRole('button', { name: '品牌文件' })
  await expect(filter).toHaveAttribute('aria-pressed', 'false')
  await expect(filter.locator('.sy-badge')).toHaveText('3')
  await expect(filter.locator('svg')).toBeVisible()
  await filter.press('Space')
  await expect(filter).toHaveAttribute('aria-pressed', 'true')
  const region = page.getByRole('region', { name: '标签颜色和操作' })
  await expect(region.getByRole('status').locator('.sy-visually-hidden')).toHaveText('已启用品牌文件筛选')
  const remove = region.getByRole('button', { name: '移除贡献标签文案' })
  await remove.press('Enter')
  await expect(remove).toHaveCount(0)
  await region.getByRole('button', { name: '恢复贡献标签' }).click()
  await expect(remove).toBeVisible()
})

test('keyboard labels resolve platform modifiers, aliases, and menu action hints', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'platform', { get: () => 'Win32' }))
  await page.goto('/?component=W.kbd')
  const section = page.getByRole('region', { name: '组合键和菜单快捷键' })
  await expect(section.locator('p').first().locator('kbd .sy-visually-hidden')).toHaveText(['Control + K', 'Shift + Enter'])
  await expect(section.locator('abbr[title="Backspace"]')).toHaveText('⌫')
  await section.getByRole('button', { name: '文件指令' }).press('Enter')
  const action = page.getByRole('menuitem', { name: /查找文件/ })
  await expect(action.locator('kbd .sy-visually-hidden')).toHaveText('Control + K')
  await action.press('Enter')
  await expect(section.getByRole('status').locator('.sy-visually-hidden')).toHaveText('已选择查找文件')
})

