test('tokenizer hides the field at its limit and keeps form validity and focus through removal and reset', async ({ page }) => {
  await page.goto('/?component=W.tokenizer')
  const approvals = page.getByRole('group', { name: '发布审批人' })
  const input = approvals.getByRole('combobox')
  await expect(input).toHaveAccessibleDescription('最多选择三位审批人。')
  await input.fill('江时')
  await page.getByRole('option', { name: '江时 · 产品设计' }).click()
  await expect(approvals.getByRole('status')).toHaveText('已选满三位审批人。移除后可以继续添加。')
  await expect(input).toBeHidden()
  await expect(approvals.getByRole('button', { name: '移除林舟 · 品牌设计' })).toBeFocused()
  await approvals.getByRole('button', { name: '移除江时 · 产品设计' }).click()
  await expect(input).toBeFocused()
  await expect(page.getByRole('combobox', { name: '继承的发布成员' })).toBeDisabled()
  await expect(page.getByRole('combobox', { name: '复核人员' })).toHaveAccessibleDescription('建议再添加一名复核人员。')

  const reviewForm = page.getByRole('group', { name: '交付评审人' })
  const reviewers = reviewForm.getByRole('combobox')
  await expect(reviewers).toHaveAttribute('aria-required', 'true')
  await expect(reviewers).toHaveAttribute('aria-invalid', 'true')
  await expect(reviewers).toHaveAccessibleDescription('至少添加一名评审人。')
  await reviewers.evaluate(node => node.scrollIntoView({ block: 'center' }))
  await reviewers.fill('周昱')
  expect(await reviewers.evaluate(node => (node as HTMLInputElement).checkValidity())).toBe(false)
  await reviewForm.getByRole('option', { name: '周昱 · 设计系统' }).click()
  await expect(reviewers).toHaveAccessibleDescription('已满足评审要求。')
  expect(await reviewers.evaluate(node => (node as HTMLInputElement).checkValidity())).toBe(true)
  await page.getByRole('button', { name: '保存评审人' }).click()
  await expect(page.getByLabel('已保存评审人').locator('.sy-visually-hidden')).toHaveText('zhou')
  await page.getByRole('button', { name: '重置评审人' }).click()
  await expect(reviewers).toHaveAttribute('aria-invalid', 'true')
  await expect(reviewForm.getByRole('listitem')).toHaveCount(0)
})

test('overflow tokens expand inline or in an anchored layer while keeping selections editable', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 900 })
  await page.goto('/?component=W.tokenizer')
  const inline = page.getByRole('group', { name: '内联展开协作者' })
  const floating = page.getByRole('group', { name: '浮层展开协作者' })
  const inlineCount = inline.getByRole('button', { name: /另有/ })
  const layerCount = floating.getByRole('button', { name: /另有/ })
  await expect(inlineCount).toBeVisible()
  await expect(layerCount).toBeVisible()
  await expect(inline.getByRole('button', { name: '移除许然 · 发布审核' })).toBeHidden()
  await inlineCount.press('Enter')
  await expect(inline.getByRole('button', { name: '移除许然 · 发布审核' })).toBeVisible()
  await expect(inline.getByRole('combobox')).toBeFocused()
  await layerCount.click()
  await expect(inlineCount).toBeVisible()
  const layer = page.getByRole('dialog', { name: '浮层展开协作者' })
  await expect(layer).toBeVisible()
  await expect(layerCount).toHaveAttribute('aria-expanded', 'true')
  await expect(layer.getByRole('button').first()).toBeFocused()
  await layer.getByRole('button', { name: '移除许然 · 发布审核' }).click()
  await expect(layer.getByRole('button', { name: '移除许然 · 发布审核' })).toHaveCount(0)
  await floating.getByRole('combobox').press('Escape')
  await expect(layer).toBeHidden()
  await expect(layerCount).toBeFocused()
})

test('touch tokenizers clear from an accessible bottom sheet', async ({ browser, baseURL }) => {
  const page = await browser.newPage({ baseURL, viewport: { width: 360, height: 900 }, hasTouch: true })
  try {
    await page.goto('/?component=W.tokenizer')
    const tags = page.getByRole('group', { name: '发布标签' })
    const input = tags.getByRole('combobox')
    await input.fill('发布记录')
    await input.press('Enter')
    const clear = tags.getByRole('button', { name: '清空发布标签' })
    await expect(clear).toHaveAttribute('aria-haspopup', 'dialog')
    await clear.tap()
    const sheet = page.getByRole('dialog', { name: '发布标签' })
    await expect(sheet.getByRole('listitem')).toHaveText('发布记录')
    await sheet.getByRole('button', { name: '清空发布标签' }).tap()
    await expect(sheet).toBeHidden()
    await expect(tags.getByRole('listitem')).toHaveCount(0)
    await expect(input).toBeFocused()
  } finally { await page.close() }
})
