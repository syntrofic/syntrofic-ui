import { expect, test } from '@playwright/test'

test('sliders announce formatted values and follow their changing validation state', async ({ page }) => {
  await page.goto('/?component=W.slider')
  const demo = page.getByRole('region', { name: '滑块示例' })
  const temperature = demo.getByRole('slider', { name: '室内温度' })
  await expect(temperature).toHaveAttribute('aria-valuetext', '72 °F')
  await temperature.press('ArrowRight')
  await expect(temperature).toHaveAttribute('aria-valuetext', '74 °F')
  const limit = demo.getByRole('slider', { name: '上传限速' })
  await expect(limit).toHaveAttribute('aria-valuetext', '50%')
  await expect(demo.getByText('最低')).toBeVisible()
  await expect(demo.getByText('最高')).toBeVisible()

  const cpu = demo.getByRole('slider', { name: '处理器占用上限' })
  const slider = cpu.locator('xpath=ancestor::*[contains(@class,"sy-slider-field") and not(contains(@class,"__"))]')
  await expect(cpu).toHaveAccessibleDescription('处理器占用过高，请降低上限。')
  await expect(cpu).toHaveAttribute('aria-invalid', 'true')
  await expect(slider).toHaveAttribute('data-status', 'error')
  await cpu.press('ArrowLeft')
  await cpu.press('ArrowLeft')
  await expect(cpu).toHaveAccessibleDescription('处理器接近建议上限。')
  await expect(cpu).not.toHaveAttribute('aria-invalid')
  await expect(slider).toHaveAttribute('data-status', 'warning')
  await expect(cpu).toBeFocused()
  await cpu.press('Home')
  await expect(cpu).toHaveAccessibleDescription('处理器分配正常。')
  await expect(slider).toHaveAttribute('data-status', 'success')
  await expect(demo.getByRole('slider', { name: '内存分配' })).toHaveAccessibleDescription('已使用一半缓冲区。')
  await expect(demo.getByRole('slider', { name: '磁盘缓存' })).toHaveAccessibleDescription('缓存空间充足。')
})

test('progress stages switch between unknown and measured work without replacing the track', async ({ page }) => {
  await page.goto('/?component=W.progress-bar')
  const demo = page.getByRole('region', { name: '进度示例' })
  const usage = demo.getByRole('progressbar', { name: '磁盘用量' })
  await expect(usage).toHaveAttribute('aria-valuetext', '3.2 GB / 5 GB')
  await demo.getByRole('button', { name: '分配 0.5 GB' }).click()
  await expect(usage).toHaveAttribute('aria-valuetext', '3.7 GB / 5 GB')
  await expect(demo.getByRole('progressbar', { name: '部分同步失败' })).toHaveAttribute('data-tone', 'danger')
  await expect(demo.getByRole('progressbar', { name: '基准容量' })).toHaveAttribute('data-tone', 'neutral')

  const progress = demo.getByRole('progressbar', { name: '资料上传进度' })
  const track = await progress.locator('.sy-measure__track').elementHandle()
  const bounds = await progress.boundingBox()
  const start = demo.getByRole('button', { name: '模拟上传' })
  await start.click()
  await expect(start).toHaveAttribute('aria-busy', 'true')
  await expect(progress).not.toHaveAttribute('aria-valuenow')
  await expect(progress.locator('.sy-measure__sweep > span')).toHaveCSS('animation-play-state', 'running')
  await expect(progress).toHaveAttribute('aria-valuenow', '100')
  await expect(progress).toHaveAttribute('data-tone', 'success')
  await expect(start).not.toHaveAttribute('aria-busy')
  expect(await progress.locator('.sy-measure__track').evaluate((node, previous) => node === previous, track)).toBe(true)
  expect(await progress.boundingBox()).toEqual(bounds)
  await expect(demo.locator('.measurement-review__status .sy-visually-hidden')).toHaveText('上传完成')
})

test('controlled and multi-open disclosures support heading structure and independent keyboard controls', async ({ page }) => {
  await page.goto('/?component=W.disclosure')
  const demo = page.getByRole('region', { name: '折叠区示例' })
  const settings = demo.getByRole('group', { name: '交付设置' })
  const region = settings.getByRole('heading', { name: '数据区域', level: 3 }).getByRole('button')
  const retention = settings.getByRole('button', { name: '保留期限' })
  await expect(region).toHaveAttribute('aria-expanded', 'true')
  await demo.getByRole('button', { name: '下一部分' }).click()
  await expect(region).toHaveAttribute('aria-expanded', 'false')
  await expect(retention).toHaveAttribute('aria-expanded', 'true')
  await expect(settings.getByText('删除的资料在保留期内仍可恢复。')).toBeVisible()
  await region.press('ArrowDown')
  await expect(retention).toBeFocused()

  const compare = demo.getByRole('group', { name: '并排比较' })
  const drafts = compare.getByRole('button', { name: '草稿可见范围' })
  const published = compare.getByRole('button', { name: '已发布资料' })
  await expect(drafts).toHaveAttribute('aria-expanded', 'true')
  await expect(published).toHaveAttribute('aria-expanded', 'true')
  await drafts.press('Enter')
  await expect(drafts).toHaveAttribute('aria-expanded', 'false')
  await expect(published).toHaveAttribute('aria-expanded', 'true')

  await demo.getByRole('button', { name: '展开发布清单' }).press('Enter')
  const panel = demo.getByRole('region', { name: '发布清单' })
  const hide = demo.getByRole('button', { name: '收起发布清单' })
  await expect(panel).toBeVisible()
  await expect(hide).toBeFocused()
  await expect(panel).toHaveCSS('transition-timing-function', /cubic-bezier/)
  await hide.press('Enter')
  await expect(panel).toBeHidden()
})

test('divided disclosure groups retain their own defaults and visibly distinct densities', async ({ page }) => {
  await page.goto('/?component=W.disclosure-group')
  const demo = page.getByRole('region', { name: '分组密度示例' })
  const compact = demo.getByRole('group', { name: '紧凑资料分组' })
  const roomy = demo.getByRole('group', { name: '宽松资料分组' })
  const first = compact.getByRole('button', { name: '数据区域' })
  const second = roomy.getByRole('button', { name: '数据区域' })
  expect((await second.boundingBox())!.height).toBeGreaterThan((await first.boundingBox())!.height)
  await expect(roomy.locator('.sy-disclosure').nth(1)).toHaveCSS('border-top-width', '1px')
  await expect(first).toHaveAttribute('aria-expanded', 'true')
  await expect(second).toHaveAttribute('aria-expanded', 'true')
  await roomy.getByRole('button', { name: '审计记录' }).click()
  await expect(second).toHaveAttribute('aria-expanded', 'false')
  await expect(first).toHaveAttribute('aria-expanded', 'true')
})

test('toast actions undo repeated saves, link to the report, and keep errors until dismissed', async ({ page }) => {
  await page.goto('/?component=W.toast')
  const demo = page.getByRole('region', { name: '通知操作示例' })
  const name = demo.getByRole('textbox', { name: '通知显示名称' })
  const save = demo.getByRole('button', { name: '保存交付偏好' })
  const toast = (title: string) => page.locator('.sy-toast[data-state="open"]').filter({ has: page.getByText(title, { exact: true }) })
  await name.fill('周岚')
  await save.click()
  const success = toast('交付偏好已保存')
  await expect(success).toHaveCount(1)
  await save.click()
  await expect(success).toHaveCount(1)
  await success.getByRole('button', { name: '撤销保存' }).click()
  await expect(name).toHaveValue('林舟')
  await expect(success).toHaveCount(0)
  await demo.getByRole('switch', { name: '模拟保存失败' }).click()
  await save.click()
  const error = toast('保存交付偏好失败')
  await expect(error).toHaveAttribute('data-tone', 'danger')
  await error.getByRole('button', { name: '关闭提示' }).click()
  await expect(error).toHaveCount(0)

  await demo.getByRole('button', { name: '生成交付报告' }).click()
  await toast('交付报告已生成。').getByRole('link', { name: '阅读报告' }).press('Enter')
  await expect(demo.locator('.toast-review__report')).toHaveAttribute('data-open', 'true')
  await expect(demo.getByText('已检查素材清单与品牌授权。')).toBeVisible()
  await toast('交付报告已生成。').getByRole('button', { name: '关闭提示' }).click()

  await demo.getByRole('button', { name: '发送普通与错误通知' }).click()
  const info = toast('交付摘要已就绪。')
  const persistent = toast('资源校验失败，请检查授权。')
  await expect(info).toBeVisible()
  await expect(persistent).toBeVisible()
  await page.mouse.move(4, 4)
  await expect(info).toHaveCount(0, { timeout: 7500 })
  await expect(persistent).toBeVisible()
  await persistent.getByRole('button', { name: '关闭提示' }).click()
  await expect(persistent).toHaveCount(0)
})
