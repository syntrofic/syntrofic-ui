import { expect, test } from '@playwright/test'

test('copies message text without changing button size or focus and exposes toggle feedback', async ({ page }) => {
  await page.addInitScript(() => {
    const state = { value: '', fail: false }
    Object.defineProperty(navigator, 'clipboard', { value: {
      async writeText(value: string) {
        if (state.fail) throw new Error('Denied')
        state.value = value
      },
    } })
    Object.defineProperty(document, 'execCommand', { value: () => false })
    Object.assign(window, { chatClipboard: state })
  })
  await page.goto('/?component=WP.chat-message-actions')
  const sample = page.getByRole('region', { name: '组件示例' })
  const actions = sample.getByRole('group', { name: '回复操作' })
  const copy = actions.getByRole('button', { name: '复制' })
  const before = await copy.boundingBox()
  await copy.press('Enter')
  await expect(actions.getByRole('status')).toHaveText('已复制')
  await expect(copy).toBeFocused()
  expect(await copy.boundingBox()).toEqual(before)
  expect(await page.evaluate(() => (window as Window & { chatClipboard?: { value: string } }).chatClipboard?.value))
    .toBe('已核对交付清单。其中 12 份文件已通过核对，另有两份需补充签名。')

  await page.evaluate(() => { (window as Window & { chatClipboard: { fail: boolean } }).chatClipboard.fail = true })
  await copy.press('Enter')
  await expect(actions.getByRole('status')).toHaveText('复制失败')
  await expect(copy).toBeFocused()
  expect(await copy.boundingBox()).toEqual(before)
  const like = actions.getByRole('button', { name: '有帮助' })
  const dislike = actions.getByRole('button', { name: '没帮助' })
  await like.press('Space')
  await expect(like).toHaveAttribute('aria-pressed', 'true')
  await dislike.press('Space')
  await expect(like).toHaveAttribute('aria-pressed', 'false')
  await expect(dislike).toHaveAttribute('aria-pressed', 'true')
  await dislike.press('Space')
  await expect(dislike).toHaveAttribute('aria-pressed', 'false')
  await actions.getByRole('button', { name: '重试' }).press('Enter')
  await expect(sample.locator('.review-chat-action-note')).toContainText('已请求重新核对。')
})

test('provides keyboard citation previews, native anchors and a grouped document action', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 820 })
  await page.goto('/?component=WP.chat-source')
  const sample = page.getByRole('region', { name: '组件示例' })
  const inline = sample.locator('.review-chat-citations__inline')
  const link = inline.getByRole('link', { name: '交付手册' })
  await expect(link).toHaveAttribute('href', 'https://kb.syntrofic.com/?id=20261120144442-j5v9ov3')
  await expect(link).toHaveAttribute('rel', 'noopener noreferrer')
  await link.focus()
  await expect(page.getByRole('tooltip')).toContainText('包括文件命名')
  await expect(link).toHaveAccessibleDescription(/包括文件命名/)
  await link.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(link).toBeFocused()
  const disclosure = sample.getByRole('button', { name: '查看引用 3 项' })
  await expect(disclosure).toHaveAttribute('aria-expanded', 'false')
  await disclosure.press('Enter')
  const citations = sample.getByRole('list', { name: '复核引用' })
  await expect(citations.getByRole('listitem')).toHaveCount(3)
  await citations.getByRole('button', { name: '复核清单.pdf' }).press('Enter')
  await expect(sample.locator('.review-chat-action-note')).toContainText('已选中复核清单。')
  await expect(citations.getByRole('link', { name: '每日交付量' })).toHaveAttribute('href', '/?component=WP.area-chart')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('preserves disclosure geometry while input streams and restores keyboard focus after approval', async ({ page }) => {
  await page.goto('/?component=WP.chat-tool')
  const sample = page.getByRole('region', { name: '组件示例' })
  const live = sample.getByRole('button', { name: /查找待复核材料/ })
  await expect(live).toHaveAttribute('aria-expanded', 'true')
  const streamingBox = await live.boundingBox()
  const tool = sample.locator('.sy-chat-tool').first()
  await expect(tool.locator('pre')).toHaveText('{"目录": "交付/')
  await sample.getByRole('button', { name: '切换参数状态' }).click()
  await expect(live).toHaveAccessibleName(/等待结果/)
  await expect(tool.locator('pre')).toHaveText('{"目录": "交付/待复核"}')
  expect(await live.boundingBox()).toEqual(streamingBox)
  const approval = sample.getByRole('button', { name: /登记交付归档/ })
  await approval.press('Enter')
  const approve = sample.getByRole('button', { name: '确认登记' })
  await approve.press('Enter')
  await expect(approval).toBeFocused()
  await expect(approval).toHaveAccessibleName(/已完成/)
  await expect(sample.getByText('归档结果', { exact: true })).toBeVisible()
  await sample.getByRole('button', { name: '复核工具' }).press('Enter')
  await sample.getByRole('button', { name: /读取文件签名/ }).press('Enter')
  await expect(sample.getByText('签名文件尚未上传。')).toBeVisible()
})
