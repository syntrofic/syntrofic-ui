test('preserves readable shimmer text and geometry with reduced motion', async ({ page }) => {
  await page.goto('/?component=WP.text-shimmer')
  const sample = page.getByRole('region', { name: '组件示例' })
  const text = sample.locator('.sy-text-shimmer').first()
  const highlight = text.locator('.sy-text-shimmer__highlight')
  await expect(highlight).toHaveCSS('animation-name', 'sy-shimmer')
  const bounds = await text.boundingBox()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(highlight).not.toBeVisible()
  expect(await text.boundingBox()).toEqual(bounds)
  await sample.getByRole('button', { name: '下一份文件' }).click()
  await expect(text.locator('.sy-text-shimmer__text > .sy-visually-hidden')).toHaveText('正在核对第 19 份文件')
  await sample.getByRole('switch', { name: '显示文字流光' }).uncheck()
  await expect(highlight).toHaveCount(0)
})
