import { expect, test } from '@playwright/test'

test('keeps the editor mounted when compact expands and handles IME, modifier submission and stop', async ({ page }) => {
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '组件示例' })
  const composer = sample.getByRole('form', { name: '写一条请求' })
  const field = composer.getByRole('textbox', { name: '写一条请求' })
  await expect(composer).toHaveAttribute('data-layout', 'compact')
  await field.fill('核对这批文件')
  const original = await field.elementHandle()
  await field.press('Shift+Enter')
  await page.keyboard.insertText('并检查附件名称。')
  await expect(composer).toHaveAttribute('data-layout', 'stacked')
  expect(await field.evaluate((node, before) => node === before, original)).toBe(true)
  await expect(field).toBeFocused()
  await sample.getByRole('switch', { name: '组合键发送' }).check()
  await field.dispatchEvent('compositionstart')
  await field.dispatchEvent('keydown', { key: 'Enter', isComposing: true, ctrlKey: true })
  await expect(composer).toHaveAttribute('data-status', 'ready')
  await field.dispatchEvent('compositionend')
  const send = composer.getByRole('button', { name: '发送' })
  const before = await send.boundingBox()
  await field.press('Control+Enter')
  const stop = composer.getByRole('button', { name: '停止' })
  await expect(stop).toBeVisible()
  const after = await stop.boundingBox()
  expect(after?.width).toBeCloseTo(before!.width, 2)
  expect(after?.height).toBeCloseTo(before!.height, 2)
  await expect(field).toHaveJSProperty('readOnly', true)
  await expect(sample.locator('[data-review-prompt-sent]')).toContainText('并检查附件名称。')
  await stop.press('Enter')
  await expect(sample.getByLabel('请求状态')).toContainText('已停止生成')
  await expect(send).toBeFocused()
  await sample.getByRole('button', { name: '模拟连接失败' }).click()
  await expect(composer.getByRole('alert')).toContainText('连接中断')
  await expect(composer.getByRole('button', { name: '重发' })).toBeVisible()
  await expect(field).toHaveValue('核对这批文件\n并检查附件名称。')
})

test('uses one file policy for native selection, drop and paste and keeps attachment removal keyboard accessible', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 820 })
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '组件示例' })
  const composer = sample.getByRole('form', { name: '写一条请求' })
  const picker = composer.locator('input[type=file]')
  await picker.setInputFiles([
    { name: '目录.txt', mimeType: 'text/plain', buffer: Buffer.from('目录') },
    { name: '不支持.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('test') },
  ])
  const list = composer.getByRole('list', { name: '已选附件' })
  await expect(list.getByRole('article', { name: '目录.txt' })).toBeVisible()
  await expect(composer.getByRole('alert')).toContainText('不支持.exe · 不支持此格式')
  const shell = composer.locator('.sy-prompt-input__shell')
  const drag = await page.evaluateHandle(() => {
    const transfer = new DataTransfer()
    transfer.items.add(new File(['test'], '待复核.pdf', { type: 'application/pdf' }))
    return transfer
  })
  await shell.dispatchEvent('dragenter', { dataTransfer: drag })
  await expect(shell).toHaveAttribute('data-dragging', 'true')
  await shell.dispatchEvent('drop', { dataTransfer: drag })
  await expect(shell).not.toHaveAttribute('data-dragging')
  await expect(list.getByRole('article', { name: '待复核.pdf' })).toBeVisible()
  const field = composer.getByRole('textbox', { name: '写一条请求' })
  await field.evaluate(node => {
    const data = new DataTransfer()
    data.items.add(new File(['text'], '补充.txt', { type: 'text/plain' }))
    const event = new ClipboardEvent('paste', { bubbles: true, cancelable: true })
    // Firefox strips files passed through the constructor of a synthetic clipboard event.
    Object.defineProperty(event, 'clipboardData', { value: data })
    node.dispatchEvent(event)
  })
  await expect(list.getByRole('listitem')).toHaveCount(3)
  await picker.setInputFiles({ name: '超出数量.txt', mimeType: 'text/plain', buffer: Buffer.from('test') })
  await expect(composer.getByRole('alert')).toContainText('超过附件数量限制')
  await composer.getByRole('button', { name: '移除 补充.txt' }).press('Enter')
  await expect(list.getByRole('listitem')).toHaveCount(2)
  await expect(field).toBeFocused()
})

test('anchors token suggestions to the caret, dismisses until it moves and inserts or deletes complete tokens', async ({ page }) => {
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '组件示例' })
  await sample.getByRole('switch', { name: '行内提及' }).check()
  const editor = sample.getByRole('combobox', { name: '写一条请求' })
  const menu = page.getByRole('listbox', { name: '可插入的提及和命令' })
  await editor.focus()
  await page.keyboard.insertText('@')
  await expect(menu.getByRole('option')).toHaveCount(2)
  await editor.press('Escape')
  await expect(menu).not.toBeVisible()
  await page.keyboard.insertText('归')
  await expect(menu).not.toBeVisible()
  await editor.press('ArrowLeft')
  await editor.press('ArrowLeft')
  await editor.press('ArrowRight')
  await editor.press('ArrowRight')
  await expect(menu.getByRole('option', { name: /归档组/ })).toBeVisible()
  await editor.press('Enter')
  const chips = editor.locator('.sy-prompt-input__token')
  await expect(chips).toHaveCount(1)
  await expect(chips.first()).toHaveAttribute('contenteditable', 'false')
  await expect(editor).toBeFocused()
  await editor.press('Backspace')
  await editor.press('Backspace')
  await expect(chips).toHaveCount(0)
  await page.keyboard.insertText('/核')
  await menu.getByRole('option', { name: /核对交付/ }).click()
  await expect(chips).toHaveText('核对交付')
  await expect(editor).toBeFocused()
  await editor.press('Enter')
  await expect(sample.locator('[data-review-prompt-sent]')).toContainText('/核对交付')
  await expect(editor).toHaveAttribute('aria-readonly', 'true')
})

test('queues two follow-ups while streaming, reorders and restores one without losing the current draft', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto('/?component=WP.prompt-input')
  const sample = page.getByRole('region', { name: '组件示例' })
  await sample.getByRole('switch', { name: '允许排队' }).check()
  const composer = sample.getByRole('form', { name: '写一条请求' })
  const field = composer.getByRole('textbox', { name: '写一条请求' })
  await field.fill('查找交付记录')
  await composer.getByRole('button', { name: '发送' }).click()
  await expect(composer).toHaveAttribute('data-status', 'streaming')
  await field.fill('复核交付批次')
  await field.press('Enter')
  await field.fill('列出需补签名')
  await composer.getByRole('button', { name: '加入队列' }).click()
  const list = composer.getByRole('group', { name: '待发送' }).getByRole('list')
  const entries = list.getByRole('listitem')
  await expect(entries).toHaveCount(2)
  await entries.first().locator('.sy-prompt-queue__handle').dragTo(entries.last())
  await expect(entries.first()).toContainText('列出需补签名')
  await entries.first().locator('.sy-prompt-queue__handle').dragTo(entries.last())
  await expect(entries.first()).toContainText('复核交付批次')
  await entries.last().getByRole('button', { name: '上移' }).press('Enter')
  await expect(entries.first()).toContainText('列出需补签名')
  await field.fill('保留这条草稿')
  await entries.first().getByRole('button', { name: '编辑' }).press('Enter')
  await expect(field).toHaveValue('列出需补签名')
  await expect(field).toBeFocused()
  await expect(entries.first()).toContainText('保留这条草稿')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})

