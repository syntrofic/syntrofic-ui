import { expect, test } from '@playwright/test'

test('reveals avatar images without moving the fallback, and tries the backup before initials or the person icon', async ({ page }) => {
  let release!: () => void
  const loading = new Promise<void>(resolve => { release = resolve })
  await page.route(/profile-lin[^/]*\.jpg(?:\?|$)/, async route => {
    if (route.request().resourceType() === 'image') await loading
    await route.continue()
  })
  await page.goto('/?component=W.avatar', { waitUntil: 'domcontentloaded' })
  const primary = page.getByRole('img', { name: '林舟', exact: true })
  try {
    await expect(primary).toHaveAttribute('aria-busy', 'true')
    await expect(primary.locator('.sy-avatar__fallback')).toHaveText('林舟')
    expect(await primary.evaluate(node => getComputedStyle(node, '::before').animationName)).toBe('sy-avatar-loading')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    expect(await primary.evaluate(node => getComputedStyle(node, '::before').animationName)).toBe('none')
  } finally {
    release()
  }
  const width = (await primary.boundingBox())!.width
  await expect(primary).toHaveAttribute('data-loaded', 'true')
  await expect(primary).toHaveAttribute('data-image-source', 'primary')
  await expect(primary.locator('img')).toHaveCSS('transition-property', 'none')
  await page.getByRole('button', { name: '切换头像来源' }).click()
  await expect(primary).toHaveAttribute('data-image-source', 'fallback')
  await expect(primary).toHaveAttribute('data-loaded', 'true')
  expect((await primary.boundingBox())!.width).toBe(width)
  const initials = page.getByRole('img', { name: 'Maya R. Lin' })
  await expect(initials).toHaveText('ML')
  await expect(initials).not.toHaveAttribute('data-image-source')
  await expect(page.getByRole('img', { name: '匿名访客' }).locator('.sy-avatar__person path[d]')).toBeVisible()
})

test('exposes avatar tooltips by pointer and keyboard, and supports a native link or button', async ({ page }) => {
  await page.goto('/?component=W.avatar')
  const named = page.getByRole('img', { name: '林舟', exact: true })
  await named.hover()
  await expect(page.getByRole('tooltip').filter({ hasText: '林舟' })).toBeVisible()
  await page.mouse.move(0, 0)
  const link = page.getByRole('link', { name: '查看林舟资料' })
  await link.focus()
  await expect(page.getByRole('tooltip').filter({ hasText: '前往个人资料' })).toBeVisible()
  await expect(link).toHaveAccessibleDescription('前往个人资料')
  const destination = await link.getAttribute('href')
  await link.press('Enter')
  await expect(page).toHaveURL(url => url.hash === destination)
  const profile = page.getByRole('button', { name: '查看陈远资料' })
  await profile.focus()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await profile.press('Space')
  const dialog = page.getByRole('dialog', { name: '陈远' })
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveAccessibleDescription('工程负责人')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(profile).toBeFocused()
})

test('uses a single tab stop for the facepile and opens the roster for the server overflow', async ({ page }) => {
  await page.goto('/?component=W.avatar-group')
  const scope = page.getByRole('region', { name: '项目成员演示' })
  const group = scope.getByRole('group', { name: '项目成员', exact: true })
  const first = group.getByRole('link', { name: '林舟' })
  const overflow = group.getByRole('button', { name: '查看其余 12 位成员' })
  await scope.getByRole('switch').focus()
  await page.keyboard.press('Tab')
  await expect(first).toBeFocused()
  await expect(group.locator('[tabindex="0"]')).toHaveCount(1)
  await first.press('ArrowRight')
  await expect(group.getByRole('link', { name: '陈远' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(group.getByRole('link', { name: '沈宁' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(overflow).toBeFocused()
  await overflow.press('Enter')
  const dialog = page.getByRole('dialog', { name: '其余项目成员' })
  await expect(dialog.getByRole('listitem')).toHaveCount(12)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(overflow).toBeFocused()
  await page.keyboard.press('Tab')
  expect(await group.evaluate(node => node.contains(node.ownerDocument.activeElement))).toBe(false)
  await scope.getByRole('switch').click()
  await expect(group.getByRole('button', { name: '查看其余 6 位成员' }).locator('.sy-motion-text > .sy-visually-hidden')).toHaveText('+6')
  await expect(scope.getByRole('img', { name: '另有 12 位社区成员' })).toHaveText('12+')
})

test('sizes avatar status markers and animates labelled delivery status with a reduced-motion fallback', async ({ page }) => {
  await page.goto('/?component=W.avatar')
  const presence = page.getByRole('region', { name: '头像在线状态' })
  const small = presence.getByRole('img', { name: '成员 1, 在线' }).locator('.sy-avatar-status')
  const large = presence.getByRole('img', { name: '成员 3, 请勿打扰' }).locator('.sy-avatar-status')
  expect((await large.boundingBox())!.width).toBeGreaterThan((await small.boundingBox())!.width)
  await presence.getByRole('button', { name: '更新在线状态' }).click()
  await expect(presence.getByRole('img', { name: '沈宁, 离线' }).locator('.sy-avatar-status')).toHaveAttribute('data-variant', 'neutral')

  await page.goto('/?component=W.status-dot')
  for (const tone of ['neutral', 'info', 'success', 'warning', 'danger']) {
    await expect(page.locator(`[aria-label="五种交付状态"] [data-tone="${tone}"]`)).toBeVisible()
  }
  const published = page.getByRole('img', { name: '已发布' })
  expect(await published.evaluate(node => getComputedStyle(node, '::after').animationName)).toMatch(/pulse/)
  await page.getByRole('button', { name: '切换状态' }).click()
  const pending = page.getByRole('img', { name: '待评审' })
  await expect(pending).toHaveAttribute('data-tone', 'warning')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await pending.evaluate(node => getComputedStyle(node, '::after').animationName)).toBe('none')
})

test('opens the matching photo, adapts remove control contrast, and keeps disabled controls readable by keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 700 })
  await page.goto('/?component=W.thumbnail')
  const photos = page.getByRole('region', { name: '成员照片缩略图' })
  await expect(photos.getByRole('button', { name: '移除林舟照片' })).toHaveAttribute('data-tone', 'dark')
  const remove = photos.getByRole('button', { name: '移除陈远照片' })
  await expect(remove).toHaveAttribute('data-tone', 'light')
  const thumbnail = photos.getByRole('button', { name: '陈远 · 工程' })
  await thumbnail.press('Enter')
  const gallery = page.getByRole('dialog', { name: '成员照片预览' })
  await expect(gallery.getByRole('img', { name: '深蓝背景的陈远肖像' })).toBeVisible()
  await gallery.getByRole('button', { name: '上一张照片' }).click()
  await expect(gallery.getByRole('img', { name: '浅绿背景的林舟肖像' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(gallery).toBeHidden()
  const disabled = photos.getByRole('button', { name: '已归档成员照片' })
  await disabled.focus()
  await expect(disabled).toBeFocused()
  await expect(disabled).toHaveAttribute('aria-disabled', 'true')
  await disabled.press('Enter')
  await expect(gallery).toBeHidden()
  await page.keyboard.press('Tab')
  const disabledRemove = photos.getByRole('button', { name: '移除归档成员照片' })
  await expect(disabledRemove).toBeFocused()
  await disabledRemove.press('Space')
  await expect(thumbnail).toBeVisible()
  await photos.getByRole('switch', { name: '显示上传进度' }).click()
  await expect(photos.getByRole('status').filter({ hasText: '等待照片上传' })).toBeAttached()
  await expect(photos.locator('.sy-thumbnail__loading')).toHaveCount(2)
  await remove.press('Enter')
  await expect(thumbnail).toHaveCount(0)
  await photos.getByRole('button', { name: '恢复成员照片' }).click()
  await expect(thumbnail).toBeVisible()
})

test.describe('touch media controls', () => {
  test.use({ hasTouch: true })

  test('opens a passive avatar tooltip and keeps thumbnail removal available without hover', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 700 })
    await page.goto('/?component=W.avatar')
    const avatar = page.getByRole('img', { name: '林舟', exact: true })
    await avatar.tap()
    const tip = page.getByRole('tooltip').filter({ hasText: '林舟' })
    await expect(tip).toBeVisible()
    await avatar.tap()
    await expect(tip).toBeHidden()

    await page.goto('/?component=W.thumbnail')
    const remove = page.getByRole('button', { name: '移除配送地图' })
    await expect(remove).toHaveCSS('opacity', '1')
    await remove.tap()
    await expect(page.getByRole('button', { name: '恢复缩略图' })).toBeVisible()
  })
})
