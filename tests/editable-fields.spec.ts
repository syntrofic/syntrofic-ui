import { expect, test } from '@playwright/test'

test('search clears without shifting or losing focus and ignores Enter during composition', async ({ page }) => {
  await page.goto('/?component=W.input')
  const scene = page.getByRole('region', { name: '文本输入示例' })
  const search = scene.getByRole('searchbox', { name: '搜索发布记录' })
  const clear = scene.getByRole('button', { name: '清除搜索' })
  await expect(search).toHaveAttribute('enterkeyhint', 'search')
  const footprint = await search.boundingBox()
  await search.fill('角色权限')
  await search.dispatchEvent('keydown', { key: 'Enter', isComposing: true, bubbles: true, cancelable: true })
  await expect(scene.getByText('搜索了 角色权限')).toHaveCount(0)
  await search.press('Enter')
  await expect(scene.getByText('搜索了 角色权限').first()).toBeVisible()
  await clear.click()
  await expect(search).toHaveValue('')
  await expect(search).toBeFocused()
  await expect(clear).toHaveCount(0)
  expect((await search.boundingBox())?.width).toBe(footprint?.width)
  await expect(scene.getByRole('textbox', { name: '小号输入' })).toHaveCSS('height', '34px')
  await expect(scene.getByRole('textbox', { name: '大号输入' })).toHaveCSS('height', '50px')
})

test('async text changes take the latest input and keep its control usable and focused', async ({ page }) => {
  await page.goto('/?component=W.input')
  const scene = page.getByRole('region', { name: '文本输入示例' })
  const name = scene.getByRole('textbox', { name: '项目名称', exact: true })
  await name.fill('第一份资料')
  await expect(name).toHaveAttribute('aria-busy', 'true')
  await name.fill('交付资料')
  await expect(name).toBeFocused()
  await expect(name).toHaveValue('交付资料')
  await expect(scene.getByText('已同步名称 交付资料').first()).toBeVisible()
  await expect(scene.getByText('已同步名称 第一份资料')).toHaveCount(0)
  await expect(name).not.toHaveAttribute('aria-busy', 'true')
  const owner = scene.getByRole('textbox', { name: '发布负责人' })
  await owner.focus()
  await expect(owner).toHaveAttribute('aria-disabled', 'true')
  await expect(owner).toHaveJSProperty('readOnly', true)
  await expect(page.getByRole('tooltip')).toHaveText('只有工作区管理员可以分配负责人。')
})

test('textarea counts graphemes, permits a soft overage and applies a distinct native limit', async ({ page }) => {
  await page.goto('/?component=W.text-area')
  const scene = page.getByRole('region', { name: '多行输入示例' })
  const area = scene.getByRole('textbox', { name: '项目备注' })
  await area.fill('👩‍👩‍👧‍👦🇨🇳e\u0301')
  const counter = area.locator('..').locator('.sy-textarea__counter')
  await expect(counter).not.toHaveAttribute('data-over-limit')
  await expect(area).toHaveAccessibleDescription(/还可输入 9 个字符/)
  const before = (await area.boundingBox())!.height
  await area.fill('第一行\n第二行\n第三行\n第四行')
  await expect(counter).toHaveAttribute('data-over-limit', 'true')
  await expect(counter.locator('svg')).toBeVisible()
  await expect(area).toBeFocused()
  await expect(area).not.toHaveAttribute('maxlength')
  await expect.poll(async () => (await area.boundingBox())!.height).toBeGreaterThan(before)
  const native = scene.getByRole('textbox', { name: '标题摘要' })
  await native.pressSequentially('1234567890')
  await expect(native).toHaveValue('12345678')
  await expect(native).toHaveAccessibleDescription(/还可输入 2 个字符/)
  await expect(scene.getByRole('textbox', { name: '待检查的备注' })).toHaveAttribute('aria-invalid', 'true')
})

test('number drafts preserve rejected text and commit valid integers, range boundaries and clears', async ({ page }) => {
  await page.goto('/?component=W.number-field')
  const scene = page.getByRole('region', { name: '数字用法示例' })
  const guests = scene.getByRole('spinbutton', { name: '评审人数' })
  await guests.fill('12.5')
  await expect(guests).not.toHaveAttribute('aria-invalid', 'true')
  await guests.press('Enter')
  await expect(guests).toHaveValue('12.5')
  await expect(guests).toHaveAttribute('aria-valuenow', '12')
  await expect(guests).toHaveAttribute('aria-invalid', 'true')
  await expect(guests).toHaveAccessibleDescription('请输入有效的整数人数。')
  await expect(scene.getByText('已保存人数 12')).toHaveCount(0)
  await guests.fill('26')
  await expect(guests).not.toHaveAttribute('aria-invalid', 'true')
  await guests.press('Enter')
  await expect(scene.getByText('已保存人数 26').first()).toBeVisible()
  await expect(guests).toHaveAttribute('aria-valuenow', '26')

  const percent = scene.getByRole('spinbutton', { name: '交付完成率' })
  await percent.fill('150')
  await percent.press('Tab')
  await expect(percent).toHaveValue('100')
  await expect(percent).toHaveAttribute('aria-valuetext', '100 %')
  await scene.getByRole('button', { name: '清除完成率' }).click()
  await expect(percent).toHaveValue('')
  await expect(percent).toBeFocused()
  const speed = scene.getByRole('spinbutton', { name: '预览倍速' })
  await expect(speed).toHaveValue('1.25 倍速')
  await speed.focus()
  await expect(speed).toHaveValue('1.25')
  await speed.fill('1.5')
  await speed.press('Tab')
  await expect(speed).toHaveValue('1.50 倍速')
})

test('date formats collapse only visually and clearing focuses the editable segments', async ({ page }) => {
  await page.goto('/?component=W.date-picker')
  const scene = page.getByRole('region', { name: '日期格式与清除' })
  const system = scene.getByRole('group', { name: '系统日期', exact: true })
  await expect(system.locator('.sy-date-control__formatted')).toContainText('2026-11-18')
  await expect(system.locator('.sy-date-control__formatted')).toHaveCSS('opacity', '1')
  await system.getByRole('spinbutton').first().focus()
  await expect(system.locator('.sy-date-control__formatted')).toHaveCSS('opacity', '0')
  const custom = scene.getByRole('group', { name: '自定义日期', exact: true })
  await expect(custom.locator('.sy-date-control__formatted')).toContainText('第 18 日 · 11 月')

  const date = scene.getByRole('group', { name: '计划完成日', exact: true })
  await expect(date).toHaveAccessibleDescription('只能选择 11 月 18 日至 24 日之间的日期。')
  await scene.getByRole('button', { name: '打开完成日日历' }).click()
  const calendar = page.getByRole('dialog', { name: '打开完成日日历' })
  await expect(calendar.locator('[data-value="2026-11-17"]')).toHaveAttribute('aria-disabled', 'true')
  await expect(calendar.locator('[data-value="2026-11-25"]')).toHaveAttribute('aria-disabled', 'true')
  await calendar.locator('.sy-calendar__day[data-value="2026-11-24"]').click()
  await expect(date.getByRole('spinbutton', { name: '日', exact: true })).toHaveAttribute('aria-valuenow', '24')
  await scene.getByRole('button', { name: '清除完成日' }).click()
  await expect(date.locator('.sy-date-control__formatted')).toHaveCount(0)
  await expect(date.getByRole('spinbutton').first()).toBeFocused()
  await expect(scene.getByRole('group', { name: '补充交付日' })).toHaveAttribute('aria-invalid', 'true')
})

test('the single-file variant enforces its own type and size limit and replaces the selection', async ({ page }) => {
  await page.goto('/?component=W.file-input')
  const field = page.locator('.sy-file-input').first()
  const picker = field.locator('input[type="file"]')
  const validation = field.locator('.sy-drop-zone__validation[data-show]')
  await expect(field.getByRole('button', { name: '选择交付清单' })).toHaveAccessibleDescription('选择一份不超过 1 MB 的 PDF 文件。')
  await picker.setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('note') })
  await expect(validation).toContainText('notes.txt · 类型不支持')
  await picker.setInputFiles({ name: 'draft.pdf', mimeType: 'application/pdf', buffer: Buffer.from('draft') })
  await expect(field.getByText('draft.pdf', { exact: true })).toBeVisible()
  await picker.setInputFiles({ name: 'oversize.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(1024 * 1024 + 1) })
  await expect(validation).toContainText('oversize.pdf · 超过文件大小限制')
  await expect(field.getByText('draft.pdf', { exact: true })).toBeVisible()
  await picker.setInputFiles({ name: 'final.pdf', mimeType: 'application/pdf', buffer: Buffer.from('final') })
  await expect(field.getByText('final.pdf', { exact: true })).toBeVisible()
  await expect(field.getByText('draft.pdf', { exact: true })).toHaveCount(0)
})
