import { mkdir, readFile, writeFile } from 'node:fs/promises'

const target = new URL('../packages/native/src/chart-model/', import.meta.url)
const origin = new URL('../src/charts/', import.meta.url)
const files = ['cartesian.ts', 'polar.ts', 'types.ts', 'values.ts', 'data-colors.ts']
const check = process.argv.includes('--check')
if (!check) await mkdir(target, { recursive: true })
for (const file of files) {
  const source = await readFile(new URL(file === 'data-colors.ts' ? '../internal/data-colors.ts' : file, origin), 'utf8')
  const output = '// Generated by scripts/sync-native-charts.mjs from the shared chart model.\n\n' +
    source.replace("from '../internal/data-colors'", "from './data-colors'")
  const destination = new URL(file, target)
  if (!check) await writeFile(destination, output)
  else if (await readFile(destination, 'utf8') !== output) throw new Error(`Native chart model is stale. Run node scripts/sync-native-charts.mjs (${file})`)
}
