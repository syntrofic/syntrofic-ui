import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'

const webSource = new URL('../src/styles/tokens.css', import.meta.url)
const nativeSource = new URL('../packages/native/src/theme-values.ts', import.meta.url)
const stylesheet = await readFile(webSource, 'utf8')
const light = {}
const dark = {}
const geometry = {}
const motion = {}

function key(name) {
  return name.replace(/-([a-z0-9])/g, (_, part) => part.toUpperCase())
}

for (const [, name, first, second] of stylesheet.matchAll(/--sy-([a-z-]+): light-dark\((#[a-f\d]{6}), (#[a-f\d]{6})\);/gi)) {
  light[key(name)] = first
  dark[key(name)] = second
}
for (const [, name, size] of stylesheet.matchAll(/--sy-((?:radius|space)-[a-z0-9]+): (\d+)px;/g)) {
  geometry[key(name)] = Number(size)
}
for (const [, name, value] of stylesheet.split('@media')[0].matchAll(/--sy-(duration|motion-[a-z-]+):\s*([^;]+);/g)) {
  // Web scopes can override a duration. The fallback is the shared default for Native.
  const fallback = /^var\(--sy-[a-z-]+,\s*(\d+)ms\)$/.exec(value.trim())
  const literal = /^(\d+)ms$/.exec(value.trim())
  const duration = (fallback ?? literal)?.[1]
  if (duration !== undefined) motion[key(name)] = Number(duration)
}
for (const [, name, values] of stylesheet.matchAll(/--sy-ease-([a-z]+): cubic-bezier\(([^)]+)\);/g)) {
  motion[name] = values.split(',').map(Number)
}
assert(light.canvas && light.focus && light.danger && geometry.radiusMd && motion.motionEnter && motion.settle)
const values = { light, dark, geometry, motion }
const lines = Object.entries(values).map(([name, value]) => 'export const ' + name + ' = ' + JSON.stringify(value, null, 2) + ' as const')
const output = '// Generated by scripts/sync-native-theme.mjs from the shared Web token definitions.\n\n' + lines.join('\n\n') + '\n'
if (process.argv.includes('--check')) assert.equal(await readFile(nativeSource, 'utf8'), output, 'Native theme tokens have drifted')
else await writeFile(nativeSource, output)
