"""Build the Native font from the Syntrofic SVG artwork using FontTools."""

import argparse
from io import BytesIO
import json
from pathlib import Path
import re
import subprocess

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path


ROOT = Path(__file__).resolve().parents[1]
NATIVE = ROOT / 'packages' / 'native'
FONT_NAME = 'SyntroficIcons'
EM = 1200
ASCENT = 900


def load_artwork():
    return json.loads(subprocess.check_output([
        'node', '--experimental-strip-types', '--input-type=module', '--eval',
        "import {syntroficIcons, iconAliases} from './src/icons/artwork.ts'; "
        'process.stdout.write(JSON.stringify([syntroficIcons, iconAliases]))',
    ], cwd=ROOT))


def font_data(icons):
    glyphs = {'.notdef': TTGlyphPen(None).glyph()}
    metrics = {'.notdef': (EM, 0)}
    mapping = {}
    # SVG coordinates start at the top left. TrueType coordinates start at the baseline.
    scale = EM / 24
    for index, (name, artwork) in enumerate(icons.items()):
        glyph_name = name.replace('-', '_')
        pen = TTGlyphPen(None)
        transform = TransformPen(Cu2QuPen(pen, max_err=.45), (scale, 0, 0, -scale, 0, ASCENT))
        parse_path(artwork['path'], transform)
        glyph = pen.glyph()
        glyph.recalcBounds(None)
        glyphs[glyph_name] = glyph
        metrics[glyph_name] = (EM, glyph.xMin)
        mapping[0xE000 + index] = glyph_name

    builder = FontBuilder(EM, isTTF=True)
    builder.setupGlyphOrder(list(glyphs))
    builder.setupCharacterMap(mapping)
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics(metrics)
    builder.setupHorizontalHeader(ascent=ASCENT, descent=ASCENT - EM, lineGap=0)
    builder.setupNameTable({
        'familyName': FONT_NAME, 'styleName': 'Regular', 'uniqueFontIdentifier': FONT_NAME + '-Regular',
        'fullName': FONT_NAME, 'psName': FONT_NAME, 'version': 'Version 1.0',
        'licenseDescription': 'MIT License', 'licenseInfoURL': 'https://github.com/syntrofic/syntrofic-ui/blob/main/LICENSE',
    })
    builder.setupOS2(sTypoAscender=ASCENT, sTypoDescender=ASCENT - EM, sTypoLineGap=0,
                     usWinAscent=ASCENT, usWinDescent=EM - ASCENT)
    builder.setupPost()
    builder.font.recalcTimestamp = False
    builder.font['head'].created = builder.font['head'].modified = 3761510400
    stream = BytesIO()
    builder.save(stream)
    return stream.getvalue()


def glyph_source(icons, aliases):
    codepoints = {name: 0xE000 + index for index, name in enumerate(icons)}
    names = {**codepoints, **{alias: codepoints[name] for alias, name in aliases.items()}}
    names.update({re.sub(r'-([a-z])', lambda match: match[1].upper(), name): value for name, value in names.items()})
    entries = ''.join(f"  {json.dumps(name)}: '\\u{value:04x}',\n" for name, value in sorted(names.items()))
    return ('// Generated by scripts/build-icon-font.py from src/icons/artwork.ts.\n'
            f"export const nativeIconFont = '{FONT_NAME}'\n"
            f'export const nativeIconGlyphs = {{\n{entries}}} as const\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    icons, aliases = load_artwork()
    for path, data in [(NATIVE / 'fonts' / (FONT_NAME + '.ttf'), font_data(icons)),
                       (NATIVE / 'src' / 'icon-glyphs.ts', glyph_source(icons, aliases))]:
        if options.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f'Regenerate {path.relative_to(ROOT)} with scripts/build-icon-font.py')
        else:
            path.write_bytes(data)
    print(f'{len(icons)} vector icons')


if __name__ == '__main__':
    main()
